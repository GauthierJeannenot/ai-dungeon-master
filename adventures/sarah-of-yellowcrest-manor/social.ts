const npc = (goal: string, likedTopics: string[], tabooTopics: string[]): SocialProfile =>
  ({ influenceable: true, goals: [goal], likedTopics, tabooTopics })
function character(goal: string, ideal: string, bond: string, traits: string[],
  likedTopics: string[], tabooTopics: string[], likedTable: string): SocialProfile {
  return { ...npc(goal, likedTopics, tabooTopics),
    personality: { ideals: [ideal], bonds: [bond], traits }, randomizeMode: 'append',
    randomize: { ideals: 'personal_ideals', bonds: 'personal_bonds', traits: 'personal_traits',
      likedTopics: likedTable, tabooTopics: 'personal_dislikes' } }
}
