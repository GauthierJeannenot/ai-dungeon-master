export interface AmmunitionAttackInput {
  weapon:WeaponSpec; weaponItem?:Item; ammunitionItemId?:string;
  // Both IDs are generated by the engine, never accepted from a public call.
  scopeId:string; attackId:string; held?:boolean;
  sequenceConsumedLoadedHosts?:ReadonlySet<string>;
}
export interface AmmunitionAttackPlan {
  attackId:string; scopeId:string; weaponItemId:string; ammunitionItemId:string;
  ammunitionType:AmmunitionType; loading:boolean;
  silvered?:true;adamantine?:AdamantineWitness;loadedHostItemId?:string;
  basicPoison?:BasicPoisonWitness;
  playerPoison?:PlayerPoisonWitness;
}
const recordedState = () => gs.getState().dmTools?.ammunition
export function ammunitionState() {
  return toolkitState().ammunition ??= initialAmmunitionState()
}
function receiptMatches(receipt:AmmunitionExpenditure,plan:AmmunitionAttackPlan) {
  return receipt.attackId===plan.attackId&&receipt.scopeId===plan.scopeId
    &&receipt.weaponItemId===plan.weaponItemId&&receipt.ammunitionItemId===plan.ammunitionItemId
    &&receipt.ammunitionType===plan.ammunitionType
    &&materialWitness(receipt.adamantine)===materialWitness(plan.adamantine)
    &&Boolean(receipt.silvered)===Boolean(plan.silvered)&&receipt.loadedHostItemId===plan.loadedHostItemId
    &&JSON.stringify(receipt.basicPoison)===JSON.stringify(plan.basicPoison)
    &&JSON.stringify(receipt.playerPoison)===JSON.stringify(plan.playerPoison)
}
/** No creation, mutation, random number or cost. An old item without an actual
 * counted stock cannot acquire a historical quantity from its name or bundle. */
export function preflightWeaponAmmunition(input:AmmunitionAttackInput):AmmunitionAttackPlan|undefined {
  const ammunition=(input.weapon.properties as readonly string[]).includes('ammunition')
  if(!ammunition) {
    if(input.ammunitionItemId!==undefined)toolkitError('AMMUNITION_NOT_APPLICABLE','Choose ammunitionItemId only for an actual ammunition weapon attack.')
    return undefined
  }
  const ammunitionType=input.weapon.ammunitionType
  if(!ammunitionType)toolkitError('AMMUNITION_PROFILE_UNSUPPORTED','The weapon has no implemented source ammunition type.')
  if(!gs.getState().currentRoomId||!gs.getState().currentMapId)
    toolkitError('AMMUNITION_LOCATION_REQUIRED','An ammunition attack requires its actual established map and room before the d20.')
  if(!input.weaponItem)toolkitError('WEAPON_NOT_OWNED','Choose the exact physical ammunition weapon.')
  if(!input.ammunitionItemId)toolkitError('AMMUNITION_REQUIRED','Choose the exact actually owned counted ammunition stack.')
  const plan:AmmunitionAttackPlan={attackId:input.attackId,scopeId:input.scopeId,weaponItemId:input.weaponItem!.id,
    ammunitionItemId:input.ammunitionItemId!,ammunitionType:ammunitionType!,
    loading:(input.weapon.properties as readonly string[]).includes('loading')}
  const receipt=recordedState()?.expenditures[plan.attackId]
  if(input.held) {
    if(receipt){plan.adamantine=receipt.adamantine;plan.silvered=receipt.silvered;plan.loadedHostItemId=receipt.loadedHostItemId
      plan.basicPoison=receipt.basicPoison
      plan.playerPoison=receipt.playerPoison
      if(receipt.loadedHostItemId&&input.ammunitionItemId===receipt.loadedHostItemId)plan.ammunitionItemId=receipt.ammunitionItemId}
    if(!receipt||!receiptMatches(receipt,plan))toolkitError('AMMUNITION_HELD_RECEIPT_INVALID','The held d20 must retain its exact actual ammunition expenditure.')
    return plan
  }
  if(receipt)toolkitError('AMMUNITION_ATTACK_ALREADY_COMMITTED','This actual attack already has an ammunition receipt.')
  const loads=gs.getState().dmTools?.improvised?.loads,loaded=!input.sequenceConsumedLoadedHosts?.has(input.weaponItem!.id)&&loads&&Object.hasOwn(loads,input.weaponItem!.id)?loads[input.weaponItem!.id]:undefined
  if((input.weapon.id==='sling'||input.weapon.improvised?.profileId==='sling')&&loaded&&input.ammunitionItemId===input.weaponItem!.id){
    plan.ammunitionItemId=loaded.ammunitionItemId;plan.loadedHostItemId=loaded.hostItemId
    const originalMaterial=gs.getState().dmTools?.adamantine?.instances[loaded.ammunitionItemId]?.witness
    if((loaded.projectile.adamantine||originalMaterial)&&materialWitness(loaded.projectile.adamantine)!==materialWitness(originalMaterial))toolkitError('ADAMANTINE_PROVENANCE_INVALID','The reserved projectile retains its actual original material before dice or costs.')
    if(loaded.projectile.adamantine)plan.adamantine=loaded.projectile.adamantine
    if(loaded.projectile.silvered)plan.silvered=true
    if(loaded.projectile.basicPoison){
      if(!validBasicPoisonWitness(gs.getState(),loaded.projectile.basicPoison))toolkitError('BASIC_POISON_WITNESS_INVALID','The reserved projectile needs its actual retained source coating; no poison is inferred from its original stack.')
      if(loaded.projectile.basicPoison.expiresAt>(gs.getState().worldTimeSeconds??0))plan.basicPoison=loaded.projectile.basicPoison
    }
    if(loaded.projectile.playerPoison){if(!validPlayerPoisonWitness(gs.getState(),loaded.projectile.playerPoison))toolkitError('PLAYER_POISON_WITNESS_INVALID','The reserved actual projectile needs its retained real DMG dose.');plan.playerPoison=loaded.projectile.playerPoison}
    return plan
  }
  if(loaded)toolkitError('SLING_ALREADY_LOADED','Fire the actual reserved projectile by explicitly selecting the host as ammunitionItemId, or unload it before loading another shot.')
  const item=gs.getPlayer().inventory.find(item=>item.id===plan.ammunitionItemId)
  if(!item||item.type!=='misc'||item.ammunitionType!==ammunitionType)
    toolkitError('AMMUNITION_TYPE_MISMATCH','Choose an actually owned physical stack of the weapon’s exact source ammunition type.')
  if(!Number.isSafeInteger(item.quantity)||item.quantity!<=0)
    toolkitError('AMMUNITION_EXHAUSTED','This actual stack has no established remaining ammunition. No stock is inferred.')
  if(item.adamantine||gs.getState().dmTools?.adamantine?.instances[item.id]){const tag=adamantineItemWitness(gs.getState(),item);if(!tag)toolkitError('ADAMANTINE_PROVENANCE_INVALID','The actual selected projectile needs its original material source before any die or expenditure.');plan.adamantine=tag}
  if(item.silvered)plan.silvered=true
  plan.basicPoison=activeBasicPoison(gs.getState(),basicPoisonKey('ammunition',item.id))
  plan.playerPoison=activePlayerPoison(gs.getState(),basicPoisonKey('ammunition',item.id))
  if(plan.playerPoison&&item.quantity!==1)toolkitError('PLAYER_POISON_SINGLE_PROJECTILE_REQUIRED','This actual single-dose coating belongs to one separated physical projectile, never a refilled multi-unit stack.')
  if(!input.weapon.properties.includes('twoHanded')&&freeHands()<1)
    toolkitError('AMMUNITION_FREE_HAND_REQUIRED','A real free hand is required to load this one-handed ammunition weapon.')
  if(plan.loading&&Object.values(recordedState()?.expenditures??{}).some(other=>other.scopeId===plan.scopeId&&other.weaponItemId===plan.weaponItemId))
    toolkitError('LOADING_LIMIT','This weapon has already fired its one piece of ammunition for this actual action, bonus action or reaction.')
  return plan
}
/** Validate the complete explicit sequence before the first d20. Scope IDs
 * encode real action identity, so Loading cannot be reset by a new tool call. */
export function preflightAmmunitionSequence(plans:(AmmunitionAttackPlan|undefined)[]) {
  const quantities=new Map<string,number>(),loadingScopes=new Set<string>()
  for(const plan of plans) {
    if(!plan)continue
    if(plan.loadedHostItemId){
      const key=`loaded:${plan.loadedHostItemId}`
      if(loadingScopes.has(key))toolkitError('AMMUNITION_SEQUENCE_EXHAUSTED','The same physically reserved projectile cannot fire twice.')
      loadingScopes.add(key);continue
    }
    const required=(quantities.get(plan.ammunitionItemId)??0)+1
    quantities.set(plan.ammunitionItemId,required)
    const item=gs.getPlayer().inventory.find(item=>item.id===plan.ammunitionItemId)
    if(!item||!Number.isSafeInteger(item.quantity)||item.quantity!<required)
      toolkitError('AMMUNITION_SEQUENCE_EXHAUSTED','The exact stack cannot supply every attack in this explicit sequence.')
    const key=JSON.stringify([plan.scopeId,plan.weaponItemId])
    if(plan.loading&&loadingScopes.has(key))toolkitError('LOADING_LIMIT','The explicit sequence fires this Loading weapon twice within the same actual action.')
    if(plan.loading)loadingScopes.add(key)
  }
}
/** Call exactly at the actual d20, before an optional reaction suspends it.
 * A depleted stack stays a real zero-count object; hydration cannot refill it. */
export function commitWeaponAmmunition(plan:AmmunitionAttackPlan,targetCell:{x:number;y:number}):AmmunitionExpenditure {
  const existing=recordedState()?.expenditures[plan.attackId]
  if(existing) {
    if(!receiptMatches(existing,plan))toolkitError('AMMUNITION_ATTACK_CONFLICT','The ammunition receipt belongs to another exact attack context.')
    return existing
  }
  const state=gs.getState(),item=state.player.inventory.find(item=>item.id===plan.ammunitionItemId)
  const loads=state.dmTools?.improvised?.loads,loaded=plan.loadedHostItemId&&loads&&Object.hasOwn(loads,plan.loadedHostItemId)?loads[plan.loadedHostItemId]:undefined
  if(plan.loadedHostItemId?!loaded||loaded.ammunitionItemId!==plan.ammunitionItemId||Boolean(loaded.projectile.silvered)!==Boolean(plan.silvered)||materialWitness(loaded.projectile.adamantine)!==materialWitness(plan.adamantine)
    :!item||item.ammunitionType!==plan.ammunitionType||!Number.isSafeInteger(item.quantity)||item.quantity!<=0||Boolean(item.silvered)!==Boolean(plan.silvered)||materialWitness(item?.adamantine)!==materialWitness(plan.adamantine))
    toolkitError('AMMUNITION_COMMIT_INVALID','The prevalidated exact ammunition stack is no longer available.')
  const receipt:AmmunitionExpenditure={attackId:plan.attackId,scopeId:plan.scopeId,weaponItemId:plan.weaponItemId,
    ammunitionItemId:plan.ammunitionItemId,ammunitionType:plan.ammunitionType,combatGeneration:state.combatGeneration??0,
    ...(state.phase==='combat'?{inCombat:true as const}:{}),
    ...(plan.adamantine?{adamantine:plan.adamantine}:{}),
    ...(plan.silvered?{silvered:true as const}:{}),...(plan.loadedHostItemId?{loadedHostItemId:plan.loadedHostItemId}:{}),
    ...(plan.basicPoison?{basicPoison:plan.basicPoison}:{}),
    ...(plan.playerPoison?{playerPoison:plan.playerPoison}:{}),
    mapId:state.currentMapId!,roomId:state.currentRoomId!,shooterCell:{...state.player.position},targetCell:{...targetCell},worldTimeSeconds:state.worldTimeSeconds??0}
  if(plan.loadedHostItemId)delete state.dmTools!.improvised!.loads[plan.loadedHostItemId]
  else item!.quantity=item!.quantity!-1
  ammunitionState().expenditures[plan.attackId]=receipt
  if(plan.playerPoison)movePlayerPoisonSurface(state,plan.playerPoison,{kind:'expended_projectile',id:plan.attackId,key:JSON.stringify(['expended_projectile',plan.attackId])})
  return receipt
}
