test('a player chooses additional hit dice after each result at the same rest end, without renewing resources or Song twice', async t => {
  const call = await engine(t, { characterId: 'bard', dice: '3,2,4,19' })
  await replace(call, state => { state.player.hp.current = 1; state.player.resources.bardic_inspiration.current = 0 })
  ok(await begin(call)); ok(await advance(call, 'light-hour', 3600))
  ok(await finish(call, { songOfRest: true }))
  const completed = await call('get_game_state'), con = Math.floor((completed.player.stats.con - 10) / 2)
  const first = ok(await call('spend_rest_hit_die', { restId: 'rest', eventId: 'first-die', songOfRest: true }))
  assert.equal(first.roll.rolls[0], 3); assert.equal(first.songRoll.rolls[0], 2)
  assert.equal(first.hpAfter, 1 + 3 + con + 2)
  const firstState = await call('get_game_state')
  ok(await call('replace_game_state', { gameState: firstState }))
  assert.equal(ok(await call('spend_rest_hit_die', { restId: 'rest', eventId: 'first-die', songOfRest: true })).replayed, true)
  assert.deepEqual(await call('get_game_state'), firstState)
  await refused(call, 'spend_rest_hit_die', { restId: 'rest', eventId: 'second-die', songOfRest: true }, 'SONG_OF_REST_UNAVAILABLE')
  const second = ok(await call('spend_rest_hit_die', { restId: 'rest', eventId: 'second-die' }))
  assert.equal(second.roll.rolls[0], 4); assert.equal(second.songRoll, undefined)
  assert.equal(second.hpAfter, first.hpAfter + 4 + con)
  const after = await call('get_game_state')
  assert.equal(after.worldTimeSeconds, completed.worldTimeSeconds)
  assert.equal(after.hero.hitDice.current, completed.hero.hitDice.current - 2)
  assert.deepEqual(after.player.resources, completed.player.resources)
  ok(await call('advance_time', { seconds: 1 }))
  await refused(call, 'spend_rest_hit_die', { restId: 'rest', eventId: 'later-die' }, 'SHORT_REST_DECISION_CLOSED')
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

