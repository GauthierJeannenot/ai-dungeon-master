test('actual movement cannot be labelled light and breaks a short rest even without invented time', async t => {
  const call = await engine(t), initial = await call('get_game_state')
  ok(await begin(call)); const cell = adjacent(initial)[0]
  ok(await call('move_token', { tokenId: 'player', toCell: cell }))
  await refused(call, 'record_rest_activity', { restId: 'rest', eventId: 'walk', activity: 'light', reason }, 'REST_STRENUOUS_ACTIVITY_REQUIRED')
  ok(await observe(call, 'walk', 'strenuous'))
  assert.equal(ok(await call('inspect_rest')).eligibility.interrupted, true)
  await refused(call, 'advance_rest', { restId: 'rest', eventId: 'more', seconds: 3600, activity: 'light', reason }, 'REST_INTERRUPTED')
  const time = (await call('get_game_state')).worldTimeSeconds
  ok(await call('abandon_rest', { restId: 'rest', reason: 'La marche a réellement interrompu cette période.' }))
  ok(await begin(call, 'short', 'new-period'))
  assert.equal((await call('get_game_state')).worldTimeSeconds, time)
})

test('a due poison boundary keeps partial rest and resumes after the exact explicit save without an extra hour', async t => {
  const call = await engine(t, { dice: ['20', ...Array(9).fill('1'), '4', '19'].join(',') }), initial = await call('get_game_state')
  ok(await call('create_affliction_source', { sourceId: 'wine', templateId: 'midnight_tears', name: 'Vin réellement contaminé', cell: initial.player.position, doses: 1 }))
  ok(await call('expose_affliction', { sourceId: 'wine', eventId: 'exposure', targetId: 'player', delivery: 'ingested', midnightAt: 100 }))
  await replace(call, state => { state.player.hp.current -= 10 })
  ok(await begin(call))
  await refused(call, 'advance_rest', { restId: 'rest', eventId: 'too-far', seconds: 3600, activity: 'light', reason }, 'REST_EVENT_BOUNDARY')
  ok(await advance(call, 'until-midnight', 100))
  await refused(call, 'finish_rest', { restId: 'rest', hitDice: 1 }, 'AFFLICTION_EVENT_REQUIRED')
  const poison = ok(await call('resolve_affliction_event', { afflictionId: 'wine:exposure' }))
  assert.equal(poison.damageResolution.damageDealt, 4)
  ok(await observe(call, 'passive-poison'))
  ok(await advance(call, 'remaining', 3500)); ok(await finish(call, { hitDice: 1 }))
  const after = await call('get_game_state')
  assert.equal(after.worldTimeSeconds, 3600)
  assert.equal(after.player.hp.current, initial.player.hp.current - 10 - 4 + 7)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

