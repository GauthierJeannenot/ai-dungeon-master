const test = require('node:test'), assert = require('node:assert/strict')
const { engine, ok, replace, adjacent } = require('./helpers/mcp-toolkit.cjs')
const reason = 'Activité réelle choisie et observée pendant cette période.'
const begin = (call, kind = 'short', restId = 'rest') => call('begin_rest', { restId, kind })
const advance = (call, eventId, seconds, activity = 'light', restId = 'rest') => call('advance_rest', { restId, eventId, seconds, activity, reason })
const observe = (call, eventId, activity = 'light') => call('record_rest_activity', { restId: 'rest', eventId, activity, reason })
const finish = (call, choices = {}, restId = 'rest') => call('finish_rest', { restId, ...choices })
async function refused(call, name, input, code) {
  const before = await call('get_game_state'), result = await call(name, input)
  assert.equal(result.code, code, JSON.stringify(result)); assert.deepEqual(await call('get_game_state'), before)
}

test('a recorded short rest preserves partial time and grants its actual chosen benefits only once', async t => {
  const call = await engine(t, { dice: '4,19' })
  await replace(call, state => { state.player.hp.current = 40; state.player.resources.second_wind.current = 0 })
  const before = await call('get_game_state')
  ok(await begin(call)); ok(await advance(call, 'first-half', 1800))
  await refused(call, 'finish_rest', { restId: 'rest', hitDice: 1 }, 'REST_NOT_COMPLETE')
  let partial = await call('get_game_state')
  assert.equal(partial.player.hp.current, 40); assert.equal(partial.player.resources.second_wind.current, 0)
  ok(await call('replace_game_state', { gameState: partial }))
  ok(await advance(call, 'second-half', 1800))
  const completed = ok(await finish(call, { hitDice: 1 })), after = await call('get_game_state')
  assert.equal(completed.seconds, 0); assert.equal(completed.elapsedSeconds, 3600)
  assert.equal(after.worldTimeSeconds, before.worldTimeSeconds + 3600)
  assert.equal(after.player.hp.current, 47); assert.equal(after.hero.hitDice.current, before.hero.hitDice.current - 1)
  assert.equal(after.player.resources.second_wind.current, 1)
  assert.equal(ok(await finish(call, { hitDice: 1 })).replayed, true)
  assert.deepEqual(await call('get_game_state'), after)
  await refused(call, 'finish_rest', { restId: 'rest', hitDice: 2 }, 'REST_COMPLETION_CONFLICT')
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

test('completed rest activity and observation retries remain immutable after hydration and another period begins', async t => {
  const call = await engine(t, { dice: '19' })
  ok(await begin(call))
  ok(await call('advance_time', { seconds: 1800 }))
  ok(await observe(call, 'observed-wait'))
  ok(await advance(call, 'remaining-half', 1800))
  ok(await finish(call))
  ok(await begin(call, 'short', 'later-period'))
  const before = await call('get_game_state')
  ok(await call('replace_game_state', { gameState: before }))
  assert.equal(ok(await observe(call, 'observed-wait')).replayed, true)
  assert.equal(ok(await advance(call, 'remaining-half', 1800)).replayed, true)
  assert.deepEqual(await call('get_game_state'), before, 'old retries cannot change the current period, time or benefits')
  await refused(call, 'advance_rest', { restId: 'rest', eventId: 'remaining-half', seconds: 1, activity: 'light', reason }, 'REST_ACTIVITY_EVENT_CONFLICT')
  await refused(call, 'record_rest_activity', { restId: 'rest', eventId: 'new-after-completion', activity: 'light', reason }, 'REST_PERIOD_REQUIRED')
  await refused(call, 'advance_rest', { restId: 'rest', eventId: 'new-after-completion', seconds: 1, activity: 'light', reason }, 'REST_PERIOD_REQUIRED')
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

test('sleep and watch satisfy a long rest without paying another eight hours or bypassing the daily benefit limit', async t => {
  const call = await engine(t)
  await replace(call, state => { state.player.hp.current = 40; state.hero.hitDice.current = 2 })
  ok(await begin(call, 'long'))
  ok(await advance(call, 'sleep', 21600, 'sleep')); ok(await advance(call, 'watch', 7200))
  const result = ok(await finish(call)), after = await call('get_game_state')
  assert.equal(result.seconds, 0); assert.equal(after.worldTimeSeconds, 28800)
  assert.equal(after.player.hp.current, after.player.hp.max); assert.equal(after.hero.hitDice.current, 5)
  assert.equal(after.hero.lastLongRestAt, 28800)
  assert.ok(after.player.conditions.includes('prone'), 'waking never stands the character automatically')
  ok(await begin(call, 'long', 'second')); ok(await advance(call, 'sleep-again', 28800, 'sleep', 'second'))
  await refused(call, 'finish_rest', { restId: 'second' }, 'LONG_REST_TOO_SOON')
})

test('real rest sleep drops held objects and ends concentration while its expiry does not rearm or stand', async t => {
  const call = await engine(t, { characterId: 'wizard' })
  ok(await call('take_rest', { kind: 'long' }))
  const rested = await call('get_game_state'), staff = Object.values(rested.droppedItems).find(drop => drop.item.type === 'weapon').item
  ok(await call('pick_up_item', { itemId: staff.id }))
  ok(await call('equip_item', { itemId: staff.id, slot: 'main_hand', operation: 'equip' }))
  ok(await call('prepare_spells', { spellIds: ['greater-invisibility'] }))
  ok(await call('cast_spell', { spellId: 'greater-invisibility', targetId: 'player', slotLevel: 4 }))
  const before = await call('get_game_state'), held = before.dmTools?.loadout?.mainHandId
    ?? before.player.inventory.find(item => item.type === 'weapon').id
  assert.ok(before.hero.concentrationIds.player)
  ok(await begin(call)); ok(await advance(call, 'nap', 1800, 'sleep'))
  const after = await call('get_game_state')
  assert.equal(after.hero.concentrationIds.player, undefined)
  assert.ok(after.droppedItems[held]); assert.ok(!after.player.inventory.some(item => item.id === held))
  assert.ok(after.player.conditions.includes('prone')); assert.ok(!after.player.conditions.includes('unconscious'))
})

