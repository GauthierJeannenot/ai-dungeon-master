const test = require('node:test')
const assert = require('node:assert/strict')
const { installPgMem } = require('./helpers/pg-mem.cjs')
const pg = installPgMem()
const { saveSession, loadSession, deleteSession } = require('../lib/session-store.ts')
const { engine, ok, spawn } = require('./helpers/mcp-toolkit.cjs')
const { prepareRechargeCalendar, createRechargeItem } = require('./helpers/recharge-calendar-fixture.cjs')
test.after(() => pg.restore())

const get = call => call('get_game_state')
const charges = async (call, id) => (await get(call)).dmTools.magicItems[id].charges
const time = (call, seconds) => call('advance_time', { seconds })

test('adoption retains a real future phase, replaces midnight and continues exact capped dice after SQL/new process', async t => {
  const call = await engine(t, { dice: '2' })
  const id = await createRechargeItem(call, 'wand_of_magic_missiles', 'phase-wand', { initialCharges: 1 })
  ok(await time(call, 86399))
  assert.equal(ok(await call('inspect_xge_recharge_calendar')).adopted, false)
  const f = await prepareRechargeCalendar(call, { firstAfterSeconds: 3600 })
  assert.equal(f.result.firstAt, 89999)
  assert.equal(f.result.source.startLine, 2620)
  assert.equal(await charges(call, id), 1)
  ok(await time(call, 1))
  assert.equal(await charges(call, id), 1, 'the replaced engine midnight does not recharge')
  ok(await time(call, 3598))
  assert.equal(await charges(call, id), 1)
  ok(await time(call, 1))
  assert.equal(await charges(call, id), 4)
  assert.equal(ok(await call('inspect_magic_items', { itemId: id })).charges, undefined)
  const saved = await get(call)
  assert.equal(saved.dmTools.rechargeCalendar.evaluatedThrough, 89999)
  assert.equal(ok(await call('adopt_xge_recharge_calendar', f.input)).replayed, true)
  assert.equal((await call('adopt_xge_recharge_calendar', { ...f.input, eventId: 'rebase-at-boundary' })).code, 'XGE_RECHARGE_CALENDAR_IMMUTABLE')
  assert.deepEqual(await get(call), saved)

  const sid = 'xge-recharge-calendar-sql'
  await saveSession(sid, { gameState: saved, history: [], adventureId: saved.adventureId, characterId: saved.characterId })
  t.after(() => deleteSession(sid))
  const resumed = await engine(t, { dice: '3,19' })
  const restored = (await loadSession(sid)).gameState
  // Public hydration may omit the redundant adventure ID. The process owns it.
  delete restored.adventureId
  ok(await resumed('replace_game_state', { gameState: restored }))
  const before = await get(resumed)
  assert.equal(before.dmTools.magicItems[id].charges, 4)
  assert.deepEqual(before.dmTools.rechargeCalendar, saved.dmTools.rechargeCalendar)
  const drift = structuredClone(before)
  drift.dmTools.rechargeCalendar.evaluatedThrough--
  assert.equal((await resumed('replace_game_state', { gameState: drift })).code, 'XGE_RECHARGE_CALENDAR_STATE_MISMATCH')
  assert.deepEqual(await get(resumed), before)
  ok(await time(resumed, 86400))
  assert.equal(await charges(resumed, id), 7)
  ok(await time(resumed, 86400))
  assert.equal(ok(await resumed('roll_dice', { notation: '1d20' })).total, 19)
})

test('a local physical recurrence exactly now starts tomorrow, and a different period cannot adopt', async t => {
  const bad = await engine(t, { dice: '19' })
  const wrong = await prepareRechargeCalendar(bad, { periodDays: 2, adopt: false })
  const before = await get(bad)
  assert.equal((await bad('adopt_xge_recharge_calendar', wrong.input)).code, 'XGE_RECHARGE_CALENDAR_REFERENCE_REQUIRED')
  assert.equal((await bad('adopt_xge_recharge_calendar', { ...wrong.input, mapId: 'wrong-map' })).code, 'XGE_RECHARGE_CALENDAR_MAP_REQUIRED')
  assert.deepEqual(await get(bad), before)
  assert.equal(ok(await bad('roll_dice', { notation: '1d20' })).total, 19)
  const good = await engine(t)
  const f = await prepareRechargeCalendar(good, { firstAfterSeconds: 0 })
  assert.equal(f.result.firstAt, 86400)
})

async function approachManorStairs(call) {
  const choose = async (name, input) => ok(await call(name, input))
  const help = npcId => choose('reveal_npc', { npcId, disposition: 'helpful' })
  const move = roomId => choose('move_token', { tokenId: 'player', roomId })
  const travel = transitionId => choose('travel_to_map', { transitionId })
  await help('sarah')
  await choose('pick_up_item', { itemId: 'sarah_diary_copy' })
  await move('3'); await travel('sail_to_waterdeep')
  await move('7'); await help('cobbler')
  await choose('reveal_clue', { clueId: 'greenfast_lead', npcId: 'cobbler' })
  await move('6')
  await choose('move_token', { tokenId: 'player', doorId: 'vecken_home', doorMode: 'approach' })
  await choose('interact_door', { doorId: 'vecken_home', action: 'open' })
  await move('6'); await help('vecken')
  await move('9'); await travel('road_to_greenfast')
  await move('11'); await help('kara')
  await move('12'); await help('old_fargo')
  await move('16'); await travel('walk_to_tower')
  await move('18'); await move('20')
  await choose('move_token', { tokenId: 'player', toCell: { x: 38, y: 22 } })
}

test('actual stairs give neither recharge nor retroactive location, and a dropped wand keeps its own map clock', async t => {
  const call = await engine(t, { dice: '2,3,19' })
  await approachManorStairs(call)
  const ground = await createRechargeItem(call, 'wand_of_magic_missiles', 'wand-stays-on-source-floor', { initialCharges: 1, pickup: false })
  const carried = await createRechargeItem(call, 'wand_of_magic_missiles', 'wand-follows-carrier', { initialCharges: 1 })
  const before = await get(call), untilDawn = 86400 - before.worldTimeSeconds % 86400
  assert.equal(before.currentMapId, 'temple')
  await prepareRechargeCalendar(call, { firstAfterSeconds: untilDawn + 60 })
  const stairs = ok(await call('travel_to_map', { transitionId: 'descend_manor' }))
  assert.equal(stairs.travelSeconds, 0)
  assert.equal((await get(call)).worldTimeSeconds, before.worldTimeSeconds)
  assert.equal(await charges(call, ground), 1)
  assert.equal(await charges(call, carried), 1)
  ok(await time(call, untilDawn))
  assert.equal(await charges(call, carried), 4)
  assert.equal(await charges(call, ground), 1)
  ok(await time(call, 60))
  assert.equal(await charges(call, carried), 4)
  assert.equal(await charges(call, ground), 5)
  const saved = await get(call)
  ok(await call('replace_game_state', { gameState: saved }))
  assert.deepEqual(await get(call), saved)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

test('the real initiative round clock crosses a selected source boundary before another action', async t => {
  const call = await engine(t, { dice: '20,1,2,19' })
  const id = await createRechargeItem(call, 'wand_of_magic_missiles', 'round-clock-wand', { initialCharges: 1 })
  await prepareRechargeCalendar(call, { firstAfterSeconds: 3 })
  const enemy = await spawn(call)
  ok(await call('enter_combat', { combatants: ['player', enemy.id] }))
  ok(await call('next_turn', { actorId: 'player', skipAction: true }))
  assert.equal(await charges(call, id), 1)
  ok(await call('next_turn', { actorId: enemy.id, skipAction: true }))
  const state = await get(call)
  assert.equal(state.worldTimeSeconds, 6)
  assert.equal(state.dmTools.rechargeCalendar.evaluatedThrough, 6)
  assert.equal(state.dmTools.magicItems[id].charges, 4)
  ok(await call('replace_game_state', { gameState: state }))
  assert.deepEqual(await get(call), state)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})
