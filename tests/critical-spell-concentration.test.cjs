const test=require('node:test'),assert=require('node:assert/strict')
Object.assign(process.env,{MONETIZATION_ENABLED:'false',LLM_MODE:'mock',ALLOW_PAID_LLM:'false',APP_LOG_PERSIST_ENABLED:'false'})
const{installPgMem}=require('./helpers/pg-mem.cjs'),pg=installPgMem()
const{engine,ok}=require('./helpers/mcp-toolkit.cjs')
const{mageConcentration,persistCritical,spawnExact}=require('./helpers/critical-spells-fixture.cjs')
test.after(()=>pg.restore())

test('actual new concentration ends its old effect before Counterspell, keeps one SQL start and spends each real spell/reaction once',async t=>{
 const f=await mageConcentration(t),before=await f.call('get_game_state')
 const a=ok(await f.call('cast_creature_spell',{casterId:f.mage.id,spellId:'greater-invisibility',targetId:f.ally.id}))
 assert.ok(a.pendingReaction)
 const held=await f.call('get_game_state')
 assert.equal(held.hero.concentrationIds[f.mage.id],undefined);assert.ok(!held.hero.effects.some(e=>e.id===f.oldId))
 assert.ok(!held.monsters[f.ally.id].conditions.includes('invisible'))
 assert.equal(held.hero.concentrationStart.id,a.pendingReaction.command.concentrationStartId)
 assert.equal(held.monsters[f.mage.id].monsterRuntime.spellSlots.level4.current,before.monsters[f.mage.id].monsterRuntime.spellSlots.level4.current)
 const corrupt=structuredClone(held);delete corrupt.hero.concentrationStart
 assert.equal((await f.call('replace_game_state',{gameState:corrupt})).code,'CRITICAL_SPELL_STATE_MISMATCH')
 assert.deepEqual(await f.call('get_game_state'),held)
 const headerChanged=structuredClone(held);headerChanged.hero.concentrationStart.at-=1
 assert.equal((await f.call('replace_game_state',{gameState:headerChanged})).code,'CRITICAL_SPELL_STATE_MISMATCH')
 assert.deepEqual(await f.call('get_game_state'),held)
 const next=await persistCritical(t,f.call),answer=ok(await next('resolve_reaction',{pendingId:a.pendingReaction.id,choice:'counterspell',slotLevel:4}))
 assert.equal(answer.countered,true)
 const after=await next('get_game_state')
 assert.equal(after.hero.concentrationStart,undefined);assert.equal(after.hero.concentrationIds[f.mage.id],undefined)
 assert.ok(!after.monsters[f.ally.id].conditions.includes('invisible'))
 assert.equal(after.monsters[f.mage.id].monsterRuntime.spellSlots.level4.current,before.monsters[f.mage.id].monsterRuntime.spellSlots.level4.current-1)
 assert.equal(after.player.spellSlots.level4.current,before.player.spellSlots.level4.current-1)
 assert.equal(after.hero.reactionsUsed.player,true);assert.equal(after.actionUsed[f.mage.id],true)
 assert.ok((await next('resolve_reaction',{pendingId:a.pendingReaction.id,choice:'counterspell',slotLevel:4})).error)
 assert.deepEqual(await next('get_game_state'),after)
 assert.equal(ok(await next('roll_dice',{notation:'1d20'})).total,19)
})

test('ending actual self Greater Invisibility exposes the new concentration casting before its qualified visual Counterspell window',async t=>{
 const f=await mageConcentration(t,{self:true})
 const a=ok(await f.call('cast_creature_spell',{casterId:f.mage.id,spellId:'greater-invisibility',targetId:f.ally.id,spellObservers:[{observerId:'player',channels:['sight']}]}))
 assert.ok(a.pendingReaction);assert.ok(a.pendingReaction.options.includes('counterspell'))
 const held=await f.call('get_game_state'),observation=held.dmTools.spellPerception.records[a.spellPerceptionEventId].original
 assert.ok(!held.monsters[f.mage.id].conditions.includes('invisible'))
 assert.ok(!observation.sourceFrame.conditions.includes('invisible'));assert.equal(observation.observers[0].sight,true)
 ok(await f.call('resolve_reaction',{pendingId:a.pendingReaction.id,choice:'decline'}))
 const after=await f.call('get_game_state')
 assert.ok(after.monsters[f.ally.id].conditions.includes('invisible'));assert.notEqual(after.hero.concentrationIds[f.mage.id],f.oldId)
 assert.equal(after.hero.concentrationStart,undefined)
 assert.equal(ok(await f.call('roll_dice',{notation:'1d20'})).total,19)
})

test('invalid original target refuses before ending current concentration, while actual Ready and long ritual keep their existing concentration starts',async t=>{
 const f=await mageConcentration(t),before=await f.call('get_game_state')
 assert.ok((await f.call('cast_creature_spell',{casterId:f.mage.id,spellId:'greater-invisibility',targetId:'not-an-actor'})).error)
 assert.deepEqual(await f.call('get_game_state'),before)
 const call=await engine(t,{characterId:'wizard',dice:'20,1,19'})
 ok(await call('prepare_spells',{spellIds:['greater-invisibility','mage-armor','counterspell','detect-magic']}))
 ok(await call('cast_spell',{spellId:'greater-invisibility',targetId:'player'}))
 const enemy=await spawnExact(call,'goblin')
 ok(await call('enter_combat',{combatants:['player',enemy.id]}))
 const old=(await call('get_game_state')).hero.concentrationIds.player
 const ready=ok(await call('combat_action',{action:'ready',readied:{kind:'spell',spellId:'mage-armor',targetId:'player',focusItemId:'component_pouch',trigger:'The selected real goblin completes its explicitly chosen visible step.'}}))
 let state=await call('get_game_state');assert.notEqual(state.hero.concentrationIds.player,old);assert.equal(state.hero.concentrationIds.player,ready.readyId)
 assert.ok(!state.player.conditions.includes('invisible'));assert.equal(state.hero.concentrationStart,undefined)
 // A second fresh real session exercises the existing long-casting producer.
 const ritual=await engine(t,{characterId:'wizard',dice:'19'})
 ok(await ritual('prepare_spells',{spellIds:['greater-invisibility','detect-magic']}))
 ok(await ritual('cast_spell',{spellId:'greater-invisibility',targetId:'player'}))
 const oldRitual=(await ritual('get_game_state')).hero.concentrationIds.player
 const begun=ok(await ritual('cast_spell',{spellId:'detect-magic',targetId:'player',ritual:true}))
 assert.ok(begun.castingId)
 state=await ritual('get_game_state');assert.notEqual(state.hero.concentrationIds.player,oldRitual);assert.ok(!state.player.conditions.includes('invisible'))
 const restored=await persistCritical(t,ritual)
 ok(await restored('cancel_casting',{castingId:begun.castingId}));assert.equal((await restored('get_game_state')).hero.concentrationIds.player,undefined)
})
