const test=require('node:test'),assert=require('node:assert/strict')
Object.assign(process.env,{MONETIZATION_ENABLED:'false',LLM_MODE:'mock',ALLOW_PAID_LLM:'false'})
const{installPgMem}=require('./helpers/pg-mem.cjs'),pg=installPgMem()
const{saveSession,loadSession,deleteSession}=require('../lib/session-store.ts')
const{engine,ok}=require('./helpers/mcp-toolkit.cjs')
const{prepareCourse}=require('./helpers/xge-training-fixture.cjs')
const{prepareLightObject}=require('./helpers/light-spell-fixture.cjs')
const{copperValue}=require('../mcp-server/dist/lib/srd/currency.js')
test.after(()=>pg.restore())

test('one real eight-hour XGE lesson expires the touched PHB Light object and SQL replay preserves both clocks, the paid block and the actual instruction date',async t=>{
 const call=await engine(t,{characterId:'wizard',dice:'19'}),f=await prepareCourse(call),object=await prepareLightObject(call)
 const initial=await call('get_game_state')
 ok(await call('configure_scene_lighting',{roomId:initial.currentRoomId,illumination:'darkness'}))
 const cast=ok(await call('cast_spell',{spellId:'light',lightObject:object.selection,focusItemId:'component_pouch'}))
 const lit=await call('get_game_state')
 assert.equal(ok(await call('inspect_lighting',{cell:lit.player.position})).illumination,'bright')
 const lesson=await f.lesson('w24-actual-eight-hour-lesson')
 ok(await call('work_xge_training',lesson))
 const taught=await call('get_game_state'),view=ok(await call('inspect_xge_training')).courses.find(c=>c.courseId===f.input.courseId)
 assert.equal(taught.worldTimeSeconds,lit.worldTimeSeconds+28800)
 assert.equal(cast.expiresAt,lit.worldTimeSeconds+3600)
 assert.equal(ok(await call('inspect_lighting',{cell:taught.player.position})).illumination,'darkness')
 assert.equal(copperValue(lit.dmTools.wallet)-copperValue(taught.dmTools.wallet),2500)
 assert.deepEqual(view.actualInstructionDays,[Math.floor(lit.worldTimeSeconds/86400)])
 assert.equal(view.actualEffortSeconds,28800);assert.equal(view.paidBlocks.length,1)
 assert.deepEqual(taught.player.languages,lit.player.languages)
 assert.deepEqual(taught.player.hp,lit.player.hp);assert.deepEqual(taught.player.spellSlots,lit.player.spellSlots)
 assert.deepEqual(taught.player.inventory,lit.player.inventory)
 const id=`w24-cross-light-training-${process.pid}-${Math.random()}`;t.after(()=>deleteSession(id))
 await saveSession(id,{gameState:taught,history:[],adventureId:taught.adventureId,characterId:taught.characterId})
 const next=await engine(t,{characterId:'wizard',dice:'19'})
 ok(await next('replace_game_state',{gameState:(await loadSession(id)).gameState}))
 const restored=await next('get_game_state')
 assert.equal(restored.worldTimeSeconds,taught.worldTimeSeconds)
 assert.deepEqual(ok(await next('inspect_xge_training')),ok(await call('inspect_xge_training')))
 assert.equal(ok(await next('inspect_lighting',{cell:restored.player.position})).illumination,'darkness')
 assert.equal(ok(await next('work_xge_training',lesson)).replayed,true)
 assert.deepEqual(await next('get_game_state'),restored)
 assert.equal(ok(await next('roll_dice',{notation:'1d20'})).total,19)
})

test('eight real instruction hours consume time and fees without becoming a rest or removing fatigue actually gained in a DMG chase',async t=>{
 const{makePlayerChaseFatigue}=require('./helpers/chase-fixture.cjs')
 const chase=await makePlayerChaseFatigue(t),call=chase.call
 const f=await prepareCourse(call,{courseId:'w24-after-actual-chase',instructorId:'w24-real-following-instructor'})
 const before=await call('get_game_state')
 assert.equal(before.dmTools.chases.fatigue.player.levels,1)
 const lesson=await f.lesson('w24-no-rest-from-instruction')
 ok(await call('work_xge_training',lesson))
 const after=await call('get_game_state')
 assert.equal(after.worldTimeSeconds,before.worldTimeSeconds+28800)
 assert.equal(after.dmTools.chases.fatigue.player.levels,1)
 assert.deepEqual(after.dmTools.chases,before.dmTools.chases)
 assert.deepEqual(after.dmTools.exhaustion,before.dmTools.exhaustion)
 assert.deepEqual(after.player.hp,before.player.hp)
 assert.equal(copperValue(before.dmTools.wallet)-copperValue(after.dmTools.wallet),2500)
 const view=ok(await call('inspect_xge_training')).courses.find(c=>c.courseId===f.input.courseId)
 assert.deepEqual(view.actualInstructionDays,[Math.floor(before.worldTimeSeconds/86400)])
 const id=`w24-cross-chase-training-${process.pid}-${Math.random()}`;t.after(()=>deleteSession(id))
 await saveSession(id,{gameState:after,history:[],adventureId:after.adventureId,characterId:after.characterId})
 const next=await engine(t,{characterId:'fighter',dice:'19'})
 ok(await next('replace_game_state',{gameState:(await loadSession(id)).gameState}))
 const restored=await next('get_game_state')
 assert.deepEqual(restored.dmTools.chases,after.dmTools.chases)
 assert.deepEqual(restored.dmTools.exhaustion,after.dmTools.exhaustion)
 assert.equal(ok(await next('work_xge_training',lesson)).replayed,true)
 assert.deepEqual(await next('get_game_state'),restored)
})
