test('a first ice check at the actual chase guard threshold refuses before the simultaneous paid step', async t => {
  const f = await setupChase(t, { dice: '20,10,1,9,17' })
  const state = await f.call('get_game_state'), from = state.monsters[f.pursuer.id].position
  const guard = state.monsters[f.guard.id], nav = grid(state, f.pursuer.id)
  const cardinal = cell => nav.neighbors(cell).filter(next => (next.x === cell.x || next.y === cell.y) && nav.step(cell, next))
  const pair = cardinal(from).flatMap(dry => cardinal(dry).map(ice => [dry, ice])).find(([, ice]) =>
    (ice.x !== from.x || ice.y !== from.y)
    && Math.max(Math.abs(ice.x - guard.position.x), Math.abs(ice.y - guard.position.y)) <= 1)
  assert.ok(pair, 'The real chase room has a 20-foot sequence through dry cells ending within the real guard reach.')
  const [dry, ice] = pair, path = [from, dry, from, dry, ice]
  const source = 'Le MJ confirme la plaque glissante sur la dernière case de cette vraie trajectoire.'
  const fact = ok(await f.call('record_scene_fact', { cell: ice, description: source })).worldFact
  const surfaceId = 'actual-guard-ice-support'
  ok(await f.call('record_vertical_surface', { eventId: 'actual-guard-ice-measure', surfaceId,
    mapId: state.currentMapId, roomId: state.currentRoomId, cells: [ice], kind: 'support',
    elevationFeet: 0, actualGeometryConfirmed: true, source }))
  ok(await f.call('record_slippery_ice', { zoneId: 'actual-guard-ice-zone', surfaceId, cells: [ice],
    factId: fact.id, actualSlipperyIceConfirmed: true }))
  await endChaseTurn(f, 'actual-guard-ice-table')
  ok(await f.call('qualify_chase_complication', { eventId: 'actual-guard-ice-route', chaseId: f.input.chaseId,
    turnEventId: 'actual-guard-ice-table', factId: f.fact.id, path, guardId: f.guard.id }))
  ok(await f.call('resolve_chase_complication', { eventId: 'actual-guard-ice-complication', chaseId: f.input.chaseId,
    turnEventId: 'actual-guard-ice-table', choice: 'resolve' }))
  await next(f)
  for (const cell of path.slice(1, 4)) assert.equal(ok(await move(f.call, cell, f.pursuer.id)).costCells, 1)
  const before = await f.call('get_game_state')
  assert.equal(before.dmTools.chases.episodes[f.input.chaseId].turns['actual-guard-ice-table'].movedFeet, 15)
  assert.equal(before.movementUsed[f.pursuer.id], 3)
  await refused(f.call, 'move_token', { tokenId: f.pursuer.id, toCell: ice }, 'SLIPPERY_ICE_CHASE_GUARD_ORDER_UNREPRESENTED')
  assert.equal(await rollMarker(f.call), 17)
})

test('a real held Acrobatics check survives SQL with its source d20, and tampered roll is refused before Inspiration', async t => {
  const call = await engine(t, { characterId: 'bard', dice: '1,20,1' })
  const f = await prepareIce(call)
  const state = await call('get_game_state'), nav = grid(state)
  const dry = nav.neighbors(f.one).find(cell => nav.step(f.one, cell)
    && Math.max(Math.abs(cell.x - f.start.x), Math.abs(cell.y - f.start.y)) <= 1
    && ![f.start, f.one, f.two].some(value => value.x === cell.x && value.y === cell.y))
  assert.ok(dry)
  const actor = await spawn(call, 'skeleton', dry)
  ok(await call('use_subclass_feature', { featureId: 'bardic_inspiration', targetId: actor.id }))
  const battle = ok(await call('enter_combat', { combatants: ['player', actor.id] }))
  assert.equal(battle.currentTurn, actor.id)
  const partial = ok(await move(call, f.one, actor.id))
  const held = ok(await resolve(call, partial.slipperyIceContactId)).pendingReaction
  assert.equal(held.command.type, 'check')
  assert.deepEqual(held.roll.rolls, [1])
  assert.ok(held.options.includes('bardic_inspiration'))
  const snapshot = await call('get_game_state'), fresh = await restoreIce(t, snapshot, '3,17')
  const altered = structuredClone(snapshot)
  altered.hero.pending.roll.total = 100
  await refused(fresh, 'replace_game_state', { gameState: altered }, 'SLIPPERY_ICE_STATE_MISMATCH')
  const retry = ok(await resolve(fresh, partial.slipperyIceContactId))
  assert.equal(retry.alreadyPending, true)
  assert.deepEqual(retry.pendingReaction, held)
  const answer = receipt(ok(await fresh('resolve_reaction', { pendingId: held.id, choice: 'bardic_inspiration' })))
  const check = answer.contactResults[0].check
  assert.deepEqual(check.roll.rolls, [1])
  assert.equal(check.roll.total, held.roll.total + 3)
  assert.equal(check.success, false)
  assert.equal(await rollMarker(fresh), 17)
})
