test('slippery ice refuses an actual exploration entry before movement or stealth dice, but actual hazard initiative does not move anyone', async t => {
  const call = await engine(t, { dice: '20,17' })
  const f = await prepareIce(call)
  await refused(call, 'move_token', { tokenId: 'player', toCell: f.one, stealth: true }, 'SLIPPERY_ICE_TURNS_REQUIRED')
  await refused(call, 'enter_combat', { ...f.approach, hazardPreparation: { kind: 'slippery_ice', hazardId: 'unobserved' } }, 'ACTIVE_HAZARD_REQUIRED')
  const started = ok(await call('enter_combat', f.approach))
  assert.deepEqual(started.initiativeOrder, ['player'])
  assert.equal(started.hazardPreparation.validatedBy, 'reachable_ground_path')
  assert.deepEqual((await call('get_game_state')).player.position, f.start)
  assert.deepEqual(ok(await call('inspect_slippery_ice')).pendingEntries, [])
  assert.equal(await rollMarker(call), 17)
})

test('the paid first step uses Acrobatics, prone leaves remaining movement, and the next real turn can check from one icy cell into another', async t => {
  const call = await engine(t, { characterId: 'bard', dice: '20,1,19,17' })
  const f = await prepareIce(call)
  ok(await call('enter_combat', f.approach))
  const preview = ok(await call('preview_navigation', { tokenId: 'player', toCell: f.two }))
  assert.deepEqual(preview.path, [f.start, f.one, f.two])
  assert.equal(preview.costCells, 4)
  const partial = ok(await move(call, f.two))
  assert.equal(partial.stopReason, 'slippery_ice_entry')
  assert.deepEqual(partial.path, [f.start, f.one])
  assert.equal(partial.costCells, 2)
  assert.equal(partial.remainingMovement, 4)
  await refused(call, 'move_token', { tokenId: 'player', toCell: f.start }, 'GROUND_GEAR_CONTACT_DUE')
  const failure = receipt(ok(await resolve(call, partial.slipperyIceContactId)))
  const check = failure.contactResults[0].check
  assert.equal(check.proficient, true)
  assert.equal(check.ability, 'dex')
  assert.equal(check.dc, 10)
  assert.deepEqual(check.roll.rolls, [1])
  assert.equal(check.success, false)
  assert.equal(failure.movementStopped, true)
  const prone = await call('get_game_state')
  assert.ok(prone.player.conditions.includes('prone'))
  assert.equal(prone.actionUsed.player ?? false, false)
  assert.equal(prone.movementUsed.player, 2)
  assert.deepEqual(prone.player.position, f.one)
  ok(await call('combat_action', { action: 'stand_up' }))
  ok(await call('combat_action', { action: 'dash' }))
  const afterStand = ok(await move(call, f.two))
  assert.equal(afterStand.costCells, 2)
  assert.equal(afterStand.slipperyIceContactId, undefined)
  const leave = ok(await move(call, f.start))
  assert.equal(leave.costCells, 3)
  assert.equal(leave.slipperyIceContactId, undefined)
  assert.equal(ok(await move(call, f.one)).slipperyIceContactId, undefined)
  const prior = await call('get_game_state')
  ok(await call('next_turn', { actorId: 'player' }))
  const newTurn = await call('get_game_state')
  assert.ok(newTurn.turnCounter > prior.turnCounter)
  const reentry = ok(await move(call, f.two))
  assert.equal(reentry.costCells, 2)
  assert.notEqual(reentry.slipperyIceContactId, partial.slipperyIceContactId)
  const success = receipt(ok(await resolve(call, reentry.slipperyIceContactId)))
  assert.deepEqual(success.contactResults[0].check.roll.rolls, [19])
  assert.equal(success.contactResults[0].check.success, true)
  assert.equal(await rollMarker(call), 17)
})

test('successful retained movement resumes its unpaid suffix after a fresh SQL restore, and a replaced narrative source keeps history', async t => {
  const call = await engine(t, { dice: '20' })
  const f = await prepareIce(call)
  ok(await call('record_scene_fact', { cell: f.one, replaceFactId: f.qualification.factId,
    description: 'Le fait de scène a été précisé. La plaque de glace mesurée demeure présente.' }))
  assert.ok(!(await call('get_game_state')).worldFacts.some(fact => fact.id === f.qualification.factId))
  ok(await call('enter_combat', f.approach))
  const partial = ok(await move(call, f.two))
  const waiting = await call('get_game_state')
  const fresh = await restoreIce(t, waiting, '19,17')
  const restored = ok(await fresh('inspect_slippery_ice')).pendingEntries[0]
  assert.equal(restored.id, partial.slipperyIceContactId)
  assert.deepEqual(restored.continuation.iceWalk.retainedPath, [f.one, f.two])
  const result = ok(await resolve(fresh, restored.id))
  assert.deepEqual(result.movement.path, [f.one, f.two])
  assert.equal(result.movement.costCells, 2)
  assert.equal(result.groundGearContact.contactResults[0].check.success, true)
  const completed = await fresh('get_game_state')
  assert.equal(completed.movementUsed.player, 4)
  assert.equal(completed.worldTimeSeconds, waiting.worldTimeSeconds)
  assert.deepEqual(completed.player.position, f.two)
  assert.equal(ok(await resolve(fresh, restored.id)).replayed, true)
  assert.deepEqual(await fresh('get_game_state'), completed)
  assert.equal(await rollMarker(fresh), 17)
})

