const test=require('node:test'),assert=require('node:assert/strict')
Object.assign(process.env,{MONETIZATION_ENABLED:'false',LLM_MODE:'mock',ALLOW_PAID_LLM:'false',RUNPOD_AUTO_MANAGE:'false',APP_LOG_PERSIST_ENABLED:'false',APP_LOG_LEVEL:'error'})
const{installPgMem}=require('./helpers/pg-mem.cjs'),pg=installPgMem()
const{saveSession,loadSession,deleteSession}=require('../lib/session-store.ts')
const{engine,ok}=require('./helpers/mcp-toolkit.cjs')
const{setupWork}=require('./helpers/downtime-fixture.cjs')
test.after(()=>pg.restore())

test('five actual Work days advance the original calendar without minting lifestyle cash, then one exact unsettled SQL result settles once in a new engine',async t=>{
 const f=await setupWork(t,{dice:'19,100,17'}),{call}=f
 let state=await call('get_game_state')
 const decision=ok(await call('record_scene_fact',{description:'The MJ establishes this exact date and 86400-second display day at the existing engine clock. No earlier Work, rest, nutrition or elapsed day is created or rebased.',cell:state.player.position})).worldFact
 const configuration={eventId:'w23-work-calendar',decisionFactId:decision.id,actualCalendarAndAnchorConfirmed:true,day86400SecondsExplicitlyAdopted:true,definition:{kind:'custom_fixed',name:'Actual Work display calendar',segments:[{segmentId:'month',name:'Chosen month',days:30}]},anchor:{year:1,segmentId:'month',day:1,secondOfDay:86399}}
 ok(await call('configure_campaign_calendar',configuration))
 const before=await call('get_game_state'),calendar=structuredClone(before.dmTools.calendar),wallet=structuredClone(before.dmTools.wallet)
 await f.complete()
 const completed=await call('get_game_state'),project=completed.dmTools.downtime.projects[f.input.projectId]
 assert.equal(project.segments.reduce((n,s)=>n+s.to-s.from,0),5*8*3600)
 assert.equal(new Set(project.segments.map(s=>s.day)).size,5)
 assert.ok(completed.worldTimeSeconds-before.worldTimeSeconds>=5*8*3600)
 assert.deepEqual(completed.dmTools.wallet,wallet)
 assert.deepEqual(completed.player.inventory,before.player.inventory)
 assert.deepEqual(completed.dmTools.calendar,calendar)
 const projected=ok(await call('inspect_campaign_calendar'))
 const elapsed=completed.worldTimeSeconds-calendar.configuration.at
 assert.equal(projected.elapsedSeconds,elapsed)
 assert.equal(projected.date.day,Math.floor((86399+elapsed)/86400)+1)
 assert.equal(projected.date.secondOfDay,(86399+elapsed)%86400)
 assert.deepEqual(await call('get_game_state'),completed)
 ok(await call('resolve_downtime_work',f.resolution))
 const resolved=await call('get_game_state'),resolution=resolved.dmTools.downtime.projects[f.input.projectId].resolution
 assert.ok(resolution.check.roll.total>=21)
 assert.equal(resolution.chance.total,100)
 assert.deepEqual(resolved.dmTools.wallet,wallet)
 assert.equal(resolved.dmTools.downtime.projects[f.input.projectId].settlement,undefined)
 const settlement=await f.settlement('w23-work-final-source-settlement',{gp:25})
 const snapshot=await call('get_game_state'),sessionId=`w23-work-real-days-calendar-${process.pid}`
 t.after(()=>deleteSession(sessionId))
 await saveSession(sessionId,{gameState:snapshot,history:[],adventureId:snapshot.adventureId,characterId:snapshot.characterId})
 const loaded=(await loadSession(sessionId)).gameState;assert.deepEqual(loaded,snapshot)
 const resumed=await engine(t,{adventureId:snapshot.adventureId,characterId:snapshot.characterId,dice:'17'})
 ok(await resumed('replace_game_state',{gameState:loaded}));assert.deepEqual(await resumed('get_game_state'),snapshot)
 ok(await resumed('inspect_xge_downtime'));ok(await resumed('inspect_campaign_calendar'))
 assert.deepEqual(await resumed('get_game_state'),snapshot)
 const paid=ok(await resumed('settle_downtime_work',settlement))
 assert.equal(paid.cashCp,2500)
 assert.equal(paid.lifestyleEntitlement.days,7)
 assert.equal(paid.lifestyleEntitlement.endDay,paid.lifestyleEntitlement.startDay+6)
 assert.equal(paid.lifestyleEntitlement.status,'recorded_nonmonetary_entitlement')
 assert.equal(paid.lifestyleEntitlement.futureExpenseConsumptionImplemented,false)
 assert.equal(paid.lifestyleEntitlement.foodOrWaterGranted,false)
 assert.equal(paid.lifestyleEntitlement.healingOrRestGranted,false)
 const after=await resumed('get_game_state')
 assert.equal(after.worldTimeSeconds,snapshot.worldTimeSeconds)
 assert.deepEqual(after.dmTools.wallet,{...wallet,gp:wallet.gp+25})
 assert.deepEqual(after.player.inventory,snapshot.player.inventory)
 assert.deepEqual(after.dmTools.calendar,calendar)
 assert.deepEqual(after.dmTools.downtime.projects[f.input.projectId].segments,project.segments)
 assert.deepEqual(after.dmTools.downtime.projects[f.input.projectId].resolution,resolution)
 assert.equal(ok(await resumed('settle_downtime_work',settlement)).replayed,true)
 assert.deepEqual(await resumed('get_game_state'),after)
 assert.equal(ok(await resumed('roll_dice',{notation:'1d20'})).total,17)
})
