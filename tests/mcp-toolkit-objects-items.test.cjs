const test = require('node:test')
const assert = require('node:assert/strict')
const { engine, ok, replace, adjacent, spawn, battle, object, addSupply } = require('./helpers/mcp-toolkit.cjs')

test('source object statistics, one-time contents and runtime state survive save/reload and idempotent creation', async t => {
  const call = await engine(t)
  const overrides = { contents: ['healers_kit', 'thieves_tools'] }
  const created = await object(call, 'supply-chest', overrides)
  assert.equal(created.object.ac, 15)
  assert.deepEqual(created.object.hp, { current: 10, max: 10 })
  const opened = ok(await call('interact_object', { objectId: 'supply-chest', action: 'open' }))
  assert.equal(opened.releasedItems.length, 2)
  ok(await call('pick_up_item', { itemId: opened.releasedItems[0].id }))
  ok(await call('interact_object', { objectId: 'supply-chest', action: 'close' }))
  assert.deepEqual(ok(await call('interact_object', { objectId: 'supply-chest', action: 'open' })).releasedItems, [])
  const state = await call('get_game_state')
  ok(await call('replace_game_state', { gameState: state }))
  assert.deepEqual((await call('get_game_state')).dmTools, state.dmTools)
  assert.equal((await object(call, 'supply-chest', overrides)).alreadyCreated, true)
  assert.equal((await call('get_game_state')).player.inventory.filter(item => item.id === opened.releasedItems[0].id).length, 1)
})

test('forcing a container rolls once and applies its stored lock/open state; generic checks cannot do so', async t => {
  const call = await engine(t, { dice: '20,17' })
  await object(call, 'locked-chest', { locked: true, lockDc: 15, forceDc: 15 })
  const forced = ok(await call('interact_object', { objectId: 'locked-chest', action: 'force' }))
  assert.equal(forced.success, true)
  assert.equal(forced.object.state, 'open')
  assert.equal(forced.object.locked, false)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 17)
})

test('a held force check applies no object change until Bardic Inspiration is resolved, even after hydration', async t => {
  const call = await engine(t, { dice: '5,4' })
  await object(call, 'held-chest', { locked: true, lockDc: 15, forceDc: 15 })
  const enemy = await spawn(call)
  await battle(call, [enemy.id])
  await replace(call, state => state.hero.inspiration.push({ targetId: 'player', expiresAt: 600, die: 8 }))
  const held = ok(await call('interact_object', { objectId: 'held-chest', action: 'force' }))
  assert.ok(held.pendingReaction)
  const state = await call('get_game_state')
  assert.equal(state.dmTools.objects['held-chest'].state, 'closed')
  assert.equal(state.hero.actionCredits, 1)
  ok(await call('replace_game_state', { gameState: state }))
  const resolved = ok(await call('resolve_reaction', { pendingId: held.pendingReaction.id, choice: 'bardic_inspiration' }))
  assert.equal(resolved.success, true)
  assert.equal(resolved.object.state, 'open')
  assert.equal((await call('get_game_state')).hero.actionCredits, 0)
})

test('an actual obstacle blocks navigation until weapon damage destroys it, retaining Extra Attack', async t => {
  const call = await engine(t, { dice: '20,8,8' })
  const state = await call('get_game_state'), cell = adjacent(state)[0]
  await object(call, 'wood-block', { kind: 'obstacle', cell })
  assert.ok((await call('preview_navigation', { tokenId: 'player', toCell: cell })).error)
  const enemy = await spawn(call)
  await battle(call, [enemy.id])
  const attack = ok(await call('interact_object', { objectId: 'wood-block', action: 'attack', weaponId: 'longsword' }))
  assert.equal(attack.hit, true)
  assert.equal(attack.object.state, 'destroyed')
  assert.equal((await call('get_game_state')).hero.attackAction.remaining, 1)
  assert.ok(!((await call('preview_navigation', { tokenId: 'player', toCell: cell })).error))
})

test('lock picking validates the real tool/proficiency and a missing force DC changes nothing or consumes dice', async t => {
  const call = await engine(t, { dice: '18' })
  await object(call, 'lock', { locked: true, lockDc: 15 })
  await addSupply(call, 'thieves_tools', 'my-tools')
  const before = await call('get_game_state')
  assert.equal((await call('interact_object', { objectId: 'lock', action: 'pick_lock', toolItemId: 'my-tools' })).code, 'TOOL_PROFICIENCY_REQUIRED')
  assert.equal((await call('interact_object', { objectId: 'lock', action: 'force' })).code, 'OBJECT_RULE_NOT_AUTHORED')
  assert.deepEqual(await call('get_game_state'), before)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 18)
})

test('explicit equipment distinguishes carrying a shield from wearing it and rejects attacks with stowed weapons', async t => {
  const call = await engine(t, { dice: '17,4' })
  assert.equal((await call('get_game_state')).player.ac, 18)
  ok(await call('equip_item', { itemId: 'shield', slot: 'shield', operation: 'unequip' }))
  let state = await call('get_game_state')
  assert.equal(state.player.ac, 16)
  assert.ok(state.player.inventory.some(item => item.id === 'shield'))
  ok(await call('equip_item', { itemId: 'shield', slot: 'shield', operation: 'equip' }))
  assert.equal((await call('get_game_state')).player.ac, 18)
  assert.equal((await call('drop_item', { itemId: 'shield' })).code, 'ITEM_EQUIPPED')
  const enemy = await spawn(call)
  await battle(call, [enemy.id])
  state = await call('get_game_state')
  assert.equal((await call('resolve_player_attack', { targetId: enemy.id, weaponOrSpell: 'handaxe' })).code, 'WEAPON_NOT_EQUIPPED')
  assert.deepEqual(await call('get_game_state'), state)
  assert.equal(ok(await call('resolve_player_attack', { targetId: enemy.id, weaponOrSpell: 'longsword' })).hit, true)
})

test('body armor uses source don/doff time and carried spare armor does not grant AC with an active loadout', async t => {
  const call = await engine(t)
  const before = await call('get_game_state')
  const doff = ok(await call('equip_item', { itemId: 'chain_mail', slot: 'armor', operation: 'unequip' }))
  assert.equal(doff.seconds, 300)
  assert.equal(doff.ac, 13) // DEX +1, shield +2.
  let state = await call('get_game_state')
  assert.equal(state.worldTimeSeconds, before.worldTimeSeconds + 300)
  ok(await call('drop_item', { itemId: 'chain_mail' }))
  ok(await call('pick_up_item', { itemId: 'chain_mail' }))
  state = await call('get_game_state')
  assert.equal(state.player.ac, 13)
  assert.equal(ok(await call('equip_item', { itemId: 'chain_mail', slot: 'armor', operation: 'equip' })).seconds, 600)
  assert.equal((await call('get_game_state')).player.ac, 18)
})

test('a healer kit stabilizes without healing or a Medicine check, spends one use and records one recovery d4 through hydration', async t => {
  const call = await engine(t, { dice: '2,19' })
  await addSupply(call, 'healers_kit', 'kit')
  const helper = await spawn(call, 'knight')
  await battle(call, [helper.id], helper.id)
  await replace(call, state => { state.player.hp.current = 0; state.player.deathSaves = { successes: 0, failures: 1 }; state.monsters[helper.id].hostile = false })
  const answer = ok(await call('use_item', { itemId: 'kit', actorId: helper.id, targetId: 'player' }))
  assert.equal(answer.hp.current, 0)
  assert.equal(answer.deathSaves.stable, true)
  assert.equal(answer.usesRemaining, 9)
  const state = await call('get_game_state')
  assert.equal(state.actionUsed[helper.id], true)
  assert.equal(state.dmTools.playerRecovery.episode.hours,2)
  ok(await call('replace_game_state', { gameState: state }))
  assert.equal((await call('get_game_state')).dmTools.itemUses.kit, 9)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

test('antitoxin is consumed, grants actual poison-save advantage for an hour and does not cure poison', async t => {
  const call = await engine(t, { dice: '2,18,7' })
  await addSupply(call, 'antitoxin', 'antidote')
  await replace(call, state => state.player.conditions.push('poisoned'))
  ok(await call('use_item', { itemId: 'antidote' }))
  let state = await call('get_game_state')
  assert.ok(!state.player.inventory.some(item => item.id === 'antidote'))
  assert.ok(state.player.conditions.includes('poisoned'))
  assert.match(ok(await call('resolve_saving_throw', { entityId: 'player', ability: 'con', dc: 15, againstCondition: 'poisoned' })).roll.detail, /ADV/)
  ok(await call('advance_time', { seconds: 3600 }))
  state = await call('get_game_state')
  assert.ok(!state.hero.effects.some(effect => effect.kind === 'antitoxin'))
  assert.doesNotMatch(ok(await call('resolve_saving_throw', { entityId: 'player', ability: 'con', dc: 15, againstCondition: 'poisoned' })).roll.detail, /ADV/)
})

