const test=require('node:test'),assert=require('node:assert/strict')
const {engine,ok,replace}=require('./helpers/mcp-toolkit.cjs')
const {WILDERNESS_NAVIGATION_DC,TravelStateSchema,validateTravelState}=require('../mcp-server/dist/lib/travel-state.js')
const source='Le MJ confirme cette observation actuelle sur la route réellement établie ; aucune donnée déduite du texte.'
const route=extra=>({journeyId:'actual-route',origin:'Origine de la carte réelle',destination:'Destination de cette même carte',distanceFeet:528000,terrain:'normal',actualRouteConfirmed:true,source,...extra})
const navigation=(eventId,extra={})=>({eventId,journeyId:'actual-route',pace:'normal',terrain:'forest',offPathConfirmed:true,aids:[],source,...extra})
const search=(eventId,extra={})=>({eventId,journeyId:'actual-route',pace:'normal',durationSeconds:3600,rank:'front',source,...extra})
const step=(eventId,extra={})=>({eventId,journeyId:'actual-route',pace:'normal',scale:'hour',durationSeconds:3600,activity:'watch',rank:'front',openTerrain:true,source,...extra})
async function start(call){
 ok(await call('begin_nutrition_tracking',{eventId:'nutrition',operation:'begin',standardNeedsConfirmed:true,hotWeather:false,source,foodDebtHalfDays:0,priorDeprivation:'none'}))
 ok(await call('begin_travel_tracking',{eventId:'known-walking',dayStartsAt:0,knownWalkingSeconds:0,historyKnown:true,source}))
 ok(await call('create_travel_route',route()))
}
async function refused(call,name,input,code){const before=await call('get_game_state'),result=await call(name,input);assert.equal(result.code,code,JSON.stringify(result));assert.deepEqual(await call('get_game_state'),before)}
async function hydrate(call){const state=await call('get_game_state');ok(await call('replace_game_state',{gameState:state}));assert.deepEqual(await call('get_game_state'),state);return state}

