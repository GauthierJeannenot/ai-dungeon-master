test('map and celestial aids require actual explicit witnesses, advantage does not stack and missing map/duplicate aid refuses before dice',async t=>{
 const call=await engine(t,{dice:'1,14,19'});await start(call)
 const aid={kind:'accurate_map',itemId:'actual-route-map',accurateForRouteConfirmed:true,source}
 await refused(call,'resolve_travel_navigation',navigation('missing-map',{aids:[aid]}),'TRAVEL_NAVIGATION_MAP_REQUIRED')
 await replace(call,state=>state.player.inventory.push({id:'actual-route-map',name:'Support renommé sans interprétation de son nom',type:'misc',description:'Carte réelle dont le MJ établit explicitement la précision.'}))
 await refused(call,'resolve_travel_navigation',navigation('duplicate',{aids:[aid,aid]}),'TRAVEL_NAVIGATION_AID_DUPLICATE')
 await replace(call,state=>state.player.conditions.push('blinded'))
 await refused(call,'resolve_travel_navigation',navigation('unseen-aid',{aids:[aid]}),'TRAVEL_NAVIGATION_AID_UNSEEN')
 await replace(call,state=>{state.player.conditions=state.player.conditions.filter(value=>value!=='blinded')})
 const input=navigation('actual-map-and-stars',{aids:[aid,{kind:'visible_celestial',body:'stars',visibleConfirmed:true,source}]})
 const done=ok(await call('resolve_travel_navigation',input));assert.equal(done.navigationSucceeded,true);assert.equal(done.check.advantage,true)
 assert.deepEqual(done.check.roll.rolls,[14]);assert.match(done.check.roll.detail,/ADV:.*\[1\].*\[14\]/);assert.equal(done.check.roll.total,15)
 const after=await hydrate(call);assert.equal(after.dmTools.travel.navigation.attempts[input.eventId].mapWitness.itemId,'actual-route-map')
 assert.equal(ok(await call('resolve_travel_navigation',input)).replayed,true);assert.deepEqual(await call('get_game_state'),after)
 await refused(call,'resolve_travel_navigation',{...input,pace:'slow'},'TRAVEL_NAVIGATION_EVENT_CONFLICT')
 assert.equal(ok(await call('roll_dice',{notation:'1d20'})).total,19)
})
test('being lost persists across routes and waiting; only real measured walking search followed by a real successful check restores direction',async t=>{
 const call=await engine(t,{dice:'1,2,20,19'});await start(call)
 const failed=ok(await call('resolve_travel_navigation',navigation('first-failed')))
 assert.equal(failed.navigationSucceeded,false);assert.equal(failed.delayRoll.total,2);assert.equal(failed.lost.requiredSearchSeconds,7200)
 await refused(call,'advance_travel',step('wrong-direction-progress'),'TRAVEL_LOST')
 await refused(call,'resolve_travel_navigation',navigation('free-retry'),'NAVIGATION_SEARCH_REQUIRED')
 ok(await call('advance_time',{seconds:7200}));assert.equal(ok(await call('inspect_travel')).navigation.lost.searchedSeconds,0)
 await refused(call,'resolve_travel_navigation',navigation('waiting-is-not-search'),'NAVIGATION_SEARCH_REQUIRED')
 ok(await call('abandon_travel_route',{eventId:'abandon',journeyId:'actual-route',reason:source}))
 ok(await call('create_travel_route',route({journeyId:'new-actual-route'})))
 await refused(call,'advance_travel',step('route-reset',{journeyId:'new-actual-route'}),'TRAVEL_LOST')
 const first=ok(await call('advance_navigation_search',search('search-first',{journeyId:'new-actual-route'})))
 assert.equal(first.distanceFeet,0);assert.equal(first.walkingSecondsThisDay,3600);assert.equal(first.navigationSearch.searchedSeconds,3600)
 assert.equal(first.contributesToThreatDetection,false);assert.equal(first.navigationSearch.directionChosen,false)
 const midway=await hydrate(call);assert.equal(ok(await call('advance_navigation_search',search('search-first',{journeyId:'new-actual-route'}))).replayed,true)
 assert.deepEqual(await call('get_game_state'),midway)
 const forged=structuredClone(midway);forged.dmTools.travel.navigation.lost.searchedSeconds++
 assert.ok(validateTravelState(forged).some(message=>message.includes('measured walking receipts')))
 ok(await call('advance_navigation_search',search('search-second',{journeyId:'new-actual-route'})))
 await refused(call,'advance_navigation_search',search('too-much-search',{journeyId:'new-actual-route'}),'NAVIGATION_SEARCH_NOT_REQUIRED')
 const found=ok(await call('resolve_travel_navigation',navigation('actual-retry',{journeyId:'new-actual-route'})))
 assert.equal(found.navigationSucceeded,true);assert.equal(found.lost,null)
 const after=await hydrate(call);assert.equal(after.worldTimeSeconds,14400);assert.equal(after.dmTools.travel.days['0'].walkingSeconds,7200)
 assert.equal(after.dmTools.travel.routes['new-actual-route'].progressedFeet,0);assert.deepEqual(after.player.position,midway.player.position)
 assert.equal(ok(await call('advance_travel',step('now-can-progress',{journeyId:'new-actual-route'}))).distanceFeet,15840)
 assert.equal(ok(await call('roll_dice',{notation:'1d20'})).total,19)
})
