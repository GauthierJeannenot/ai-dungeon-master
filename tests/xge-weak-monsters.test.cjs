const test = require('node:test'), assert = require('node:assert/strict')
process.env.MONETIZATION_ENABLED = 'false'
const { installPgMem } = require('./helpers/pg-mem.cjs'), pg = installPgMem()
const { engine, ok } = require('./helpers/mcp-toolkit.cjs')
const { saveSession, loadSession, deleteSession } = require('../lib/session-store.ts')
test.after(() => pg.restore())
const planned = (...groups) => ({ mode: 'planned', groups })
const group = (monsterType, count = 1) => ({ monsterType, count })
const assess = (call, input) => call('assess_xge_encounter', input)

test('real level-seven low CR uses separate source and exact mixed fractions without state or dice, then SQL re-evaluates identically', async t => {
  const call = await engine(t, { characterId: 'wizard', dice: '19' }), before = await call('get_game_state')
  assert.equal(before.player.level, 7)
  const selected = planned(group('rat'), group('bandit'))
  const mixed = ok(await assess(call, selected))
  assert.deepEqual(mixed.characterEquivalent, { numerator: 1, denominator: 6 })
  assert.deepEqual(mixed.groups.map(g => g.ratioStatus), ['weak_monster_guideline', 'printed'])
  assert.equal(mixed.groups[0].challengeRating, 0)
  assert.deepEqual(mixed.groups[0].ratio, { characters: 1, monsters: 12 })
  const source = mixed.groups[0].ratioSource
  assert.equal(source.book, 'xge'); assert.equal(source.startLine, 1257); assert.equal(source.endLine, 1259)
  assert.equal(source.sha256, '519584ec7fc7da6fea056c182a22254bc807db5d077c2fc205801bd872d761bf')
  assert.equal(source.tableId, undefined); assert.equal(source.rowLine, undefined)
  assert.equal(mixed.source.rowLine, 1230); assert.notEqual(source.sectionId, mixed.source.sectionId)
  assert.equal(mixed.groups[1].ratioSource, undefined)
  assert.equal(ok(await assess(call, planned(group('rat', 12)))).comparison, 'equal_to_one_character')
  assert.deepEqual(ok(await assess(call, planned(group('rat', 1000)))).characterEquivalent, { numerator: 250, denominator: 3 })
  const catalogue = ok(await assess(call, { mode: 'catalogue' }))
  assert.equal(catalogue.weakMonsterRule.belowChallengeRating, 0.125)
  assert.ok(catalogue.weakProfiles.some(p => p.monsterType === 'rat' && p.ratioStatus === 'weak_monster_guideline'))
  assert.ok(catalogue.profilesOutsidePrintedColumns.some(p => p.monsterType === 'rat'))
  assert.ok(!catalogue.rows.some(row => row.challengeRating === 0), 'The separate rule never invents a printed table column.')
  assert.deepEqual(await call('get_game_state'), before)
  const id = 'weak-monster-sql-' + process.pid + '-' + Math.random()
  t.after(() => deleteSession(id))
  await saveSession(id, { gameState: before, history: [], adventureId: before.adventureId, characterId: before.characterId })
  const restored = await engine(t, { characterId: before.characterId, adventureId: before.adventureId, dice: '19' })
  ok(await restored('replace_game_state', { gameState: (await loadSession(id)).gameState }))
  assert.deepEqual(await restored('get_game_state'), before)
  assert.deepEqual(ok(await assess(restored, selected)), mixed)
  assert.deepEqual(await restored('get_game_state'), before)
  assert.equal(ok(await restored('roll_dice', { notation: '1d20' })).total, 19)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

test('a real first-level blank cell and higher outside CR remain indeterminate beside a genuine lower CR, with no input override or effect', async t => {
  const call = await engine(t, { adventureId: 'grammys-country-apple-pie', dice: '17' }), before = await call('get_game_state')
  assert.equal(before.player.level, 1)
  const result = ok(await assess(call, planned(group('awakened_tree'), group('archmage'), group('rat'))))
  assert.deepEqual(result.groups.map(g => g.ratioStatus), ['blank_source_cell', 'cr_outside_printed_columns', 'weak_monster_guideline'])
  assert.equal(result.groups[0].ratio, null); assert.equal(result.groups[1].ratio, null)
  assert.equal(result.characterEquivalent, null); assert.equal(result.comparison, 'indeterminate')
  assert.equal(result.partySize, 1)
  assert.equal((await assess(call, planned(group('unpublished-creature')))).code, 'XGE_ENCOUNTER_MONSTER_UNKNOWN')
  for (const input of [{ ...planned(group('rat', 12)), playerLevel: 20 },
    { ...planned(group('rat', 12)), partySize: 6 }, { mode: 'planned', groups: [{ ...group('rat', 12), challengeRating: 0 }] }])
    assert.ok((await assess(call, input)).error)
  assert.deepEqual(await call('get_game_state'), before)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 17)
})
