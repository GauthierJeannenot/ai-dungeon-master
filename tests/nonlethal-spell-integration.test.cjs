const test=require('node:test'),assert=require('node:assert/strict')
const {engine,ok,adjacent}=require('./helpers/mcp-toolkit.cjs')
async function spawn(call){const state=await call('get_game_state');return ok(await call('spawn_monster',{monsterType:'goblin',cell:adjacent(state)[0]}))}
async function freeHand(call){ok(await call('equip_item',{itemId:'mace',slot:'main_hand',operation:'unequip'}))}
async function roundtrip(call){const state=await call('get_game_state');ok(await call('replace_game_state',{gameState:JSON.parse(JSON.stringify(state))}));assert.deepEqual(await call('get_game_state'),state);return state}
async function refused(call,name,input){const state=await call('get_game_state'),answer=await call(name,input);assert.ok(answer.error,JSON.stringify(answer));assert.deepEqual(await call('get_game_state'),state,'refusal precedes resource, position, condition and log changes');return answer}
async function dungeon(call,id){
 const state=await call('get_game_state'),layout=ok(await call('generate_dungeon',{seed:id,width:3,height:3,count:5})).layout
 return ok(await call('install_dungeon',{dungeonId:id,layout,entranceCell:state.player.position,
  questLink:{goal:'Retrouver la personne recherchée.',lead:'Un indice dans ce passage poursuit la recherche principale.',delivery:'clue',discoveryDc:15}}))
}
const liveWeapon=state=>state.hero.effects.find(effect=>effect.kind==='spiritual-weapon'&&effect.sourceId==='player'&&effect.data.mapId===state.currentMapId)

test('a genuine Spiritual Weapon knockout recovers on its real archived floor deadline and returns without activation, a new die or duplicated XP',async t=>{
 const call=await engine(t,{characterId:'cleric',dice:'20,1,17,4,1,19'});await freeHand(call)
 const initial=await call('get_game_state'),installed=await dungeon(call,'spell-ko-return'),target=await spawn(call)
 ok(await call('enter_combat',{combatants:['player',target.id]}))
 const cast=ok(await call('cast_spell',{spellId:'spiritual-weapon',slotLevel:2,toCell:initial.player.position,targetId:target.id,nonlethal:true}))
 const hit=cast.results.find(result=>result.targetId===target.id&&result.roll)
 assert.equal(hit.roll.rolls[0],17)
 const knocked=await roundtrip(call),body=knocked.monsters[target.id],attackId=body.knockout.attackEventId,wakeAt=body.knockout.recovery.wakeAt
 assert.equal(body.hp.current,0);assert.equal(body.isAlive,true);assert.equal(body.knockout.recovery.hours,1)
 assert.equal(body.npcLife.policy,undefined);assert.equal(body.npcLife.episode.knockoutAttackEventId,attackId)
 assert.equal(knocked.hero.corpseTimes[target.id],undefined);assert.equal(knocked.hero.pending,undefined)
 const ended=ok(await call('end_combat'))
 assert.equal(ended.xpAwarded,target.xpValue)
 assert.equal((await call('get_game_state')).monsters[target.id].xpAwarded,true)
 ok(await call('travel_to_map',{transitionId:installed.entryTransitionId}))
 const away=await roundtrip(call)
 assert.equal(away.monsters[target.id],undefined)
 const advanced=ok(await call('advance_time',{seconds:wakeAt-away.worldTimeSeconds}))
 const event=advanced.naturalRecoveries.find(event=>event.entityId===target.id)
 assert.ok(event);assert.equal(event.archived,true);assert.equal(event.attackEventId,attackId);assert.equal(event.wakeAt,wakeAt)
 const recovered=await roundtrip(call),archive=recovered.sceneMemory.floorMonsters[initial.currentMapId][target.id]
 assert.equal(recovered.currentMapId,away.currentMapId);assert.equal(recovered.monsters[target.id],undefined)
 assert.equal(archive.hp.current,1);assert.equal(archive.isAlive,true);assert.equal(archive.knockout,undefined)
 assert.ok(archive.conditions.includes('prone'));assert.equal(archive.xpAwarded,true,'the original defeat reward witness survives recovery')
 const exit=installed.exitTransitionId
 assert.ok(exit,'the installed dungeon has its genuine reciprocal transition')
 ok(await call('travel_to_map',{transitionId:exit}))
 const returned=await roundtrip(call)
 assert.equal(returned.currentMapId,initial.currentMapId);assert.deepEqual(returned.monsters[target.id],archive)
 assert.equal(ok(await call('roll_dice',{notation:'1d20'})).total,19)
})

test('the only current melee spell remains ineligible for Ready because its actual casting time is a bonus action',async t=>{
 const call=await engine(t,{characterId:'cleric',dice:'20,1,19'});await freeHand(call)
 const target=await spawn(call);ok(await call('enter_combat',{combatants:['player',target.id]}))
 const state=await call('get_game_state');assert.equal(state.currentTurn,'player')
 assert.ok(state.player.knownSpells.includes('spiritual-weapon'),'actual cleric repertoire, no spell grant')
 const answer=await refused(call,'combat_action',{action:'ready',readied:{kind:'spell',spellId:'spiritual-weapon',slotLevel:2,
  targetId:target.id,toCell:state.player.position,trigger:'Lorsque cet adversaire lève son arme devant moi.'}})
 assert.equal(answer.code,'READY_SPELL_CASTING_TIME')
 assert.equal(ok(await call('roll_dice',{notation:'1d20'})).total,19)
})

test('neither initial nor repeated nonlethal spell attacks can turn a genuinely archived actor into a remote target',async t=>{
 const call=await engine(t,{characterId:'cleric',dice:'20,1,19'});await freeHand(call)
 const initial=await call('get_game_state'),installed=await dungeon(call,'spell-ko-remote'),archived=await spawn(call)
 ok(await call('travel_to_map',{transitionId:installed.entryTransitionId}))
 let state=await call('get_game_state')
 ok(await call('cast_spell',{spellId:'spiritual-weapon',slotLevel:2,toCell:state.player.position}))
 const local=await spawn(call);ok(await call('enter_combat',{combatants:['player',local.id]}))
 state=await roundtrip(call);const effect=liveWeapon(state)
 assert.ok(effect);assert.equal(state.monsters[archived.id],undefined)
 assert.ok(state.sceneMemory.floorMonsters[initial.currentMapId][archived.id])
 await refused(call,'cast_spell',{spellId:'spiritual-weapon',slotLevel:2,toCell:state.player.position,targetId:archived.id,nonlethal:true})
 const toCell={...local.position};assert.notDeepEqual(toCell,effect.data.cell,'the rejected request contains a real weapon move')
 await refused(call,'use_subclass_feature',{featureId:'spiritual_weapon',effectId:effect.id,targetId:archived.id,toCell,nonlethal:true})
 assert.equal(ok(await call('roll_dice',{notation:'1d20'})).total,19)
})

test('an already summoned weapon can knock out a genuinely grappled actor after the real grapple action, and releasing the hold does not heal or wake it',async t=>{
 const call=await engine(t,{characterId:'cleric',dice:'20,1,17,1,17,4,2,19'});await freeHand(call)
 let state=await call('get_game_state')
 ok(await call('cast_spell',{spellId:'spiritual-weapon',slotLevel:2,toCell:state.player.position}))
 const target=await spawn(call);ok(await call('enter_combat',{combatants:['player',target.id]}))
 const grapple=ok(await call('combat_action',{action:'grapple',actorId:'player',targetId:target.id,defenseSkill:'acrobatics'}))
 assert.equal(grapple.success,true)
 state=await roundtrip(call);const hold=state.hero.effects.find(effect=>effect.kind==='grapple'&&effect.sourceId==='player'&&effect.targetIds.includes(target.id))
 assert.ok(hold);const effect=liveWeapon(state),before=state
 ok(await call('use_subclass_feature',{featureId:'spiritual_weapon',effectId:effect.id,targetId:target.id,nonlethal:true}))
 const knocked=await roundtrip(call),body=knocked.monsters[target.id]
 assert.equal(body.hp.current,0);assert.equal(body.isAlive,true);assert.equal(body.npcLife.episode.status,'stable')
 assert.ok(body.conditions.includes('grappled'));assert.ok(body.conditions.includes('unconscious'))
 assert.ok(knocked.hero.effects.some(effect=>effect.id===hold.id))
 assert.equal(knocked.hero.actionCredits,before.hero.actionCredits,'the repeat is not another action after the real grapple')
 assert.deepEqual(knocked.player.spellSlots,before.player.spellSlots,'the existing effect does not cast or debit a slot again')
 assert.equal(knocked.bonusActionUsed.player,true)
 ok(await call('combat_action',{action:'release_grapple',actorId:'player',effectId:hold.id}))
 const released=await roundtrip(call)
 assert.equal(released.monsters[target.id].hp.current,0);assert.ok(released.monsters[target.id].conditions.includes('unconscious'))
 assert.equal(released.monsters[target.id].conditions.includes('grappled'),false)
 assert.deepEqual(released.monsters[target.id].knockout,body.knockout)
 assert.equal(released.hero.actionCredits,knocked.hero.actionCredits)
 assert.equal(ok(await call('roll_dice',{notation:'1d20'})).total,19)
})

test('a genuinely created, acquired and readable Spiritual Weapon scroll knocks out once without slots or learning, while a ranged scroll refuses before consumption',async t=>{
 const call=await engine(t,{characterId:'cleric',dice:'20,1,17,4,2,17,4,19'});await freeHand(call)
 const initial=await call('get_game_state')
 for(const [itemId,spellId]of [['ko-spirit-scroll','spiritual-weapon'],['ko-ranged-scroll','guiding-bolt']]){
  ok(await call('create_spell_scroll',{itemId,spellId,name:'Parchemin préparé par le MJ',description:'Une véritable feuille enluminée porte le sort exact choisi par le MJ.',cell:initial.player.position}))
  ok(await call('pick_up_item',{itemId}));ok(await call('read_spell_scroll',{itemId}))
 }
 const target=await spawn(call),laterTarget=await spawn(call)
 ok(await call('enter_combat',{combatants:['player',target.id,laterTarget.id]}))
 const before=await roundtrip(call)
 await refused(call,'use_spell_scroll',{itemId:'ko-ranged-scroll',targetId:target.id,nonlethal:true})
 const cast=ok(await call('use_spell_scroll',{itemId:'ko-spirit-scroll',targetId:target.id,toCell:before.player.position,nonlethal:true}))
 const scrollSource=require('../mcp-server/dist/lib/srd/spell-scrolls.js').supportedScrollSpell('spiritual-weapon')
 const initialStrike=cast.results.find(result=>result.targetId===target.id&&result.roll)
 assert.ok(scrollSource);assert.ok(initialStrike)
 assert.equal(initialStrike.roll.modifier,scrollSource.attackBonus,'the initial attack uses the fixed source scroll bonus without Bless')
 const damageModifier=Math.floor((before.player.stats[before.player.spellcastingAbility]-10)/2)
 assert.equal(initialStrike.damageRoll.modifier,damageModifier,'the source attack bonus does not replace the actual spellcasting damage modifier')
 assert.equal(cast.spellScrollUse.consumed,true)
 const state=await roundtrip(call),body=state.monsters[target.id]
 assert.equal(body.hp.current,0);assert.equal(body.isAlive,true);assert.equal(body.npcLife.episode.status,'stable')
 assert.equal(body.knockout.recovery.hours,2)
 assert.equal(state.dmTools.spellScrolls['ko-spirit-scroll'].status,'consumed')
 assert.equal(state.dmTools.spellScrolls['ko-ranged-scroll'].status,'active')
 assert.equal(state.player.inventory.some(item=>item.id==='ko-spirit-scroll'),false)
 assert.ok(state.player.inventory.some(item=>item.id==='ko-ranged-scroll'))
 assert.deepEqual(state.player.spellSlots,before.player.spellSlots)
 assert.deepEqual(state.player.knownSpells,before.player.knownSpells)
 assert.deepEqual(state.player.spellbook,before.player.spellbook)
 assert.equal(state.hero.actionCredits,before.hero.actionCredits);assert.equal(state.bonusActionUsed.player,true)
 const effect=liveWeapon(state)
 assert.ok(effect);assert.equal(effect.data.scrollAttackBonus,scrollSource.attackBonus)
 assert.equal(effect.data.scrollItemId,'ko-spirit-scroll')
 assert.equal(Object.hasOwn(effect.data,'nonlethal'),false,'the true initial KO choice is not a durable weapon preference')
 await refused(call,'use_spell_scroll',{itemId:'ko-spirit-scroll',targetId:target.id,toCell:before.player.position,nonlethal:true})
 ok(await call('next_turn',{actorId:'player',skipAction:true,reason:'Le joueur attend explicitement la prochaine ouverture sans autre action.'}))
 assert.equal((await call('get_game_state')).currentTurn,laterTarget.id)
 const batch=ok(await call('run_monster_turns',{holdIds:[laterTarget.id]}))
 assert.equal(batch.currentTurn,'player');assert.equal(batch.round,state.round+1)
 const next=await roundtrip(call),persisted=liveWeapon(next)
 assert.equal(persisted.id,effect.id);assert.equal(persisted.data.scrollAttackBonus,scrollSource.attackBonus)
 assert.equal(persisted.data.scrollItemId,'ko-spirit-scroll');assert.equal(Boolean(next.bonusActionUsed.player),false)
 const repeat=ok(await call('use_subclass_feature',{featureId:'spiritual_weapon',effectId:persisted.id,targetId:laterTarget.id}))
 assert.equal(repeat.roll.modifier,scrollSource.attackBonus,'the persisted scroll source still fixes the repeated melee attack bonus')
 assert.equal(repeat.damageRoll.modifier,damageModifier)
 assert.notEqual(repeat.attackEventId,initialStrike.attackEventId,'the later strike has its own real attack witness')
 const after=await roundtrip(call)
 assert.equal(after.monsters[laterTarget.id].hp.current,0);assert.equal(after.monsters[laterTarget.id].isAlive,false,'omitting the later KO choice retains the ordinary lethal result')
 assert.equal(after.monsters[laterTarget.id].knockout,undefined)
 assert.equal(after.hero.actionCredits,next.hero.actionCredits,'the later bonus strike never adds a primary-action debit')
 assert.equal(after.bonusActionUsed.player,true)
 assert.deepEqual(after.player.spellSlots,before.player.spellSlots)
 assert.deepEqual(after.player.knownSpells,before.player.knownSpells)
 assert.equal(after.dmTools.spellScrolls['ko-spirit-scroll'].status,'consumed')
 assert.equal(after.dmTools.spellScrolls['ko-ranged-scroll'].status,'active')
 assert.equal(after.player.inventory.some(item=>item.id==='ko-spirit-scroll'),false)
 assert.deepEqual(after.monsters[target.id].knockout,body.knockout,'the first real KO and its sole recovery die are unchanged')
 assert.equal(Object.hasOwn(liveWeapon(after).data,'nonlethal'),false)
 assert.equal(ok(await call('roll_dice',{notation:'1d20'})).total,19)
})
