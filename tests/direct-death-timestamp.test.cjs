const test=require('node:test'),assert=require('node:assert/strict')
const {engine,ok,spawn}=require('./helpers/mcp-toolkit.cjs')

test('Consume Life records the actual death instant used by resurrection, including time zero',async t=>{
 const call=await engine(t,{dice:'1,1,1,1,17'}),initial=await call('get_game_state')
 const source=await spawn(call,'will_o_wisp')
 ok(await call('update_hp',{entityId:'player',delta:-initial.player.hp.current,reason:'Dégâts établis sans surplus létal.'}))
 const dying=await call('get_game_state')
 assert.equal(Boolean(dying.player.deathSaves.dead),false)
 assert.equal(dying.hero.corpseTimes.player,undefined)
 const answer=ok(await call('use_monster_power',{monsterId:source.id,powerName:'Consume Life',targetId:'player'}))
 assert.equal(answer.killed,true)
 const dead=await call('get_game_state')
 assert.equal(dead.player.deathSaves.dead,true)
 assert.equal(dead.hero.corpseTimes.player,dying.worldTimeSeconds)
 assert.equal(dead.player.hp.current,0)
 ok(await call('replace_game_state',{gameState:dead}))
 assert.equal((await call('get_game_state')).hero.corpseTimes.player,dying.worldTimeSeconds)
 assert.equal(ok(await call('roll_dice',{notation:'1d20'})).total,17)
})

test('a successful Consume Life save keeps the dying player alive and creates no death timestamp',async t=>{
 const call=await engine(t,{dice:'20,17'}),initial=await call('get_game_state')
 const source=await spawn(call,'will_o_wisp')
 ok(await call('update_hp',{entityId:'player',delta:-initial.player.hp.current,reason:'Dégâts établis sans surplus létal.'}))
 const before=await call('get_game_state')
 const answer=ok(await call('use_monster_power',{monsterId:source.id,powerName:'Consume Life',targetId:'player'}))
 assert.equal(answer.killed,false)
 const after=await call('get_game_state')
 assert.equal(Boolean(after.player.deathSaves.dead),false)
 assert.equal(after.hero.corpseTimes.player,undefined)
 assert.deepEqual(after.player.hp,before.player.hp)
 assert.equal(after.monsters[source.id].hp.current,before.monsters[source.id].hp.current)
 assert.equal(ok(await call('roll_dice',{notation:'1d20'})).total,17)
})
