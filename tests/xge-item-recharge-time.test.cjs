const test = require('node:test'), assert = require('node:assert/strict')
const { installPgMem } = require('./helpers/pg-mem.cjs'), pg = installPgMem()
const { saveSession, loadSession, deleteSession } = require('../lib/session-store.ts')
const { engine, ok, spawn } = require('./helpers/mcp-toolkit.cjs')
const { createRechargeItem, expendPearl, prepareRechargeCalendar } = require('./helpers/recharge-calendar-fixture.cjs')
const { approachManorStairs } = require('./helpers/recharge-plane-fixture.cjs')
const { prepareItemRechargeTime } = require('./helpers/item-recharge-time-fixture.cjs')
test.after(() => pg.restore())
const get = call => call('get_game_state')
const charges = async (call, id) => (await get(call)).dmTools.magicItems[id].charges
async function unchanged(call, name, input, code) {
  const before = await get(call), result = await call(name, input)
  assert.equal(result.code, code, JSON.stringify(result)); assert.deepEqual(await get(call), before)
}

test('only explicitly selected real instances replace dawn, retain source dice/caps and survive SQL without recharge or reanchoring', async t => {
  const call = await engine(t, { characterId: 'wizard', dice: '2,3,19' })
  const selected = await createRechargeItem(call, 'wand_of_magic_missiles', 'selected-time-wand', { initialCharges: 1 })
  const ordinary = await createRechargeItem(call, 'wand_of_magic_missiles', 'ordinary-dawn-wand', { initialCharges: 1 })
  const pearl = await expendPearl(call, 'selected-time-spent-pearl')
  const f = await prepareItemRechargeTime(call, [selected, pearl])
  assert.equal(await charges(call, selected), 1); assert.equal(await charges(call, ordinary), 1); assert.equal(await charges(call, pearl), 0)
  ok(await call('advance_time', { seconds: 60 }))
  assert.equal(await charges(call, selected), 4); assert.equal(await charges(call, ordinary), 1); assert.equal(await charges(call, pearl), 1)
  const at = await get(call)
  ok(await call('advance_time', { seconds: 86400 - at.worldTimeSeconds % 86400 }))
  assert.equal(await charges(call, selected), 4); assert.equal(await charges(call, ordinary), 5)
  const saved = await get(call), sid = 'item-time-sql-' + process.pid
  await saveSession(sid, { gameState: saved, history: [], adventureId: saved.adventureId, characterId: saved.characterId })
  t.after(() => deleteSession(sid))
  const fresh = await engine(t, { characterId: 'wizard', dice: '19' })
  ok(await fresh('replace_game_state', { gameState: (await loadSession(sid)).gameState }))
  assert.deepEqual(await get(fresh), saved)
  assert.equal(ok(await fresh('adopt_xge_item_recharge_time', f.input)).replayed, true)
  await unchanged(fresh, 'adopt_xge_item_recharge_time', { ...f.input, eventId: 'attempt-new-phase' }, 'XGE_ITEM_RECHARGE_INSTANCE_IMMUTABLE')
  const drift = structuredClone(saved); drift.dmTools.itemRechargeCalendar.choices[f.input.eventId].firstAt++
  await unchanged(fresh, 'replace_game_state', { gameState: drift }, 'XGE_ITEM_RECHARGE_CALENDAR_STATE_MISMATCH')
  assert.deepEqual(await get(fresh), saved)
  assert.equal(ok(await fresh('roll_dice', { notation: '1d20' })).total, 19)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

test('carried and ground selected instances keep actual map schedules across real stairs and return without missed-boundary credit', async t => {
  const call = await engine(t, { dice: '2,3,4,1,19' })
  await approachManorStairs(call)
  const ground = await createRechargeItem(call, 'wand_of_magic_missiles', 'item-time-stays-temple', { initialCharges: 1, pickup: false })
  const carried = await createRechargeItem(call, 'wand_of_magic_missiles', 'item-time-leaves-temple', { initialCharges: 1 })
  const f = await prepareItemRechargeTime(call, [ground, carried])
  const before = await get(call)
  assert.equal(ok(await call('travel_to_map', { transitionId: 'descend_manor' })).travelSeconds, 0)
  assert.equal((await get(call)).worldTimeSeconds, before.worldTimeSeconds)
  ok(await call('advance_time', { seconds: 60 }))
  assert.equal(await charges(call, ground), 4); assert.equal(await charges(call, carried), 1)
  const away = await get(call)
  ok(await call('advance_time', { seconds: 86400 - away.worldTimeSeconds % 86400 }))
  assert.equal(await charges(call, ground), 4); assert.equal(await charges(call, carried), 5)
  const instant = (await get(call)).worldTimeSeconds
  ok(await call('travel_to_map', { transitionId: 'ascend_manor' }))
  assert.equal((await get(call)).worldTimeSeconds, instant)
  assert.equal(await charges(call, carried), 5, 'return does not earn the occurrence missed in another map')
  assert.equal(ok(await call('adopt_xge_item_recharge_time', f.input)).replayed, true)
  ok(await call('advance_time', { seconds: f.result.itemTimes[0].firstAt + 86400 - instant }))
  assert.equal(await charges(call, ground), 7); assert.equal(await charges(call, carried), 7)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

test('local dawn-world choices reject overlap in both dawnless procedures and coexist with the real policy on another map', async t => {
  const call = await engine(t, { dice: '2,3,19' })
  await approachManorStairs(call)
  const id = await createRechargeItem(call, 'wand_of_magic_missiles', 'selected-then-dawnless-traveller', { initialCharges: 1 })
  const f = await prepareItemRechargeTime(call, [id])
  await unchanged(call, 'adopt_xge_recharge_calendar', { eventId: 'overlap-original-adoption', mapId: 'temple',
    referenceId: f.input.referenceId, actualDawnlessMapConfirmed: true }, 'XGE_RECHARGE_MAP_POLICY_CONFLICT')
  ok(await call('travel_to_map', { transitionId: 'descend_manor' }))
  const old = await prepareRechargeCalendar(call, { firstAfterSeconds: 90 })
  const savedOriginal = (await get(call)).dmTools.rechargeCalendar.adoption
  await unchanged(call, 'adopt_xge_item_recharge_time', { ...f.input, eventId: 'overlap-item-time', mapId: 'cellar',
    referenceId: old.input.referenceId }, 'XGE_RECHARGE_MAP_POLICY_CONFLICT')
  ok(await call('advance_time', { seconds: 90 }))
  assert.equal(await charges(call, id), 4, 'the actual dawnless cycle on the other map remains authoritative there')
  ok(await call('travel_to_map', { transitionId: 'ascend_manor' }))
  const atReturn = await get(call)
  await unchanged(call, 'bind_xge_recharge_plane_map', { eventId: 'overlap-plane-binding', originMapId: 'cellar', mapId: 'temple',
    planeId: 'same-source-plane', planeName: 'Plan choisi', factId: 'no-new-qualification-before-conflict',
    actualSameDawnlessPlaneConfirmed: true }, 'XGE_RECHARGE_MAP_POLICY_CONFLICT')
  assert.deepEqual((await get(call)).dmTools.rechargeCalendar.adoption, savedOriginal)
  assert.equal(await charges(call, id), 4)
  assert.deepEqual(await get(call), atReturn)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 3)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

test('invalid instance choices refuse atomically and the actual initiative clock crosses the selected source boundary', async t => {
  const call = await engine(t, { dice: '20,1,2,19' })
  const id = await createRechargeItem(call, 'wand_of_magic_missiles', 'round-alternate-time-wand', { initialCharges: 1 })
  const potion = await createRechargeItem(call, 'potion_of_healing', 'not-a-recharge-item')
  const f = await prepareItemRechargeTime(call, [id], { firstAfterSeconds: 3, adopt: false })
  await unchanged(call, 'adopt_xge_item_recharge_time', { ...f.input, itemIds: [potion] }, 'XGE_ITEM_RECHARGE_INSTANCE_REQUIRED')
  await unchanged(call, 'adopt_xge_item_recharge_time', { ...f.input, itemIds: ['future-instance'] }, 'XGE_ITEM_RECHARGE_INSTANCE_REQUIRED')
  await unchanged(call, 'adopt_xge_item_recharge_time', { ...f.input, mapId: 'cellar' }, 'XGE_ITEM_RECHARGE_MAP_REQUIRED')
  ok(await call('adopt_xge_item_recharge_time', f.input))
  const enemy = await spawn(call)
  ok(await call('enter_combat', { combatants: ['player', enemy.id] }))
  ok(await call('next_turn', { actorId: 'player', skipAction: true }))
  assert.equal(await charges(call, id), 1)
  ok(await call('next_turn', { actorId: enemy.id, skipAction: true }))
  const state = await get(call)
  assert.equal(state.worldTimeSeconds, 6); assert.equal(await charges(call, id), 4)
  assert.equal(state.dmTools.rechargeCalendar, undefined)
  assert.equal(state.dmTools.itemRechargeCalendar.evaluatedThrough, 6)
  ok(await call('replace_game_state', { gameState: state }))
  assert.deepEqual(await get(call), state)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})
