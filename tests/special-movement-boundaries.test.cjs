const test=require('node:test'),assert=require('node:assert/strict')
const{setup,water,climb,surface,swim,climbMove,gs,ok,refused,source}=require('./helpers/special-movement-fixture.cjs')
const{assertGameTimeAdvance}=require('../mcp-server/dist/mcp-server/time-preflight.js')
const{locomotionPhysicalIssue}=require('../mcp-server/dist/lib/locomotion-geometry.js')
for(const mode of ['swim','climb'])test(`a body in actual ${mode} cannot begin an unperformed rest or gain an uninterrupted rest benefit`,async t=>{
 const f=await setup(t,{dice:'17'})
 if(mode==='swim'){await water(f);ok(await f.call('move_by_climbing_or_swimming',swim({path:[{x:1,y:2,zFeet:0},{x:2,y:2,zFeet:0}]})))}
 else{await climb(f);ok(await f.call('move_by_climbing_or_swimming',climbMove({path:[{x:1,y:2,zFeet:0},{x:1,y:2,zFeet:5}]})))}
 await refused(f,'begin_rest',{restId:'unperformed-unsupported-rest',kind:'short'},'REST_ACTUAL_SUPPORT_REQUIRED')
 await refused(f,'take_rest',{kind:'short'},'REST_ACTUAL_SUPPORT_REQUIRED')
 assert.equal(gs.getState().dmTools?.rests?.active,undefined);assert.equal(ok(await f.call('roll_dice',{notation:'1d20'})).total,17)
})
for(const mode of ['swim','climb'])test(`actual ${mode} during a recorded rest prevents credit and completion before clock, HP or resources change`,async t=>{
 const f=await setup(t,{dice:'17'})
 if(mode==='swim')await water(f);else await climb(f)
 ok(await f.call('begin_rest',{restId:'real-ground-rest',kind:'short'}))
 if(mode==='swim')ok(await f.call('move_by_climbing_or_swimming',swim({path:[{x:1,y:2,zFeet:0},{x:2,y:2,zFeet:0}]})))
 else ok(await f.call('move_by_climbing_or_swimming',climbMove({path:[{x:1,y:2,zFeet:0},{x:1,y:2,zFeet:5}]})))
 assert.equal(gs.getState().dmTools.rests.active.segments.at(-1).activity,'strenuous')
 await refused(f,'advance_rest',{restId:'real-ground-rest',eventId:'unsupported-hour',seconds:3600,activity:'light',reason:source},'REST_ACTUAL_SUPPORT_REQUIRED')
 await refused(f,'finish_rest',{restId:'real-ground-rest',hitDice:1},'REST_ACTUAL_SUPPORT_REQUIRED')
 assert.equal(ok(await f.call('roll_dice',{notation:'1d20'})).total,17)
})
test('lost real climbing grip blocks positive time and another creature action before its die, but its exact completed fall remains resolvable',async t=>{
 const f=await setup(t,{dice:'4,17'});await climb(f);await surface(f,'real-physical-outcome-floor')
 ok(await f.call('observe_standing_surface',{eventId:'real-floor-before-climb',entityId:'player',surfaceId:'real-physical-outcome-floor',actualCurrentSupportConfirmed:true,source}))
 ok(await f.call('move_by_climbing_or_swimming',climbMove()))
 ok(await f.call('apply_condition',{entityId:'player',condition:'unconscious'}));assert.equal(locomotionPhysicalIssue(gs.getState()).entityId,'player')
 const before=structuredClone(gs.getState())
 assert.throws(()=>assertGameTimeAdvance(1),error=>error.code==='LOCOMOTION_PHYSICAL_OUTCOME_REQUIRED');assert.deepEqual(gs.getState(),before)
 await refused(f,'roll_ability_check',{entityId:'target',ability:'str',dc:10},'LOCOMOTION_PHYSICAL_OUTCOME_REQUIRED')
 const result=ok(await f.call('complete_locomotion_fall',{eventId:'one-real-physical-outcome',entityId:'player',landingSurfaceId:'real-physical-outcome-floor',reason:source}))
 assert.equal(result.distanceFeet,10);assert.equal(result.roll.total,4);assert.equal(locomotionPhysicalIssue(gs.getState()),null)
 assert.doesNotThrow(()=>assertGameTimeAdvance(1));assert.equal(gs.getState().worldTimeSeconds,before.worldTimeSeconds)
 assert.equal(ok(await f.call('roll_dice',{notation:'1d20'})).total,17)
})
