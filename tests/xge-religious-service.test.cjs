test('separate actual temple sites share a global favor cap, overflow never backfills after a true spend and SQL preserves history', async t => {
  const call = await engine(t, { characterId: 'wizard', dice: '20,99,20,99,19' }), first = await prepareService(call)
  ok(await call('start_xge_religious_service', first.input)); await completeServiceWork(call, first)
  const r1 = ok(await call('resolve_xge_religious_service', first.resolve))
  assert.equal(r1.week.resolution.outcome.printedFavors, 2); assert.equal(r1.week.resolution.outcome.earned, 1)
  const from = await get(call), cell = adjacent(from).find(c => ![...Object.values(from.npcs ?? {}), ...Object.values(from.monsters)].some(a => a.position.x === c.x && a.position.y === c.y))
  assert.ok(cell); ok(await call('move_token', { tokenId: 'player', toCell: cell }))
  await nextServiceDate(call)
  const second = await prepareService(call, { weekId: 'other-temple-week', templeId: 'other-real-temple', representativeId: 'other-temple-representative' })
  ok(await call('start_xge_religious_service', second.input)); await completeServiceWork(call, second)
  const r2 = ok(await call('resolve_xge_religious_service', second.resolve))
  assert.equal(r2.week.resolution.outcome.printedFavors, 2); assert.equal(r2.week.resolution.outcome.earned, 0)
  assert.equal(r2.unusedFavors.length, 1); assert.equal(r2.unusedFavors[0].templeId, first.input.templeId)
  const oldFavor = r2.unusedFavors[0].id, badSpend = await second.acceptedFavor(oldFavor)
  await refused(call, 'spend_xge_religious_favor', badSpend, 'XGE_SERVICE_TEMPLE_REQUIRED')
  ok(await call('move_token', { tokenId: 'player', toCell: first.site.cell }))
  const spend = await first.acceptedFavor(oldFavor)
  ok(await call('spend_xge_religious_favor', spend))
  assert.deepEqual(ok(await call('inspect_xge_religious_service')).unusedFavors, [])
  const closed = await get(call), resumed = await fromSql(t, closed, '17', 'global-cap')
  assert.equal(latest(await get(resumed)).resolution.outcome.earned, 0)
  assert.deepEqual(ok(await resumed('inspect_xge_religious_service')).unusedFavors, [])
  assert.equal(await marker(call), 19); assert.equal(await marker(resumed), 17)
})
