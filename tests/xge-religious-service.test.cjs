async function fromSql(t, state, dice, suffix) {
  const session = 'actual-service-' + suffix + '-' + process.pid, { adventureId, characterId } = state
  t.after(() => deleteSession(session))
  await saveSession(session, { gameState: state, history: [], adventureId, characterId })
  const resumed = await engine(t, { adventureId, characterId, dice })
  ok(await resumed('replace_game_state', { gameState: (await loadSession(session)).gameState }))
  return resumed
}
test('actual POST temple service earns one real promise, keeps secret-table example documentary, and spends once after SQL with actual acceptance', async t => {
  const call = await engine(t, { characterId: 'wizard', dice: '7,10,6,19' }), f = await prepareService(call)
  const tools = (await call.client.listTools()).tools
  for (const verb of ['start', 'work', 'resolve', 'abandon', 'inspect']) assert.ok(tools.some(tool => tool.name === verb + '_xge_religious_service'))
  assert.ok(tools.some(tool => tool.name === 'spend_xge_religious_favor'))
  const source = ok(await call('inspect_xge_religious_service')).source
  assert.equal(source.sha256, '519584ec7fc7da6fea056c182a22254bc807db5d077c2fc205801bd872d761bf')
  assert.equal(source.startLine, 2333); assert.equal(source.endLine, 2363); assert.equal(source.foundationLine, 1987)
  assert.ok(ok(await call('get_rules_support', { domain: 'xge_religious_service' })).tools.includes('spend_xge_religious_favor'))
  await refused(call, 'start_xge_religious_service', { ...f.input, representativeId: 'nonexistent-clergy' }, 'XGE_SERVICE_REPRESENTATIVE_REQUIRED')
  const initial = await get(call), start = { name: 'start_xge_religious_service', input: f.input }, work = { name: 'work_xge_religious_service', input: f.work(0) }
  const { result, seen } = await play(t, call, [start, params => { assert.equal(ok(lastResult(params)).paidCp, 0); return work },
    params => { assert.equal(ok(lastResult(params)).seconds, 28800); return 'Tu consacres une journée réelle au service de ce temple.' }], 'Je sers ce temple pendant cette journée.')
  assert.deepEqual(seen, [start, work]); assert.equal(result.newGameState.worldTimeSeconds, initial.worldTimeSeconds + 28800)
  assert.equal(copperValue(result.newGameState.dmTools.wallet), copperValue(initial.dmTools.wallet))
  await refused(call, 'work_xge_religious_service', f.work(1), 'XGE_SERVICE_WORKDAY_REQUIRED')
  await refused(call, 'resolve_xge_religious_service', f.resolve, 'XGE_SERVICE_RESOLUTION_REQUIRED')
  await completeServiceWork(call, f, { start: 1, gap: true })
  const resolution = ok(await call('resolve_xge_religious_service', f.resolve)).week.resolution
  assert.equal(resolution.check.ability, 'int'); assert.equal(resolution.check.roll.total, 11)
  assert.equal(resolution.check.dc, undefined); assert.equal(resolution.check.success, undefined)
  assert.equal(resolution.outcome.printedFavors, 1); assert.equal(resolution.outcome.earned, 1); assert.equal(resolution.outcome.cap, 1)
  assert.equal(resolution.outcome.example.roll.total, 6); assert.match(resolution.outcome.example.text, /fiend worshiper/)
  await refused(call, 'abandon_xge_religious_service', { eventId: 'no-erasing-earned-favor', weekId: f.input.eventId, abandonUnfinishedWeekConfirmed: true }, 'XGE_SERVICE_ABANDONMENT_UNAVAILABLE')
  const closed = await get(call)
  for (const key of ['player', 'npcs', 'monsters', 'phase', 'worldFacts', 'revealedClues', 'quests']) assert.deepEqual(closed[key], initial[key])
  assert.equal(await marker(call), 19)
  const resumed = await fromSql(t, closed, '17', 'favor')
  const corrupt = structuredClone(closed); latest(corrupt).resolution.outcome.earned++
  await refused(resumed, 'replace_game_state', { gameState: corrupt }, 'XGE_SERVICE_STATE_MISMATCH')
  for (const [name, input] of [['start_xge_religious_service', f.input], ['work_xge_religious_service', f.work(0)], ['resolve_xge_religious_service', f.resolve]])
    assert.equal(ok(await resumed(name, input)).replayed, true)
  const originalUnused = ok(await resumed('inspect_xge_religious_service')).unusedFavors
  const restoredFixture = { ...f, acceptedFavor: (await prepareService(resumed, { weekId: 'unused-new-week-qualification' })).acceptedFavor }
  const spend = await restoredFixture.acceptedFavor(originalUnused[0].id)
  await refused(resumed, 'spend_xge_religious_favor', { ...spend, acceptanceFactId: spend.requestFactId }, 'XGE_SERVICE_ACCEPTANCE_REQUIRED')
  await refused(resumed, 'spend_xge_religious_favor', { ...spend, favorId: 'invented-favor' }, 'XGE_SERVICE_UNUSED_FAVOR_REQUIRED')
  await refused(resumed, 'spend_xge_religious_favor', { ...spend, purpose: 'cleric_spell_service' }, 'MCP_INPUT_INVALID')
  const beforeSpend = await get(resumed), used = ok(await resumed('spend_xge_religious_favor', spend))
  assert.equal(used.grantedBenefit, false); assert.deepEqual(used.unusedFavors, [])
  const afterSpend = await get(resumed)
  for (const key of ['player', 'npcs', 'monsters', 'worldFacts', 'revealedClues', 'quests', 'worldTimeSeconds']) assert.deepEqual(afterSpend[key], beforeSpend[key])
  assert.equal(ok(await resumed('spend_xge_religious_favor', spend)).replayed, true)
  await refused(resumed, 'spend_xge_religious_favor', { ...spend, eventId: 'no-second-consumption' }, 'XGE_SERVICE_UNUSED_FAVOR_REQUIRED')
  const after = await get(resumed), again = await fromSql(t, after, '16', 'spent')
  assert.equal(ok(await again('spend_xge_religious_favor', spend)).replayed, true); assert.deepEqual(ok(await again('inspect_xge_religious_service')).unusedFavors, [])
  assert.equal(await marker(resumed), 17); assert.equal(await marker(again), 16)
})
