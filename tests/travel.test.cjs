const test=require('node:test'),assert=require('node:assert/strict')
const {engine,ok,replace,spawn,addSupply}=require('./helpers/mcp-toolkit.cjs')
const {TRAVEL_PACE_FEET,TravelStateSchema}=require('../mcp-server/dist/lib/travel-state.js')
const source='Route et distance effectivement établies par le MJ sur sa carte, sans destination déduite du message.'
const nutrition={eventId:'food-history',operation:'begin',standardNeedsConfirmed:true,hotWeather:false,source,foodDebtHalfDays:0,priorDeprivation:'none'}
const beginning=extra=>({eventId:'walking-history',dayStartsAt:0,knownWalkingSeconds:0,historyKnown:true,source,...extra})
const route=extra=>({journeyId:'actual-route',origin:'Origine établie sur la carte du MJ',destination:'Destination établie sur cette même carte',distanceFeet:528000,terrain:'normal',actualRouteConfirmed:true,source,...extra})
const step=(eventId,extra={})=>({eventId,journeyId:'actual-route',pace:'normal',scale:'hour',durationSeconds:3600,stopAtDestination:false,activity:'watch',rank:'front',openTerrain:true,source,...extra})
async function start(call,{begin={},routeInput={}}={}){ok(await call('begin_nutrition_tracking',nutrition));ok(await call('begin_travel_tracking',beginning(begin)));ok(await call('create_travel_route',route(routeInput)))}
async function refused(call,name,input,code){const before=await call('get_game_state'),result=await call(name,input);assert.equal(result.code,code,JSON.stringify(result));assert.deepEqual(await call('get_game_state'),before)}
async function hydrate(call){const state=await call('get_game_state');ok(await call('replace_game_state',{gameState:state}));assert.deepEqual(await call('get_game_state'),state);return state}
async function eightHours(call,eventId='actual-eight'){return ok(await call('advance_travel',step(eventId,{scale:'day',durationSeconds:28800})))}

