test.after(() => pg.restore())

test('exact measured hedge is two real cells, blocks movement/placement and never treats proximity as touch', async t => {
  const call = await engine(t, { dice: '17' }), f = await prepareRazorvine(call, { publish: false })
  await refused(call, 'record_razorvine', { ...f.qualification, secondCell: f.anchor }, 'RAZORVINE_FOOTPRINT_REQUIRED')
  const created = ok(await call('record_razorvine', f.qualification)), hedge = created.hedge
  assert.deepEqual(created.dimensionsFeet, { width: 10, thickness: 5, height: 10 })
  assert.equal(hedge.ac, 11)
  assert.deepEqual(hedge.hp, { current: 25, max: 25 })
  assert.deepEqual(hedge.damageProfile.immunities, ['bludgeoning', 'piercing', 'psychic'])
  const state = await call('get_game_state'), nav = grid(state)
  assert.equal(nav.free(f.anchor, false), false)
  assert.equal(nav.free(f.face, false), false)
  assert.equal(nav.free(f.neighbor, false), true)
  const obstacle = spellAreaBlockers(state).find(blocker => blocker.key === 'razorvine:' + f.hedgeId)
  assert.equal(obstacle.boxes.length, 2)
  assert.equal(obstacle.bottom, 0)
  assert.equal(obstacle.top, 10)
  await refused(call, 'spawn_monster', { monsterType: 'skeleton', cell: f.face }, 'RAZORVINE_VOLUME_BLOCKED')
  for (const toCell of [f.face, f.anchor])
    await refused(call, 'move_token', { tokenId: 'player', toCell }, 'DESTINATION_BLOCKED')
  const moved = ok(await call('move_token', { tokenId: 'player', toCell: f.neighbor }))
  assert.deepEqual(moved.finalPosition, f.neighbor)
  assert.deepEqual(ok(await call('inspect_razorvine')).contacts, [])
  await refused(call, 'resolve_razorvine_contact', touch(f, 'no-initiative-contact'), 'RAZORVINE_TURNS_REQUIRED')
  const chest = ok(await call('create_scene_object', { objectId: 'actual-hedge-oil-chest', name: 'Coffre', description: 'La vraie fiole d’huile est dans ce coffre.',
    cell: f.neighbor, kind: 'container', material: 'wood', size: 'small', resilience: 'resilient', contents: ['oil_flask'] }))
  const oil = ok(await call('interact_object', { objectId: chest.object.id, action: 'open' })).releasedItems[0]
  assert.equal(oil.equipmentId, 'oil_flask')
  ok(await call('pick_up_item', { itemId: oil.id }))
  ok(await call('equip_item', { itemId: 'longsword', operation: 'unequip', slot: 'main_hand' }))
  await refused(call, 'use_oil_flask', { useId: 'no-unsupported-oil-face', itemId: oil.id, targetKind: 'object',
    targetId: f.hedgeId, mode: 'throw' }, 'RAZORVINE_OIL_FACE_UNREPRESENTED')
  assert.equal(await marker(call), 17)
})

test('exact face contact rolls a true Dexterity save and one failure die, with one check per global turn', async t => {
  const call = await engine(t, { dice: '20,1,7,19,17' }), f = await prepareRazorvine(call)
  const started = ok(await call('enter_combat', f.approach))
  assert.deepEqual(started.initiativeOrder, ['player'])
  assert.deepEqual(started.hazardPreparation.hazardCell, f.face)
  assert.deepEqual(ok(await call('inspect_razorvine')).contacts, [])
  await refused(call, 'resolve_razorvine_contact', { ...touch(f, 'bad-face'), faceCell: f.anchor }, 'RAZORVINE_DIRECT_FACE_REQUIRED')
  const before = await call('get_game_state'), failed = ok(await call('resolve_razorvine_contact', touch(f, 'first-thorn-touch')))
  assert.deepEqual(failed.save.roll.rolls, [1])
  assert.equal(failed.save.ability, 'dex')
  assert.equal(failed.save.dc, 10)
  assert.equal(failed.save.success, false)
  assert.equal(failed.damageRoll.total, 7)
  assert.equal(failed.damageResolution.damageType, 'slashing')
  const after = await call('get_game_state')
  assert.equal(after.player.hp.current, before.player.hp.current - 7)
  assert.deepEqual(after.player.position, before.player.position)
  assert.deepEqual(after.movementUsed, before.movementUsed)
  assert.deepEqual(after.actionUsed, before.actionUsed)
  assert.equal(ok(await call('resolve_razorvine_contact', touch(f, 'another-touch-same-turn'))).alreadyCheckedThisTurn, true)
  assert.deepEqual(await call('get_game_state'), after)
  ok(await call('next_turn', { actorId: 'player', skipAction: true, reason: 'Le joueur termine explicitement son vrai tour.' }))
  const success = ok(await call('resolve_razorvine_contact', touch(f, 'next-real-turn-touch')))
  assert.deepEqual(success.save.roll.rolls, [19])
  assert.equal(success.damageRoll, undefined)
  assert.equal(success.damageDealt, 0)
  assert.equal(await marker(call), 17)
})

test('direct thorn save retains the original natural die and its true face through SQL and Inspiration', async t => {
  const call = await engine(t, { characterId: 'bard', dice: '20,1,1' }), f = await prepareRazorvine(call)
  const body = await spawn(call, 'skeleton', f.neighbor)
  await f.stand(body.id)
  ok(await call('equip_item', { itemId: 'rapier', operation: 'unequip', slot: 'main_hand' }))
  ok(await call('equip_item', { itemId: 'dagger', operation: 'equip', slot: 'main_hand' }))
  ok(await call('use_subclass_feature', { featureId: 'bardic_inspiration', targetId: body.id }))
  ok(await call('enter_combat', { combatants: ['player', body.id] }))
  await refused(call, 'interact_object', { eventId: 'no-unrepresented-thrown-face', objectId: f.hedgeId,
    action: 'attack', weaponId: 'dagger', attackMode: 'thrown', targetCell: f.anchor }, 'RAZORVINE_RANGED_FAR_FACE')
  const input = touch(f, 'held-thorn-save', body.id)
  const held = ok(await call('resolve_razorvine_contact', input)).pendingReaction
  assert.equal(held.command.type, 'save')
  assert.deepEqual(held.roll.rolls, [1])
  assert.ok(held.options.includes('bardic_inspiration'))
  const snapshot = await call('get_game_state'), fresh = await restoreRazorvine(t, snapshot, '3,8,17')
  const tampered = structuredClone(snapshot)
  tampered.hero.pending.roll.total = 100
  await refused(fresh, 'replace_game_state', { gameState: tampered }, 'RAZORVINE_STATE_MISMATCH')
  assert.equal(ok(await fresh('resolve_razorvine_contact', input)).alreadyPending, true)
  const resolved = ok(await fresh('resolve_reaction', { pendingId: held.id, choice: 'bardic_inspiration' }))
  assert.deepEqual(resolved.save.roll.rolls, [1])
  assert.equal(resolved.save.roll.total, held.roll.total + 3)
  assert.equal(resolved.damageRoll.total, 8)
  const after = await fresh('get_game_state')
  assert.equal(after.monsters[body.id].hp.current, snapshot.monsters[body.id].hp.current - 8)
  assert.equal(ok(await fresh('resolve_razorvine_contact', input)).replayed, true)
  assert.deepEqual(await fresh('get_game_state'), after)
  assert.equal(await marker(fresh), 17)
})

test('a held mace reaches the explicitly selected near hedge face but source bludgeoning immunity preserves HP', async t => {
  const call = await engine(t, { characterId: 'cleric', dice: '20,14,6,17' }), f = await prepareRazorvine(call)
  ok(await call('enter_combat', f.approach))
  const attack = { eventId: 'actual-mace-near-face', objectId: f.hedgeId, action: 'attack', weaponId: 'mace' }
  await refused(call, 'interact_object', attack, 'RAZORVINE_ATTACK_FACE_REQUIRED')
  const result = ok(await call('interact_object', { ...attack, targetCell: f.face }))
  assert.equal(result.hit, true)
  assert.equal(result.targetAC, 11)
  assert.equal(result.damageDealt, 0)
  assert.ok(result.damageResolution.components[0].immune)
  assert.equal(result.object.hp.current, 25)
  assert.deepEqual(result.targetCell, f.face)
  assert.equal(await marker(call), 17)
})

test('real slashing attacks destroy one hedge and reopen both exact footprint cells after SQL restore', async t => {
  const call = await engine(t, { dice: '20,20,8,8,18,8' }), f = await prepareRazorvine(call)
  ok(await call('record_scene_fact', { cell: f.anchor, replaceFactId: f.qualification.factId,
    description: 'Le fait public est précisé sans remplacer cette même haie réellement enracinée.' }))
  ok(await call('enter_combat', f.approach))
  const attack = { objectId: f.hedgeId, action: 'attack', weaponId: 'longsword', targetCell: f.face }
  const one = ok(await call('interact_object', { ...attack, eventId: 'first-cut-actual-hedge' }))
  assert.ok(one.damageDealt > 0)
  assert.equal(one.object.state, 'intact')
  const two = ok(await call('interact_object', { ...attack, eventId: 'second-cut-actual-hedge' }))
  assert.equal(two.object.hp.current, 0)
  assert.equal(two.object.state, 'destroyed')
  const after = await call('get_game_state'), restored = await restoreRazorvine(t, after, '17'), nav = grid(after)
  assert.equal(nav.free(f.anchor), true)
  assert.equal(nav.free(f.face), true)
  assert.ok(!spellAreaBlockers(after).some(blocker => blocker.key === 'razorvine:' + f.hedgeId))
  await refused(restored, 'resolve_razorvine_contact', touch(f, 'destroyed-vine-no-touch'), 'RAZORVINE_DIRECT_FACE_REQUIRED')
  const move = ok(await restored('move_token', { tokenId: 'player', toCell: f.anchor }))
  assert.deepEqual(move.path, [f.start, f.face, f.anchor])
  assert.equal(await marker(restored), 17)
})
