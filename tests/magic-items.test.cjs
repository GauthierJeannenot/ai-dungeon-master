async function item(call,templateId,id=templateId,extra={}){
  const state=await call('get_game_state')
  const input={itemId:id,templateId,name:'Un objet mystérieux',description:'Un objet au dessin inhabituel.',cell:state.player.position,...extra}
  ok(await call('create_magic_item',input));ok(await call('pick_up_item',{itemId:id}));return input
}
async function hold(call,id){
  const state=await call('get_game_state'),held=state.dmTools.loadout?.mainHandId??state.player.inventory.find(i=>i.type==='weapon')?.id
  if(held)ok(await call('equip_item',{itemId:held,slot:'main_hand',operation:'unequip'}))
  return ok(await call('equip_item',{itemId:id,slot:'main_hand',operation:'equip'}))
}
async function farMonster(call){
  const state=await call('get_game_state'),nav=grid(state),map=require('../mcp-server/dist/lib/adventure-map.js').getMapSpec(state.currentMapId,state)
  for(let y=0;y<map.grid.rows;y++)for(let x=0;x<map.grid.cols;x++)if(Math.max(Math.abs(x-state.player.position.x),Math.abs(y-state.player.position.y))>=5&&nav.free({x,y})&&playerSeesCell(state,{x,y}))return spawn(call,'goblin',{x,y})
  assert.fail('fixture needs a visible target outside the Fireball radius around the caster')
}

test('catalog numerical sources retain primary PDF provenance and original passage hashes',()=>{
  const {MAGIC_ITEMS,MAGIC_ITEM_IDS}=require('../mcp-server/dist/lib/srd/magic-items.js'),source=require('../lib/srd/magic-items-sources.json')
  assert.equal(MAGIC_ITEM_IDS.length,13)
  for(const spec of Object.values(MAGIC_ITEMS)){
    const record=source.records[spec.sourceName];assert.ok(record);assert.equal(record.page,spec.page)
    assert.equal(record.sha256,crypto.createHash('sha256').update(record.text).digest('hex'))
  }
})

