const test = require('node:test')
const assert = require('node:assert/strict')
const { engine, ok, replace, adjacent, spawn, battle, grid } = require('./helpers/mcp-toolkit.cjs')

test('a grapple requires a real free hand, replaces one attack, and a kick can use the remaining attack', async t => {
  const call = await engine(t, { dice: '20,1,17' })
  const enemy = await spawn(call)
  await battle(call, [enemy.id])
  const blocked = await call('combat_action', { action: 'grapple', targetId: enemy.id, defenseSkill: 'acrobatics' })
  assert.equal(blocked.code, 'FREE_HAND_REQUIRED')
  await replace(call, state => { state.phase = 'exploration'; state.currentTurn = null; state.initiativeOrder = [] })
  ok(await call('equip_item', { itemId: 'longsword', operation: 'unequip', slot: 'main_hand' }))
  await battle(call, [enemy.id])
  const grapple = ok(await call('combat_action', { action: 'grapple', targetId: enemy.id, defenseSkill: 'acrobatics' }))
  assert.equal(grapple.success, true)
  let state = await call('get_game_state')
  assert.equal(state.hero.attackAction.remaining, 1)
  assert.ok(state.monsters[enemy.id].conditions.includes('grappled'))
  assert.equal((await call('move_token', { tokenId: enemy.id, toCell: state.player.position })).code, 'ACTOR_IMMOBILE')
  const strike = ok(await call('resolve_player_attack', { targetId: enemy.id, weaponOrSpell: 'unarmed' }))
  assert.equal(strike.hit, true)
  state = await call('get_game_state')
  assert.equal(state.hero.attackAction.remaining, 0)
  const effect = state.hero.effects.find(effect => effect.kind === 'grapple')
  ok(await call('combat_action', { action: 'release_grapple', effectId: effect.id }))
  assert.ok(!(await call('get_game_state')).monsters[enemy.id].conditions.includes('grappled'))
})

test('a tied shove preserves the prior position and consumes only one attack; missing choices roll nothing', async t => {
  const call = await engine(t, { dice: '10,15,19' })
  const enemy = await spawn(call)
  await battle(call, [enemy.id])
  const before = await call('get_game_state')
  assert.equal((await call('combat_action', { action: 'shove', targetId: enemy.id })).code, 'SHOVE_CHOICE_REQUIRED')
  assert.deepEqual(await call('get_game_state'), before)
  // Fighter Athletics +7 versus goblin Acrobatics +2: 10+7 == 15+2.
  const answer = ok(await call('combat_action', { action: 'shove', targetId: enemy.id, shove: 'prone', defenseSkill: 'acrobatics' }))
  assert.equal(answer.success, false)
  const after = await call('get_game_state')
  assert.deepEqual(after.monsters[enemy.id].position, before.monsters[enemy.id].position)
  assert.ok(!after.monsters[enemy.id].conditions.includes('prone'))
  assert.equal(after.hero.attackAction.remaining, 1)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

test('Help grants one actual advantage to the selected ally attack and is consumed even on a miss', async t => {
  const call = await engine(t, { dice: '1,2' })
  const enemy = await spawn(call), ally = await spawn(call, 'knight')
  await replace(call, state => { state.monsters[ally.id].hostile = false; state.monsters[enemy.id].ac = 99 })
  await battle(call, [ally.id, enemy.id])
  ok(await call('combat_action', { action: 'help', helpKind: 'attack', beneficiaryId: ally.id, targetId: enemy.id }))
  ok(await call('next_turn', { actorId: 'player' }))
  const attack = ok(await call('resolve_attack', { attackerId: ally.id, targetId: enemy.id, weaponOrSpell: 'Greatsword' }))
  assert.equal(attack.hit, false)
  assert.match(attack.attackRoll.detail, /ADV/)
  assert.equal((await call('get_game_state')).hero.effects.filter(effect => effect.kind === 'help-attack').length, 0)
})

test('hiding in plain sight refuses without a roll; an unseen hero can store a real Stealth result', async t => {
  const call = await engine(t, { characterId: 'wizard', dice: '20' })
  const enemy = await spawn(call)
  await battle(call, [enemy.id])
  const before = await call('get_game_state')
  assert.equal((await call('combat_action', { action: 'hide' })).code, 'CANNOT_HIDE_IN_PLAIN_SIGHT')
  assert.deepEqual(await call('get_game_state'), before)
  await replace(call, state => state.player.conditions.push('invisible'))
  assert.equal(ok(await call('combat_action', { action: 'hide' })).success, true)
  const after = await call('get_game_state')
  assert.ok(after.hero.effects.some(effect => effect.kind === 'hidden' && effect.data.stealth >= 20))
  assert.equal(after.hero.actionCredits, 0)
})

test('standing uses half speed without an action and refuses when movement is insufficient', async t => {
  const call = await engine(t), enemy = await spawn(call)
  await battle(call, [enemy.id])
  await replace(call, state => state.player.conditions.push('prone'))
  const answer = ok(await call('combat_action', { action: 'stand_up' }))
  assert.equal(answer.costCells, 3)
  let state = await call('get_game_state')
  assert.equal(state.hero.actionCredits, 1)
  assert.equal(state.movementUsed.player, 3)
  await replace(call, state => { state.player.conditions.push('prone'); state.movementUsed.player = 5 })
  state = await call('get_game_state')
  assert.equal((await call('combat_action', { action: 'stand_up' })).code, 'MOVEMENT_EXCEEDED')
  assert.deepEqual(await call('get_game_state'), state)
})

test('readied attacks trigger only explicitly, spend one reaction and do not receive Extra Attack', async t => {
  const call = await engine(t, { dice: '17,4' }), enemy = await spawn(call)
  await battle(call, [enemy.id])
  const ready = ok(await call('combat_action', { action: 'ready', readied: { kind: 'attack', weaponId: 'longsword', trigger: 'Lorsque l’adversaire lève son arme.' } }))
  assert.equal((await call('get_game_state')).monsters[enemy.id].hp.current, 200)
  ok(await call('next_turn', { actorId: 'player' }))
  assert.equal((await call('resolve_readied_action', { readyId: ready.readyId, choice: 'execute', targetId: enemy.id })).code, 'READY_TRIGGER_REQUIRED')
  const strike = ok(await call('resolve_readied_action', { readyId: ready.readyId, choice: 'execute', targetId: enemy.id, triggerObserved: 'L’adversaire lève son arme devant moi.' }))
  assert.equal(strike.hit, true)
  const state = await call('get_game_state')
  assert.equal(state.hero.reactionsUsed.player, true)
  assert.equal(state.hero.attackAction, undefined)
  assert.ok((await call('resolve_readied_action', { readyId: ready.readyId, choice: 'execute', targetId: enemy.id, triggerObserved: 'Encore.' })).error)
})

test('a readied spell pays once on preparation, holds concentration, then releases without another slot or action', async t => {
  const call = await engine(t, { characterId: 'wizard', dice: '1,2,3' }), enemy = await spawn(call)
  await battle(call, [enemy.id])
  const before = await call('get_game_state')
  const ready = ok(await call('combat_action', { action: 'ready', readied: { kind: 'spell', spellId: 'magic-missile', slotLevel: 1,
    targetId: enemy.id, trigger: 'Lorsque l’adversaire s’avance.' } }))
  let state = await call('get_game_state')
  assert.equal(state.player.spellSlots.level1.current, before.player.spellSlots.level1.current - 1)
  assert.equal(state.monsters[enemy.id].hp.current, 200)
  assert.equal(state.hero.concentrationId, ready.readyId)
  ok(await call('next_turn', { actorId: 'player' }))
  ok(await call('resolve_readied_action', { readyId: ready.readyId, choice: 'execute', triggerObserved: 'L’adversaire s’avance dans la scène.' }))
  state = await call('get_game_state')
  assert.equal(state.player.spellSlots.level1.current, before.player.spellSlots.level1.current - 1)
  assert.equal(state.monsters[enemy.id].hp.current, 191)
  assert.equal(state.hero.reactionsUsed.player, true)
  assert.equal(state.hero.concentrationId, undefined)
})

test('readied movement can interrupt an enemy turn and resume after an opportunity reaction without spending normal movement', async t => {
  const call = await engine(t), enemy = await spawn(call)
  await battle(call, [enemy.id])
  await replace(call, state => { state.movementUsed.player = 5 })
  const initial = await call('get_game_state')
  const cells = adjacent(initial)
  const cell = cells.find(cell => Math.max(Math.abs(cell.x - enemy.position.x), Math.abs(cell.y - enemy.position.y)) > 1)
  assert.ok(cell, 'fixture needs one adjacent destination leaving enemy reach')
  const ready = ok(await call('combat_action', { action: 'ready', readied: { kind: 'move', trigger: 'Quand le passage se libère.' } }))
  ok(await call('next_turn', { actorId: 'player' }))
  const normalMovement = structuredClone((await call('get_game_state')).movementUsed)
  const move = ok(await call('resolve_readied_action', { readyId: ready.readyId, choice: 'execute', triggerObserved: 'Le passage se libère.', toCell: cell }))
  assert.ok(move.pendingReaction)
  assert.equal(move.pendingReaction.sourceId, enemy.id)
  ok(await call('resolve_reaction', { pendingId: move.pendingReaction.id, choice: 'decline' }))
  const after = await call('get_game_state')
  assert.deepEqual(after.player.position, cell)
  assert.equal(after.currentTurn, enemy.id)
  assert.deepEqual(after.movementUsed, normalMovement)
  assert.equal(after.hero.reactionsUsed.player, true)
})

test('a readied spell expires at the next player turn without refunding its slot', async t => {
  const call = await engine(t, { characterId: 'wizard', dice: '20,1' }), enemy = await spawn(call)
  await battle(call, [enemy.id])
  const slots = (await call('get_game_state')).player.spellSlots.level1.current
  const ready = ok(await call('combat_action', { action: 'ready', readied: { kind: 'spell', spellId: 'magic-missile', targetId: enemy.id, trigger: 'Un événement qui ne survient pas.' } }))
  ok(await call('next_turn', { actorId: 'player' }))
  ok(await call('next_turn', { actorId: enemy.id, skipAction: true }))
  const after = await call('get_game_state')
  assert.equal(after.player.spellSlots.level1.current, slots - 1)
  assert.ok(!after.hero.effects.some(effect => effect.id === ready.readyId))
  assert.equal((await call('resolve_readied_action', { readyId: ready.readyId, choice: 'execute', triggerObserved: 'Trop tard.' })).code, 'READY_EFFECT_NOT_FOUND')
})

test('pushing a held enemy out of reach ends the grapple immediately', async t => {
  const call = await engine(t, { dice: '20,1,20,1' })
  ok(await call('equip_item', { itemId: 'longsword', slot: 'main_hand', operation: 'unequip' }))
  const before = await call('get_game_state'), origin = before.player.position, nav = grid(before)
  const cell = adjacent(before).find(cell => nav.step(cell, { x: cell.x + Math.sign(cell.x - origin.x), y: cell.y + Math.sign(cell.y - origin.y) }))
  assert.ok(cell, 'fixture needs an unobstructed push destination')
  const enemy = await spawn(call, 'goblin', cell)
  await battle(call, [enemy.id])
  assert.equal(ok(await call('combat_action', { action: 'grapple', targetId: enemy.id, defenseSkill: 'acrobatics' })).success, true)
  const toCell = { x: cell.x + Math.sign(cell.x - origin.x), y: cell.y + Math.sign(cell.y - origin.y) }
  assert.equal(ok(await call('combat_action', { action: 'shove', targetId: enemy.id, defenseSkill: 'acrobatics', shove: 'push', toCell })).success, true)
  const after = await call('get_game_state')
  assert.ok(!after.monsters[enemy.id].conditions.includes('grappled'))
  assert.ok(!after.hero.effects.some(effect => effect.kind === 'grapple'))
})
