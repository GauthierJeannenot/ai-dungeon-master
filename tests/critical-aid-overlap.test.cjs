const test=require('node:test'),assert=require('node:assert/strict')
Object.assign(process.env,{MONETIZATION_ENABLED:'false',LLM_MODE:'mock',ALLOW_PAID_LLM:'false',APP_LOG_PERSIST_ENABLED:'false'})
const{installPgMem}=require('./helpers/pg-mem.cjs'),pg=installPgMem()
const{ok}=require('./helpers/mcp-toolkit.cjs')
const{cleric,aid,persistCritical,spawnExact,nextCasterTurn}=require('./helpers/critical-spells-fixture.cjs')
test.after(()=>pg.restore())
const instances=s=>s.hero.effects.filter(e=>e.kind==='aid'&&e.targetIds.includes('player'))

test('a genuine stronger Aid applies only its positive potency delta, retains all paid durations and survives SQL without a second increase',async t=>{
 const call=await cleric(t),base=await call('get_game_state')
 const first=ok(await aid(call,2));let s=await call('get_game_state')
 assert.equal(s.player.hp.max,base.player.hp.max+5);assert.equal(s.player.hp.current,base.player.hp.current+5)
 ok(await call('advance_time',{seconds:3600}))
 const stronger=ok(await aid(call,3));s=await call('get_game_state')
 assert.equal(s.player.hp.max,base.player.hp.max+10);assert.equal(s.player.hp.current,base.player.hp.current+10)
 assert.equal(stronger.results[0].currentHpDelta,5)
 assert.equal(instances(s).length,2);assert.deepEqual(instances(s).map(e=>e.data.aidAppliedBonus),[0,10])
 assert.equal(instances(s)[0].expiresAt,28800);assert.equal(instances(s)[1].expiresAt,32400)
 const next=await persistCritical(t,call)
 assert.deepEqual(await next('get_game_state'),s)
 const corrupt=structuredClone(s);instances(corrupt)[0].data.aidAppliedBonus=5
 assert.equal((await next('replace_game_state',{gameState:corrupt})).code,'CRITICAL_SPELL_STATE_MISMATCH')
 assert.deepEqual(await next('get_game_state'),s)
 ok(await next('advance_time',{seconds:25200}));s=await next('get_game_state')
 assert.equal(instances(s).length,1);assert.equal(s.player.hp.max,base.player.hp.max+10)
 ok(await next('advance_time',{seconds:3600}));s=await next('get_game_state')
 assert.equal(instances(s).length,0);assert.equal(s.player.hp.max,base.player.hp.max);assert.equal(s.player.hp.current,base.player.hp.max)
 assert.equal(first.spell,'aid');assert.equal(ok(await next('roll_dice',{notation:'1d20'})).total,19)
})

test('equal or weaker real casts never heal existing damage, and a later equal instance keeps its own paid duration without new HP',async t=>{
 const call=await cleric(t,'1,20,20,1,1,19'),base=await call('get_game_state')
 ok(await aid(call,3))
 ok(await call('advance_time',{seconds:3600}))
 const enemy=await spawnExact(call,'bandit')
 ok(await call('enter_combat',{combatants:['player',enemy.id]}));assert.equal((await call('get_game_state')).currentTurn,enemy.id)
 ok(await call('resolve_monster_action',{monsterId:enemy.id,actionName:'Scimitar',targetId:'player'}))
 ok(await call('next_turn',{actorId:enemy.id}))
 const damaged=await call('get_game_state');assert.ok(damaged.player.hp.current<damaged.player.hp.max)
 const weaker=ok(await aid(call,2));let s=await call('get_game_state')
 assert.equal(weaker.results[0].currentHpDelta,0);assert.equal(s.player.hp.current,damaged.player.hp.current)
 // The two real spell costs and damage remain; combat ends by an explicit MJ event.
 ok(await call('end_combat',{force:true,reason:'The actual bandit gives up this encounter; its attack damage and the cast remain real.'}))
 const equal=ok(await aid(call,3));s=await call('get_game_state')
 assert.equal(equal.results[0].currentHpDelta,0);assert.equal(s.player.hp.current,damaged.player.hp.current)
 // The equal stronger instance is later than the first. It keeps the same
 // potency through first expiry; no currentHP is granted by reactivation.
 const beforeExpiry=s.player.hp.current
 ok(await call('advance_time',{seconds:25200}));s=await call('get_game_state')
 assert.equal(s.player.hp.max,base.player.hp.max+10);assert.equal(s.player.hp.current,beforeExpiry)
 const next=await persistCritical(t,call)
 ok(await next('advance_time',{seconds:3600}));s=await next('get_game_state')
 assert.equal(s.player.hp.max,base.player.hp.max);assert.equal(s.player.hp.current,Math.min(beforeExpiry,base.player.hp.max))
 assert.equal(ok(await next('roll_dice',{notation:'1d20'})).total,19)
})

test('a later weaker Aid remains after the stronger expires, only one real maximum contribution is restored, including exhaustion basis',async t=>{
 const call=await cleric(t),base=await call('get_game_state')
 ok(await aid(call,3));ok(await call('advance_time',{seconds:3600}));ok(await aid(call,2))
 const before=await call('get_game_state')
 assert.deepEqual(instances(before).map(e=>e.data.aidAppliedBonus),[10,0])
 const next=await persistCritical(t,call)
 ok(await next('advance_time',{seconds:25200}));let s=await next('get_game_state')
 assert.equal(s.player.hp.max,base.player.hp.max+5);assert.equal(instances(s).length,1);assert.equal(instances(s)[0].data.aidAppliedBonus,5)
 assert.equal(s.player.hp.current,Math.min(before.player.hp.current,s.player.hp.max))
 ok(await next('advance_time',{seconds:3600}));s=await next('get_game_state')
 assert.equal(s.player.hp.max,base.player.hp.max);assert.equal(s.player.hp.current,base.player.hp.max)
 // A separate existing producer gives real exhaustion, not an injected max.
 const exhausted=await cleric(t),b=await exhausted('get_game_state')
 ok(await exhausted('add_exhaustion',{eventId:'critical-aid-exhaustion',targetId:'player',levels:4,reason:'The MJ explicitly establishes these four real exhaustion levels for this current actor.'}))
 ok(await aid(exhausted,2));ok(await aid(exhausted,3));s=await exhausted('get_game_state')
 assert.equal(s.dmTools.exhaustion.creatures.player.unexhaustedHpMax,b.player.hp.max+10)
 assert.equal(s.player.hp.max,Math.floor((b.player.hp.max+10)/2))
 ok(await exhausted('advance_time',{seconds:28800}));s=await exhausted('get_game_state')
 assert.equal(s.dmTools.exhaustion.creatures.player.unexhaustedHpMax,b.player.hp.max)
 assert.equal(s.player.hp.max,Math.floor(b.player.hp.max/2))
})
