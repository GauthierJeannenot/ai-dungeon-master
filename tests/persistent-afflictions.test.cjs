const test=require('node:test'),assert=require('node:assert/strict')
const {engine,ok,replace,spawn,addSupply,battle,grid}=require('./helpers/mcp-toolkit.cjs')
const {AFFLICTIONS}=require('../mcp-server/dist/lib/srd/afflictions.js')
async function source(call,templateId,id=templateId,cell){
  const state=await call('get_game_state'),input={sourceId:id,templateId,name:'Contamination préparée',cell:cell??state.player.position,doses:2}
  ok(await call('create_affliction_source',input));return input
}
async function expose(call,sourceId,templateId,eventId='first',extra={}){
  return ok(await call('expose_affliction',{sourceId,eventId,targetId:'player',delivery:AFFLICTIONS[templateId].delivery,...extra}))
}
const record=(state,id,eventId='first')=>state.dmTools.afflictions.records[`${id}:${eventId}`]
async function freeClericHand(call){
  const state=await call('get_game_state'),loadout=state.dmTools?.loadout
  const main=loadout?loadout.mainHandId:state.player.inventory.find(item=>item.type==='weapon')?.id
  assert.ok(main,'the cleric fixture starts holding its actual weapon')
  ok(await call('equip_item',{itemId:main,operation:'unequip',slot:'main_hand'}))
}
