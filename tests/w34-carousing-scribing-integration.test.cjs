const test = require('node:test'), assert = require('node:assert/strict')
Object.assign(process.env, { MONETIZATION_ENABLED: 'false', LLM_MODE: 'mock', ALLOW_PAID_LLM: 'false' })
const { installPgMem } = require('./helpers/pg-mem.cjs'), pg = installPgMem()
const { engine, ok, adjacent, grid } = require('./helpers/mcp-toolkit.cjs')
const { prepareCarousing, nextCarousingDate } = require('./helpers/xge-carousing-fixture.cjs')
const { prepareMultiDayScroll } = require('./helpers/xge-multiday-scribing-fixture.cjs')
const { copperValue } = require('../mcp-server/dist/lib/srd/currency.js')
const { playerSeesCell } = require('../mcp-server/dist/lib/scene-perception.js')
test.after(() => pg.restore())

async function unchanged(call, name, input, code) {
  const before = await call('get_game_state'), answer = await call(name, input)
  assert.equal(answer.code, code, JSON.stringify(answer))
  assert.deepEqual(await call('get_game_state'), before)
}

async function persisted(t, call) {
  const { saveSession, loadSession, deleteSession } = require('../lib/session-store.ts')
  const state = await call('get_game_state'), id = 'w34-cross-' + process.pid + '-' + Math.random()
  t.after(() => deleteSession(id))
  await saveSession(id, { gameState: state, history: [], adventureId: state.adventureId, characterId: state.characterId })
  const fresh = await engine(t, { characterId: state.characterId, adventureId: state.adventureId, dice: '19' })
  ok(await fresh('replace_game_state', { gameState: (await loadSession(id)).gameState }))
  assert.deepEqual(await fresh('get_game_state'), state)
  return fresh
}

test('actual Carousing and three-date Misty Step scribing share the real8h date budget both ways, retain paid effort through SQL, and produce one usable physical scroll without spending a spell slot', async t => {
  let call = await engine(t, { characterId: 'wizard', dice: '19' })
  ok(await call('prepare_spells', { spellIds: ['misty-step'] }))
  const social = await prepareCarousing(call, { projectId: 'cross-actual-social-week', fundGp: 300 })
  const scroll = await prepareMultiDayScroll(call, { projectId: 'cross-actual-three-dates', scrollItemId: 'cross-actual-misty-scroll' })
  const before = await call('get_game_state')
  ok(await call('start_xge_carousing', social.startInput))
  ok(await call('start_xge_spell_scroll_project', scroll.input))
  assert.equal(copperValue(before.dmTools.wallet) - copperValue((await call('get_game_state')).dmTools.wallet), 25000)
  const paidSocialDay = social.work(0, { gp: 10 })
  ok(await call('work_xge_carousing', paidSocialDay))
  await unchanged(call, 'work_xge_spell_scroll_project', scroll.work(0), 'DOWNTIME_SHARED_DAY_REQUIRED')
  await nextCarousingDate(call)
  ok(await call('work_xge_spell_scroll_project', scroll.work(0)))
  await unchanged(call, 'work_xge_carousing', social.work(1), 'DOWNTIME_SHARED_DAY_REQUIRED')
  call = await persisted(t, call)
  const frozen = await call('get_game_state')
  assert.equal(ok(await call('work_xge_carousing', paidSocialDay)).replayed, true)
  assert.equal(ok(await call('work_xge_spell_scroll_project', scroll.work(0))).replayed, true)
  assert.deepEqual(await call('get_game_state'), frozen)
  for (let index = 1; index < 3; index++) {
    await nextCarousingDate(call)
    ok(await call('work_xge_spell_scroll_project', scroll.work(index)))
  }
  const completed = await call('get_game_state')
  assert.equal(copperValue(before.dmTools.wallet) - copperValue(completed.dmTools.wallet), 26000)
  assert.deepEqual(completed.player.spellSlots, before.player.spellSlots)
  assert.equal(completed.droppedItems[scroll.input.scrollItemId].item.quantity, 1)
  assert.equal(completed.dmTools.spellScrolls[scroll.input.scrollItemId].spellId, 'misty-step')
  call = await persisted(t, call)
  ok(await call('pick_up_item', { itemId: scroll.input.scrollItemId }))
  const state = await call('get_game_state')
  const destination = adjacent(state).find(cell => grid(state).free(cell) && playerSeesCell(state, cell))
  assert.ok(destination, 'Choose one actual visible free adjacent destination.')
  const used = ok(await call('use_spell_scroll', { itemId: scroll.input.scrollItemId, toCell: destination }))
  assert.equal(used.spellScrollUse.consumed, true)
  assert.equal(used.spellSlotSpent, false)
  const after = await call('get_game_state')
  assert.deepEqual(after.player.position, destination)
  assert.deepEqual(after.player.spellSlots, before.player.spellSlots)
  assert.equal(after.dmTools.spellScrolls[scroll.input.scrollItemId].status, 'consumed')
  await unchanged(call, 'use_spell_scroll', { itemId: scroll.input.scrollItemId, toCell: state.player.position }, 'SPELL_SCROLL_CONSUMED')
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})
