const test = require('node:test')
const assert = require('node:assert/strict')
const { Client } = require('@modelcontextprotocol/sdk/client/index.js')
const { StdioClientTransport } = require('@modelcontextprotocol/sdk/client/stdio.js')

test('door interactions validate side and range before rolling, preserve failed/successful force results and require explicit crossing', async t => {
  const client = new Client({ name: 'doors-test', version: '1' })
  await client.connect(new StdioClientTransport({ command: 'node', args: ['mcp-server/dist/mcp-server/index.js'], env: { ...process.env, ADVENTURE_ID: 'grammys-country-apple-pie', AI_DM_TEST_DICE_SEQUENCE: '1,20' } }))
  t.after(() => client.close())
  const call = async (name, args = {}) => JSON.parse((await client.callTool({ name, arguments: args })).content[0].text)
  assert.equal((await call('interact_door', { doorId: 'front', action: 'force' })).code, 'DOOR_OUT_OF_REACH')
  assert.equal((await call('move_token', { tokenId: 'player', doorId: 'entry-apartment', doorMode: 'approach' })).code, 'DOOR_NOT_ACCESSIBLE')
  const beforeConflict = await call('get_game_state')
  const conflict = await call('move_token', { tokenId: 'player', doorId: 'front', doorMode: 'approach', toCell: { x: 11, y: 12 } })
  assert.equal(conflict.code, 'INVALID_DESTINATION')
  assert.deepEqual(await call('get_game_state'), beforeConflict)
  const approach = await call('move_token', { tokenId: 'player', doorId: 'front', doorMode: 'approach' })
  assert.deepEqual(approach.newPosition, { x: 11, y: 13 })
  assert.equal(approach.crossed, false)
  assert.equal((await call('interact_door', { doorId: 'front', action: 'open' })).code, 'DOOR_BARRED')
  assert.equal((await call('move_token', { tokenId: 'player', doorId: 'front', doorMode: 'cross' })).code, 'DOOR_CLOSED')
  const failure = await call('interact_door', { doorId: 'front', action: 'force' })
  assert.equal(failure.check.roll.rolls[0], 1)
  assert.equal(failure.check.dc, 14)
  assert.equal(failure.doorState, 'closed')
  assert.equal((await call('get_game_state')).sceneMemory?.discoveredRoomIds?.includes('4') ?? false, false)
  const success = await call('interact_door', { doorId: 'front', action: 'force' })
  assert.equal(success.check.roll.rolls[0], 20)
  assert.equal(success.doorState, 'broken')
  const afterOpening = await call('get_game_state')
  assert.ok(afterOpening.sceneMemory.discoveredRoomIds.includes('4'), 'opening reveals the room before crossing')
  assert.equal(afterOpening.roomsVisited.includes('4'), false, 'sight never completes a room visit')
  assert.equal(afterOpening.sceneMemory.discoveredRoomIds.includes('8'), false, 'open doors deeper inside do not reveal chained rooms')
  const restored = await call('replace_game_state', { gameState: await call('get_game_state') })
  assert.equal(restored.sceneMemory.doorStates.front, 'broken')
  assert.deepEqual(restored.sceneMemory.discoveredRoomIds, afterOpening.sceneMemory.discoveredRoomIds)
  assert.equal(restored.currentRoomId, '1')
  assert.equal((await call('move_token', { tokenId: 'player', doorId: 'front', doorMode: 'cross' })).currentRoomId, '4')
  assert.equal((await call('interact_door', { doorId: 'front', action: 'close' })).doorState, 'broken')
})
