const test = require('node:test'), assert = require('node:assert/strict')
Object.assign(process.env, { MONETIZATION_ENABLED: 'false', LLM_MODE: 'mock', ALLOW_PAID_LLM: 'false' })
const { installPgMem } = require('./helpers/pg-mem.cjs'), pg = installPgMem()
const { engine, ok, adjacent, grid } = require('./helpers/mcp-toolkit.cjs')
const { playerSeesCell } = require('../mcp-server/dist/lib/scene-perception.js')
const { prepareSacredRitesAtCurrentSite, nextSacredRiteDate } = require('./helpers/sacred-rites-fixture.cjs')
test.after(() => pg.restore())

test('Inspiration actually earned on a Sacred Rites date survives SQL and cancels Shove Aside disadvantage on the one real opposed Athletics check', async t => {
  const call = await engine(t, { characterId: 'bard', dice: '2,3,20,1' })
  const rites = await prepareSacredRitesAtCurrentSite(call, {
    projectId: 'cross-rites-before-aside', role: 'temple_priest', deityName: 'La divinité réellement vénérée dans ce temple qualifié',
  })
  ok(await call('start_sacred_rites', rites.input))
  for (let index = 0; index < 10; index++) {
    if (index) await nextSacredRiteDate(call)
    ok(await call('work_sacred_rites', rites.work(index)))
  }
  let state = await call('get_game_state')
  const project = state.dmTools.sacredRites.projects.find(p => p.start.input.projectId === rites.input.projectId)
  assert.deepEqual(project.benefit.roll.rolls, [2, 3])
  ok(await call('advance_time', { seconds: project.benefit.fromDay * 86400 - state.worldTimeSeconds }))
  assert.equal((await call('get_game_state')).dmTools.dmInspiration.held, true)
  state = await call('get_game_state')
  const nav = grid(state), free = adjacent(state).filter(cell => nav.free(cell) && playerSeesCell(state, cell))
  const pair = free.flatMap(target => free.filter(destination =>
    Math.abs(target.x - destination.x) + Math.abs(target.y - destination.y) === 1 && nav.step(target, destination))
    .map(destination => ({ target, destination }))).find(Boolean)
  assert.ok(pair, 'Use two actual free supported adjacent cells, one cardinal step apart and both within player reach.')
  const target = ok(await call('spawn_monster', { monsterType: 'goblin', cell: pair.target }))
  ok(await call('enter_combat', { combatants: ['player', target.id] }))
  assert.equal((await call('get_game_state')).currentTurn, 'player')
  ok(await call('spend_inspiration', { spendId: 'cross-actual-rites-athletics', rollKind: 'check' }))
  const { saveSession, loadSession, deleteSession } = require('../lib/session-store.ts')
  const sessionId = 'w34-rites-aside-' + process.pid
  t.after(() => deleteSession(sessionId))
  state = await call('get_game_state')
  await saveSession(sessionId, { gameState: state, history: [], adventureId: state.adventureId, characterId: state.characterId })
  const fresh = await engine(t, { adventureId: state.adventureId, characterId: state.characterId, dice: '18,1,19' })
  ok(await fresh('replace_game_state', { gameState: (await loadSession(sessionId)).gameState }))
  assert.deepEqual(await fresh('get_game_state'), state)
  assert.equal((await fresh('get_game_state')).currentTurn, 'player')
  const attempt = ok(await fresh('combat_action', { action: 'shove', shove: 'aside', targetId: target.id, defenseSkill: 'acrobatics', toCell: pair.destination }))
  // The actual Lore bard may react to the defender's retained ability check.
  assert.ok(attempt.pendingReaction.options.includes('cutting_words_check'))
  assert.deepEqual(attempt.pendingReaction.command.toolkitResolution.command.firstCheck.roll.rolls, [18])
  assert.deepEqual(attempt.pendingReaction.roll.rolls, [1])
  ok(await fresh('resolve_reaction', { pendingId: attempt.pendingReaction.id, choice: 'decline' }))
  const after = await fresh('get_game_state')
  assert.deepEqual(after.monsters[target.id].position, pair.destination)
  assert.deepEqual(after.player.position, state.player.position)
  assert.equal(after.dmTools.dmInspiration.held, false)
  assert.equal(after.dmTools.dmInspiration.prepared, undefined)
  assert.equal(after.actionUsed.player, true)
  assert.equal(after.hero.actionCredits, 0)
  assert.equal(after.movementUsed[target.id] ?? 0, 0)
  assert.equal(after.dmTools.sacredRites.projects[0].benefit.awards.length, 1)
  assert.equal(ok(await fresh('roll_dice', { notation: '1d20' })).total, 19)
})
