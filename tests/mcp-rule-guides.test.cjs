const test = require('node:test')
const assert = require('node:assert/strict')
const { engine, ok } = require('./helpers/mcp-toolkit.cjs')

test('MCP rules index stays compact and domain procedures remain read-only without consuming dice', async t => {
  const call = await engine(t, { dice: '19' }), before = await call('get_game_state')
  const index = ok(await call('get_rules_support'))
  assert.ok(index.domains.includes('nutrition') && index.domains.includes('chases'))
  assert.ok(JSON.stringify(index).length < 5000)
  assert.equal(index.procedures, undefined)
  assert.equal(index.nutrition, undefined)
  const domain = ok(await call('get_rules_support', { domain: 'chases' }))
  assert.equal(domain.domain, 'chases')
  assert.ok(domain.tools.includes('begin_chase'))
  assert.ok(domain.procedures.some(guide => guide.text.includes('resolve_chase_turn')))
  assert.ok(!domain.procedures.some(guide => guide.text.includes('tumblePath')))
  assert.deepEqual(await call('get_game_state'), before)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})
