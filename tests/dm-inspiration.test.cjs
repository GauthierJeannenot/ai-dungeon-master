const test = require('node:test')
const assert = require('node:assert/strict')
const { engine, ok, replace, spawn, battle } = require('./helpers/mcp-toolkit.cjs')
const { DMInspirationStateSchema } = require('../mcp-server/dist/lib/dm-inspiration-state.js')

const grant = (call, eventId = 'gift-1', reason = 'Le personnage assume son idéal malgré un risque établi.') =>
  call('grant_inspiration', { eventId, reason })
const spend = (call, rollKind = 'check', spendId = 'spend-1') => call('spend_inspiration', { spendId, rollKind })
const ledger = async call => (await call('get_game_state')).dmTools.dmInspiration
const check = (call, extra = {}) => call('roll_ability_check', { ability: 'int', dc: 10, ...extra })

test('DM inspiration receipts cap at one, retain capped events, and never regrant or reprepare on replay', async t => {
  const call = await engine(t, { dice: '2,18,19' })
  assert.equal(ok(await grant(call)).granted, true)
  assert.equal(ok(await grant(call, 'capped-gift')).capped, true)
  assert.equal(ok(await grant(call)).replayed, true)
  const beforeConflict = await call('get_game_state')
  assert.equal((await grant(call, 'gift-1', 'Une autre raison.')).code, 'INSPIRATION_EVENT_CONFLICT')
  assert.deepEqual(await call('get_game_state'), beforeConflict)
  ok(await spend(call)); ok(await check(call))
  const consumed = await ledger(call)
  assert.equal(consumed.held, false); assert.equal(consumed.prepared, undefined)
  assert.equal(consumed.spends['spend-1'].status, 'consumed')
  assert.equal(ok(await grant(call, 'capped-gift')).originalOutcome, 'capped')
  assert.equal(ok(await grant(call)).originalOutcome, 'granted')
  assert.equal((await ledger(call)).held, false)
  ok(await grant(call, 'gift-2'))
  assert.equal(ok(await spend(call)).alreadyConsumed, true)
  assert.equal((await ledger(call)).held, true)
  assert.equal((await spend(call, 'save')).code, 'INSPIRATION_SPEND_CONFLICT')
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

test('grant and preparation require exact choices, spend no action/time/dice, and reserve the single capacity', async t => {
  const call = await engine(t, { dice: '19' }), target = await spawn(call)
  await battle(call, [target.id])
  const initial = await call('get_game_state')
  assert.equal((await spend(call)).code, 'INSPIRATION_NOT_HELD')
  assert.ok((await call('grant_inspiration', { eventId: 'bad', reason: ' ' })).error)
  assert.ok((await call('spend_inspiration', { spendId: 'bad', rollKind: 'damage' })).error)
  assert.deepEqual(await call('get_game_state'), initial)
  ok(await grant(call)); ok(await spend(call, 'attack'))
  const prepared = await call('get_game_state')
  for (const key of ['worldTimeSeconds', 'actionUsed', 'bonusActionUsed', 'movementUsed']) assert.deepEqual(prepared[key], initial[key])
  assert.deepEqual(prepared.player, initial.player); assert.deepEqual(prepared.hero, initial.hero)
  assert.equal(prepared.dmTools.dmInspiration.held, false)
  assert.equal((await grant(call, 'gift-2')).code, 'INSPIRATION_ROLL_PREPARED')
  assert.equal((await spend(call, 'save', 'spend-2')).code, 'INSPIRATION_ROLL_PREPARED')
  assert.equal(ok(await spend(call, 'attack')).replayed, true)
  assert.deepEqual(await call('get_game_state'), prepared)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
  assert.equal((await ledger(call)).prepared.kind, 'attack', 'documentary dice do not consume the prepared attack')
})

test('a matching check gains advantage, preserves the actual modifier, and consumes exactly one prepared token', async t => {
  const call = await engine(t, { dice: '2,18,19' })
  ok(await grant(call)); ok(await spend(call))
  const result = ok(await check(call, { roleplayBonus: 2, roleplayReason: 'Une approche concrète justifiée.' }))
  assert.equal(result.roll.rolls[0], 18); assert.equal(result.advantage, true)
  assert.match(result.roll.detail, /ADV:/); assert.match(result.roll.detail, /Inspiration du MJ/)
  const state = await call('get_game_state'), expectedMod = Math.floor((state.player.stats.int - 10) / 2) + 2
  assert.equal(result.roll.modifier, expectedMod)
  assert.equal(result.roll.total, 18 + expectedMod)
  assert.equal(state.dmTools.dmInspiration.spends['spend-1'].status, 'consumed')
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

test('redundant advantage rolls only two dice and cancellation with disadvantage still spends inspiration', async t => {
  const adv = await engine(t, { dice: '2,18,19' })
  ok(await grant(adv)); ok(await spend(adv))
  assert.equal(ok(await check(adv, { advantage: true, advantageReason: 'Aide déjà établie.' })).roll.rolls[0], 18)
  assert.equal(ok(await adv('roll_dice', { notation: '1d20' })).total, 19)
  const dis = await engine(t, { dice: '4,19' })
  ok(await grant(dis)); ok(await spend(dis))
  const cancelled = ok(await check(dis, { disadvantage: true, advantageReason: 'Circonstance défavorable établie.' }))
  assert.equal(cancelled.roll.rolls[0], 4); assert.doesNotMatch(cancelled.roll.detail, /ADV:|DIS:/)
  assert.equal((await ledger(dis)).spends['spend-1'].status, 'consumed')
  assert.equal(ok(await dis('roll_dice', { notation: '1d20' })).total, 19)
})

test('other categories, actors and invalid attacks preserve the reservation until a real player attack', async t => {
  const call = await engine(t, { dice: '3,4,2,18,1,19' }), target = await spawn(call)
  ok(await grant(call)); ok(await spend(call, 'attack'))
  assert.equal(ok(await check(call)).roll.rolls[0], 3)
  assert.equal(ok(await call('resolve_saving_throw', { entityId: target.id, ability: 'wis', dc: 10 })).roll.rolls[0], 4)
  await battle(call, [target.id])
  const before = await call('get_game_state')
  assert.ok((await call('resolve_player_attack', { targetId: 'nonexistent', weaponOrSpell: 'unarmed' })).error)
  assert.deepEqual(await call('get_game_state'), before)
  const attack = ok(await call('resolve_player_attack', { targetId: target.id, weaponOrSpell: 'unarmed' }))
  assert.equal(attack.attackRoll.rolls[0], 18); assert.match(attack.attackRoll.detail, /Inspiration du MJ/)
  assert.equal((await ledger(call)).spends['spend-1'].status, 'consumed')
  // Unarmed damage is fixed; neither a DM token nor a capped gift adds a die.
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 1)
})

test('a source automatic save failure preserves inspiration and consumes no d20', async t => {
  const call = await engine(t, { dice: '2,18,19' })
  ok(await grant(call)); ok(await spend(call, 'save'))
  await replace(call, state => { state.player.conditions.push('paralyzed') })
  const automatic = ok(await call('resolve_saving_throw', { entityId: 'player', ability: 'dex', dc: 10 }))
  assert.equal(automatic.roll.notation, 'automatic-failure')
  assert.equal((await ledger(call)).prepared.kind, 'save')
  const actual = ok(await call('resolve_saving_throw', { entityId: 'player', ability: 'con', dc: 10 }))
  assert.equal(actual.roll.rolls[0], 18); assert.match(actual.roll.detail, /ADV:/)
  assert.equal((await ledger(call)).prepared, undefined)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

test('death saves use explicitly prepared save inspiration and the kept natural die', async t => {
  const call = await engine(t, { dice: '1,20,19' }), target = await spawn(call)
  await battle(call, [target.id])
  await replace(call, state => {
    state.player.hp.current = 0; state.player.conditions.push('unconscious')
    state.player.deathSaves = { successes: 0, failures: 0, stable: false, dead: false }
  })
  ok(await call('checkpoint_player_dying',{eventId:'inspired-save-observed',reason:'Ancien corps mourant observé au présent, avant son prochain vrai tour.'}))
  ok(await call('next_turn',{actorId:'player',skipAction:true}))
  ok(await call('next_turn',{actorId:target.id,skipAction:true}))
  ok(await grant(call)); ok(await spend(call, 'save'))
  const result = ok(await call('roll_death_save'))
  assert.equal(result.criticalSuccess, true); assert.equal(result.roll.rolls[0], 20)
  assert.equal((await call('get_game_state')).player.hp.current, 1)
  assert.equal((await ledger(call)).spends['spend-1'].status, 'consumed')
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

test('held Bardic checks hydrate and resume without another d20 or another DM inspiration consumption', async t => {
  const call = await engine(t, { dice: '1,13,6,19' })
  await replace(call, state => { state.hero.inspiration.push({ targetId: 'player', expiresAt: state.worldTimeSeconds + 600, die: 8 }) })
  ok(await grant(call)); ok(await spend(call))
  const held = ok(await check(call, { dc: 30 }))
  assert.ok(held.pendingReaction)
  const saved = await call('get_game_state')
  assert.equal(saved.dmTools.dmInspiration.spends['spend-1'].status, 'consumed')
  assert.equal(saved.dmTools.dmInspiration.prepared, undefined)
  assert.equal(saved.hero.inspiration.length, 1, 'the distinct Bardic die has not been spent')
  ok(await call('replace_game_state', { gameState: saved }))
  assert.equal((await grant(call, 'retroactive')).code, 'REACTION_PENDING')
  assert.equal((await spend(call, 'check', 'retroactive')).code, 'REACTION_PENDING')
  assert.deepEqual(await call('get_game_state'), saved)
  const finished = ok(await call('resolve_reaction', { pendingId: held.pendingReaction.id, choice: 'bardic_inspiration' }))
  assert.equal(finished.roll.total, 13 + saved.hero.pending.roll.modifier + 6)
  const resumed = await call('get_game_state')
  assert.equal(resumed.hero.inspiration.length, 0)
  assert.deepEqual(resumed.dmTools.dmInspiration, saved.dmTools.dmInspiration)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

test('held and prepared inspiration persist across hydration and rests without automatic awards or recharge', async t => {
  const call = await engine(t, { dice: '2,18' })
  ok(await grant(call)); const held = await ledger(call)
  ok(await call('take_rest', { kind: 'short' })); assert.deepEqual(await ledger(call), held)
  ok(await spend(call)); const saved = await call('get_game_state')
  ok(await call('replace_game_state', { gameState: saved }))
  ok(await call('take_rest', { kind: 'short' }))
  assert.deepEqual(await ledger(call), saved.dmTools.dmInspiration)
  ok(await check(call)); const consumed = await ledger(call)
  ok(await call('take_rest', { kind: 'long' })); assert.deepEqual(await ledger(call), consumed)
})

test('strict persisted schema rejects stacking, orphan reservations, inconsistent consumed receipts and unsafe keys', () => {
  const prepared = { held: false, prepared: { spendId: 's1', kind: 'check' }, grants: {}, spends: { s1: { kind: 'check', status: 'prepared' } } }
  assert.equal(DMInspirationStateSchema.safeParse(prepared).success, true)
  assert.equal(DMInspirationStateSchema.safeParse({ ...prepared, held: true }).success, false)
  assert.equal(DMInspirationStateSchema.safeParse({ ...prepared, prepared: undefined }).success, false)
  assert.equal(DMInspirationStateSchema.safeParse({ ...prepared, spends: {} }).success, false)
  assert.equal(DMInspirationStateSchema.safeParse({ held: false, grants: {}, spends: { s1: { kind: 'check', status: 'consumed' } } }).success, false)
  assert.equal(DMInspirationStateSchema.safeParse({ held: false, grants: { constructor: { reason: 'x', outcome: 'granted' } }, spends: {} }).success, false)
})
