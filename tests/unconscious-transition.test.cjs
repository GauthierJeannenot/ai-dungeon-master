const test = require('node:test'), assert = require('node:assert/strict')
const { engine, ok, replace, spawn, battle } = require('./helpers/mcp-toolkit.cjs')

const damage = (call, delta) => call('update_hp', {
  entityId: 'player', delta, reason: 'Dégâts établis dans ce scénario de perte de conscience.',
})
const heldMain = state => state.dmTools?.loadout
  ? state.dmTools.loadout.mainHandId
  : state.player.inventory.find(item => item.type === 'weapon')?.id

test('actual zero HP drops the legacy held weapon at the real cell, adds prone, and retains worn armor and shield', async t => {
  const call = await engine(t, { dice: '17' }), before = await call('get_game_state')
  const mainId = heldMain(before), held = before.player.inventory.find(item => item.id === mainId)
  assert.ok(held)
  ok(await damage(call, -before.player.hp.current))
  const after = await call('get_game_state')
  assert.equal(after.player.hp.current, 0); assert.equal(Boolean(after.player.deathSaves.dead), false)
  assert.ok(after.player.conditions.includes('unconscious')); assert.ok(after.player.conditions.includes('prone'))
  assert.deepEqual(after.droppedItems[mainId].item, held)
  assert.deepEqual(after.droppedItems[mainId].position, before.player.position)
  assert.equal(after.droppedItems[mainId].mapId, before.currentMapId)
  assert.equal(after.droppedItems[mainId].roomId, before.currentRoomId)
  assert.deepEqual(after.player.inventory, before.player.inventory.filter(item => item.id !== mainId))
  assert.equal(after.dmTools.loadout.mainHandId, undefined)
  assert.equal(after.dmTools.loadout.shieldId, 'shield')
  assert.ok(after.player.inventory.some(item => item.id === after.dmTools.loadout.armorId))
  assert.equal(after.player.ac, before.player.ac)
  assert.deepEqual(after.actionUsed, before.actionUsed); assert.deepEqual(after.movementUsed, before.movementUsed)
  assert.equal(after.worldTimeSeconds, before.worldTimeSeconds)
  ok(await call('replace_game_state', { gameState: after }))
  assert.deepEqual(await call('get_game_state'), after, 'hydrating the actual fall does not drop a second object or infer a spare weapon')
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 17)
})

test('two exact held instances drop once; a carried spare stays and positive-HP unconsciousness survives hydration', async t => {
  const call = await engine(t, { characterId: 'wizard', dice: '17' }), initial = await call('get_game_state')
  ok(await call('equip_item', { itemId: heldMain(initial), operation: 'unequip', slot: 'main_hand' }))
  await replace(call, state => state.player.inventory.push(
    { id: 'fall-left', equipmentId: 'dagger', name: 'Dague tenue à gauche', type: 'weapon' },
    { id: 'fall-right', equipmentId: 'dagger', name: 'Dague tenue à droite', type: 'weapon' },
    { id: 'fall-spare', equipmentId: 'dagger', name: 'Dague rangée', type: 'weapon' }))
  ok(await call('equip_item', { itemId: 'fall-left', operation: 'equip', slot: 'main_hand' }))
  ok(await call('equip_item', { itemId: 'fall-right', operation: 'equip', slot: 'off_hand' }))
  const before = await call('get_game_state')
  ok(await call('apply_condition', { entityId: 'player', condition: 'unconscious' }))
  const after = await call('get_game_state')
  assert.deepEqual(after.player.hp, before.player.hp)
  for (const id of ['fall-left', 'fall-right']) {
    assert.ok(after.droppedItems[id]); assert.ok(!after.player.inventory.some(item => item.id === id))
  }
  assert.ok(after.player.inventory.some(item => item.id === 'fall-spare'))
  assert.equal(after.dmTools.loadout.mainHandId, undefined); assert.equal(after.dmTools.loadout.offHandId, undefined)
  ok(await call('apply_condition', { entityId: 'player', condition: 'unconscious' }))
  assert.deepEqual(await call('get_game_state'), after, 'reapplying the same state has no extra physical or time cost')
  ok(await call('replace_game_state', { gameState: after }))
  assert.deepEqual(await call('get_game_state'), after, 'loading is neither healing nor waking a positive-HP creature')
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 17)
})

test('healing and retrieval do not stand the player or re-equip a dropped weapon; a later actual fall may drop it again', async t => {
  const call = await engine(t), before = await call('get_game_state'), mainId = heldMain(before)
  ok(await damage(call, -before.player.hp.current))
  ok(await call('update_hp', { entityId: 'player', delta: 1, reason: 'Soin réel après la chute.' }))
  let state = await call('get_game_state')
  assert.ok(!state.player.conditions.includes('unconscious')); assert.ok(state.player.conditions.includes('prone'))
  assert.ok(state.droppedItems[mainId]); assert.equal(state.dmTools.loadout.mainHandId, undefined)
  ok(await call('pick_up_item', { itemId: mainId }))
  state = await call('get_game_state')
  assert.ok(state.player.inventory.some(item => item.id === mainId)); assert.equal(state.droppedItems[mainId], undefined)
  assert.equal(state.dmTools.loadout.mainHandId, undefined, 'retrieval is not drawing the weapon')
  ok(await call('equip_item', { itemId: mainId, operation: 'equip', slot: 'main_hand' }))
  ok(await call('apply_condition', { entityId: 'player', condition: 'unconscious' }))
  state = await call('get_game_state')
  assert.ok(state.droppedItems[mainId]); assert.ok(!state.player.inventory.some(item => item.id === mainId))
  assert.equal(Object.values(state.droppedItems).filter(drop => drop.item.id === mainId).length, 1)
})

test('a real sprite sleep drops the held object, and an explicit wake leaves poison, prone and ground items unchanged', async t => {
  const call = await engine(t, { characterId: 'wizard', dice: '20,20,1,19' })
  const initial = await call('get_game_state'), mainId = heldMain(initial)
  const sprite = await spawn(call, 'sprite'), helper = await spawn(call, 'commoner')
  await battle(call, [sprite.id, helper.id], sprite.id)
  const shot = ok(await call('resolve_monster_action', { monsterId: sprite.id, actionName: 'Shortbow', targetId: 'player' }))
  if (shot.pendingReaction) ok(await call('resolve_reaction', { pendingId: shot.pendingReaction.id, choice: 'decline' }))
  let state = await call('get_game_state')
  assert.ok(state.player.hp.current > 0)
  assert.ok(state.player.conditions.includes('unconscious')); assert.ok(state.player.conditions.includes('poisoned'))
  assert.ok(state.player.conditions.includes('prone')); assert.ok(state.droppedItems[mainId])
  ok(await call('replace_game_state', { gameState: state }))
  ok(await call('next_turn', { actorId: sprite.id }))
  ok(await call('wake_sleeping_creature', { actorId: helper.id, targetId: 'player' }))
  state = await call('get_game_state')
  assert.ok(!state.player.conditions.includes('unconscious')); assert.ok(state.player.conditions.includes('poisoned'))
  assert.ok(state.player.conditions.includes('prone')); assert.ok(state.droppedItems[mainId])
  assert.equal(state.dmTools.loadout.mainHandId, undefined)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

test('stabilization and damage while dying preserve one ground instance and add only the real death failures', async t => {
  const call = await engine(t, { dice: '17,2,19' }), initial = await call('get_game_state'), mainId = heldMain(initial)
  const helper = await spawn(call, 'commoner')
  await battle(call, [helper.id], helper.id)
  ok(await damage(call, -initial.player.hp.current))
  ok(await call('combat_action', { actorId: helper.id, action: 'stabilize', targetId: 'player' }))
  const stabilized = await call('get_game_state')
  assert.equal(stabilized.player.deathSaves.stable, true)
  ok(await damage(call, -1))
  const damaged = await call('get_game_state')
  assert.equal(damaged.player.deathSaves.failures, 1); assert.equal(damaged.player.deathSaves.stable, false)
  assert.deepEqual(damaged.droppedItems[mainId], stabilized.droppedItems[mainId])
  assert.ok(damaged.player.conditions.includes('prone')); assert.equal(damaged.dmTools.loadout.mainHandId, undefined)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

test('massive damage and genuine death failures record the real death time without repeating the fall', async t => {
  const call = await engine(t), initial = await call('get_game_state'), mainId = heldMain(initial)
  ok(await call('advance_time', { seconds: 7 }))
  ok(await damage(call, -initial.player.hp.current))
  for (let index = 0; index < 3; index++) ok(await damage(call, -1))
  let state = await call('get_game_state')
  assert.equal(state.player.deathSaves.dead, true); assert.equal(state.hero.corpseTimes.player, 7)
  assert.ok(state.player.conditions.includes('unconscious')); assert.ok(state.player.conditions.includes('prone'))
  assert.equal(Object.values(state.droppedItems).filter(drop => drop.item.id === mainId).length, 1)
  ok(await call('replace_game_state', { gameState: state }))
  assert.deepEqual(await call('get_game_state'), state)

  const massive = await engine(t), before = await massive('get_game_state')
  ok(await damage(massive, -999))
  state = await massive('get_game_state')
  assert.equal(state.player.deathSaves.dead, true); assert.equal(state.hero.corpseTimes.player, 0)
  assert.ok(state.player.conditions.includes('prone')); assert.ok(state.droppedItems[heldMain(before)])
})

test('actual death-save failures retain prone and the one dropped instance across the next real round', async t => {
  const call = await engine(t, { dice: '20,1,1,1,19' }), helper=await spawn(call,'commoner'), initial = await call('get_game_state'), mainId = heldMain(initial)
  ok(await damage(call, -initial.player.hp.current))
  ok(await call('enter_combat',{combatants:['player',helper.id]}))
  ok(await call('roll_death_save'))
  let state = await call('get_game_state')
  assert.equal(state.player.deathSaves.failures, 2)
  ok(await call('next_turn', { actorId: 'player' }))
  ok(await call('next_turn', { actorId: helper.id,skipAction:true }))
  ok(await call('roll_death_save'))
  state = await call('get_game_state')
  assert.equal(state.player.deathSaves.dead, true)
  assert.equal(state.hero.corpseTimes.player, 6)
  assert.ok(state.player.conditions.includes('prone'))
  assert.equal(Object.values(state.droppedItems).filter(drop => drop.item.id === mainId).length, 1)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

test('other disabling conditions do not invent an unconscious fall, and monster source weapons do not become loot', async t => {
  const call = await engine(t), initial = await call('get_game_state'), mainId = heldMain(initial)
  for (const condition of ['stunned', 'paralyzed']) ok(await call('apply_condition', { entityId: 'player', condition }))
  let state = await call('get_game_state')
  assert.ok(!state.player.conditions.includes('unconscious')); assert.ok(!state.player.conditions.includes('prone'))
  assert.ok(state.player.inventory.some(item => item.id === mainId)); assert.equal(state.droppedItems[mainId], undefined)
  const target = await spawn(call, 'commoner'), drops = structuredClone(state.droppedItems)
  ok(await call('apply_condition', { entityId: target.id, condition: 'unconscious' }))
  state = await call('get_game_state')
  assert.ok(state.monsters[target.id].conditions.includes('unconscious')); assert.ok(state.monsters[target.id].conditions.includes('prone'))
  assert.deepEqual(state.droppedItems, drops, 'an attack name is not a modeled physical NPC inventory')
})

test('loading a historical unconscious snapshot does not replay a new drop or infer a second physical event', async t => {
  const call = await engine(t, { dice: '17' }), initial = await call('get_game_state')
  const legacy = structuredClone(initial)
  legacy.player.hp.current = 0; legacy.player.conditions = ['unconscious']
  delete legacy.dmTools.loadout
  ok(await call('replace_game_state', { gameState: legacy }))
  const loaded = await call('get_game_state')
  assert.deepEqual(loaded.player.inventory, initial.player.inventory)
  assert.deepEqual(loaded.droppedItems, initial.droppedItems)
  assert.equal(loaded.dmTools.loadout, undefined)
  ok(await call('replace_game_state', { gameState: loaded }))
  assert.deepEqual(await call('get_game_state'), loaded)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 17)
})
