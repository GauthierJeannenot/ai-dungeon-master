const test=require('node:test'),assert=require('node:assert/strict')
Object.assign(process.env,{MONETIZATION_ENABLED:'false',LLM_MODE:'mock',ALLOW_PAID_LLM:'false',RUNPOD_AUTO_MANAGE:'false',APP_LOG_PERSIST_ENABLED:'false',APP_LOG_LEVEL:'error'})
const{installPgMem}=require('./helpers/pg-mem.cjs'),pg=installPgMem()
const{saveSession,loadSession,deleteSession}=require('../lib/session-store.ts')
const{engine,ok,adjacent}=require('./helpers/mcp-toolkit.cjs')
const{setupKnot}=require('./helpers/knot-fixture.cjs')
const{noIdentity}=require('./helpers/spell-perception-fixture.cjs')
test.after(()=>pg.restore())

test('one actually purchased rope keeps its mass/custody and original knot DC across a real observed spell, calendar projection, SQL and a new engine',async t=>{
 const f=await setupKnot(t,{dice:'10,19'}),{call}=f
 ok(await call('prepare_spells',{spellIds:['mage-armor']}))
 let state=await call('get_game_state')
 const fact=ok(await call('record_scene_fact',{description:'The MJ explicitly chooses this exact current calendar anchor and the actual 86400-second display day; no earlier work, rest or elapsed time is rewritten.',cell:state.player.position})).worldFact
 const configuration={eventId:'w23-cross-calendar',decisionFactId:fact.id,actualCalendarAndAnchorConfirmed:true,day86400SecondsExplicitlyAdopted:true,definition:{kind:'custom_fixed',name:'Actual chosen cross-domain calendar',segments:[{segmentId:'month',name:'Chosen month',days:30}]},anchor:{year:1,segmentId:'month',day:1,secondOfDay:0}}
 ok(await call('configure_campaign_calendar',configuration))
 const before=await call('get_game_state'),carriedBefore=ok(await call('inspect_carrying_capacity',{entityId:'player'}))
 assert.equal(carriedBefore.items.filter(i=>i.itemId===f.input.itemId).length,1)
 const tied=ok(await call('tie_knot',f.tie))
 assert.equal(tied.check.ability,'int');assert.equal(tied.dc,tied.check.roll.total)
 state=await call('get_game_state')
 assert.equal(state.worldTimeSeconds,before.worldTimeSeconds+f.tie.cost.seconds)
 assert.equal(state.player.inventory.some(i=>i.id===f.input.itemId),false)
 const carriedTied=ok(await call('inspect_carrying_capacity',{entityId:'player'}))
 assert.equal(carriedTied.knownLoadLb,carriedBefore.knownLoadLb)
 assert.equal(carriedTied.items.filter(i=>i.itemId===f.input.itemId).length,1)
 assert.equal(carriedTied.items.find(i=>i.itemId===f.input.itemId).weightLb,10)
 const originalKnot=structuredClone(state.dmTools.knots.knots[f.tie.knotId]),calendar=structuredClone(state.dmTools.calendar)
 const cell=adjacent(state).find(c=>c.x!==f.cell.x||c.y!==f.cell.y)
 assert.ok(cell,'A second actual free observer cell is required')
 const observer=ok(await call('spawn_monster',{monsterType:'goblin',cell,hpOverride:7}))
 const cast=ok(await call('cast_spell',{spellId:'mage-armor',targetId:'player',focusItemId:'component_pouch',spellObservers:[{observerId:observer.id,channels:['sight']}]}))
 assert.ok(cast.spellPerceptionEventId)
 const view=ok(await call('inspect_spellcasting_perception',{eventId:cast.spellPerceptionEventId,observerId:observer.id}))
 noIdentity(view);assert.equal(view.castingPerceived,true);assert.equal(view.sourceAttributed,true);assert.equal(view.casterId,'player')
 assert.ok(view.perceivedComponents.includes('M'))
 state=await call('get_game_state')
 assert.deepEqual(state.dmTools.knots.knots[f.tie.knotId],originalKnot)
 assert.deepEqual(state.dmTools.calendar,calendar)
 const anchor=state.dmTools.calendar.configuration.at
 const snapshot=structuredClone(state),projection=ok(await call('inspect_campaign_calendar'))
 assert.equal(projection.date.secondOfDay,state.worldTimeSeconds-anchor)
 assert.deepEqual(await call('get_game_state'),snapshot)
 const sessionId=`w23-cross-rope-spell-calendar-${process.pid}`;t.after(()=>deleteSession(sessionId))
 await saveSession(sessionId,{gameState:snapshot,history:[],adventureId:snapshot.adventureId,characterId:snapshot.characterId})
 const loaded=(await loadSession(sessionId)).gameState;assert.deepEqual(loaded,snapshot)
 const resumed=await engine(t,{adventureId:snapshot.adventureId,characterId:snapshot.characterId,dice:'19,17'})
 ok(await resumed('replace_game_state',{gameState:loaded}));assert.deepEqual(await resumed('get_game_state'),snapshot)
 assert.deepEqual(ok(await resumed('inspect_spellcasting_perception',{eventId:cast.spellPerceptionEventId,observerId:observer.id})),view)
 const inspection=await resumed('get_game_state');ok(await resumed('inspect_knots'));ok(await resumed('inspect_campaign_calendar'))
 assert.deepEqual(await resumed('get_game_state'),inspection)
 const attempt=f.attempt('untie','w23-cross-original-rope-return'),untied=ok(await resumed('resolve_knot',attempt))
 assert.equal(untied.success,true);assert.equal(untied.check.ability,'int');assert.equal(untied.dc,tied.dc)
 const after=await resumed('get_game_state')
 assert.equal(after.worldTimeSeconds,snapshot.worldTimeSeconds+attempt.cost.seconds)
 assert.equal(after.player.inventory.filter(i=>i.id===f.input.itemId).length,1)
 assert.deepEqual(after.player.inventory.find(i=>i.id===f.input.itemId),originalKnot.ropeItem)
 assert.equal(ok(await resumed('inspect_carrying_capacity',{entityId:'player'})).knownLoadLb,carriedBefore.knownLoadLb)
 assert.deepEqual(after.dmTools.spellPerception,snapshot.dmTools.spellPerception)
 assert.deepEqual(after.dmTools.calendar,calendar)
 assert.equal(ok(await resumed('resolve_knot',attempt)).replayed,true)
 assert.deepEqual(await resumed('get_game_state'),after)
 assert.equal(ok(await resumed('roll_dice',{notation:'1d20'})).total,17)
})
