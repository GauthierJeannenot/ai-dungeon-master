const test = require('node:test'), assert = require('node:assert/strict')
const { engine, ok, replace, spawn, battle } = require('./helpers/mcp-toolkit.cjs')

const fatigue = (targetId, levels, eventId) => ({ targetId, levels, eventId, reason: 'Épuisement explicitement établi pour cette scène.' })
const revive = (call, targetId) => call('cast_spell', { spellId: 'revivify', targetId, materialItemId: 'revivify_diamonds' })
const kill = (call, targetId) => call('update_hp', { entityId: targetId, delta: -1000, damageType: 'force', damageOrigin: 'spell', reason: 'Coup fatal établi.' })

test('actual Life Drain reduces the unexhausted maximum before halving and a real long rest restores the same additive amount', async t => {
  const call = await engine(t, { dice: '18,5,19,1,17' }), wight = await spawn(call, 'wight')
  const initial = await call('get_game_state'), base = initial.player.hp.max
  ok(await call('add_exhaustion', fatigue('player', 4, 'drain-fatigue')))
  await battle(call, [wight.id], wight.id)
  const attack = ok(await call('resolve_attack', { attackerId: wight.id, targetId: 'player', weaponOrSpell: 'Life Drain' }))
  assert.equal(attack.hit, true); assert.equal(attack.damageDealt, 7)
  const save = attack.riderEffects.find(effect => effect.ability === 'con')
  assert.ok(save); assert.equal(save.success, false); assert.match(save.roll.detail, /DIS:/)
  const drained = await call('get_game_state')
  assert.equal(drained.dmTools.exhaustion.creatures.player.unexhaustedHpMax, base - 7)
  assert.equal(drained.player.hp.max, Math.floor((base - 7) / 2))
  assert.notEqual(drained.player.hp.max, Math.floor(base / 2) - 7)
  const reduction = drained.monsterEffects.find(effect => effect.kind === 'life-drain' && effect.targetId === 'player')
  assert.equal(reduction.hpMaxReduction, 7, 'the recorded restoration amount is additive before exhaustion')
  ok(await call('replace_game_state', { gameState: drained }))
  ok(await call('end_combat', { force: true, reason: 'Le personnage échappe à son adversaire.' }))
  const rest = ok(await call('take_rest', { kind: 'long' })), restored = await call('get_game_state')
  assert.equal(rest.rest, 'long')
  assert.equal(restored.dmTools.exhaustion.creatures.player.level, 4, 'untracked nutrition does not manufacture exhaustion recovery')
  assert.equal(restored.dmTools.exhaustion.creatures.player.unexhaustedHpMax, base)
  assert.equal(restored.player.hp.max, Math.floor(base / 2))
  assert.equal(restored.player.hp.current, restored.player.hp.max)
  assert.ok(!restored.monsterEffects.some(effect => effect.kind === 'life-drain' && effect.targetId === 'player'))
  assert.equal((await call('take_rest', { kind: 'long' })).code, 'LONG_REST_TOO_SOON')
  assert.deepEqual(await call('get_game_state'), restored)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 17)
})

test('actual Revivify restores life before removing exactly one exhaustion level, charges once, and survives hydration without replaying the gift', async t => {
  const call = await engine(t, { characterId: 'cleric', dice: '19' }), ally = await spawn(call, 'knight')
  ok(await call('equip_item', { itemId: 'mace', slot: 'main_hand', operation: 'unequip' }))
  await replace(call, state => { state.monsters[ally.id].hostile = false })
  const base = (await call('get_game_state')).monsters[ally.id].hp.max
  ok(await call('add_exhaustion', fatigue(ally.id, 4, 'revive-fatigue')))
  ok(await kill(call, ally.id))
  const dead = await call('get_game_state')
  assert.equal(dead.monsters[ally.id].isAlive, false)
  assert.equal(dead.monsters[ally.id].hp.max, Math.floor(base / 2))
  assert.ok(dead.player.inventory.some(item => item.id === 'revivify_diamonds'))
  const beforeReceipts = Object.keys(dead.dmTools.exhaustion.receipts)
  const result = ok(await revive(call, ally.id)), raised = await call('get_game_state')
  assert.equal(result.revived, true)
  assert.equal(raised.monsters[ally.id].isAlive, true)
  assert.equal(raised.monsters[ally.id].hp.current, 1)
  assert.equal(raised.monsters[ally.id].hp.max, base)
  assert.equal(raised.dmTools.exhaustion.creatures[ally.id].level, 3)
  assert.equal(raised.dmTools.exhaustion.creatures[ally.id].unexhaustedHpMax, undefined)
  assert.equal(raised.player.spellSlots.level3.current, dead.player.spellSlots.level3.current - 1)
  assert.ok(!raised.player.inventory.some(item => item.id === 'revivify_diamonds'))
  const receiptIds = Object.keys(raised.dmTools.exhaustion.receipts).filter(id => !beforeReceipts.includes(id))
  assert.equal(receiptIds.length, 1)
  const receipt = raised.dmTools.exhaustion.receipts[receiptIds[0]]
  assert.equal(receipt.operation, 'raised_from_dead'); assert.equal(receipt.levels, 1)
  assert.equal(receipt.beforeLevel, 4); assert.equal(receipt.afterLevel, 3)
  assert.equal(receipt.hpBefore.current, 1, 'the exhaustion hook follows a successful resurrection')
  ok(await call('replace_game_state', { gameState: raised }))
  assert.equal((await revive(call, ally.id)).code, 'REVIVIFY_TOO_LATE')
  assert.deepEqual(await call('get_game_state'), raised)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})

test('Revivify refuses an unresolved legacy exhaustion marker before the real diamond, slot or resurrection is committed', async t => {
  const call = await engine(t, { characterId: 'cleric', dice: '19' }), ally = await spawn(call, 'knight')
  ok(await call('equip_item', { itemId: 'mace', slot: 'main_hand', operation: 'unequip' }))
  ok(await kill(call, ally.id))
  await replace(call, state => { state.monsters[ally.id].conditions.push('exhaustion') })
  const before = await call('get_game_state')
  assert.ok(before.player.inventory.some(item => item.id === 'revivify_diamonds'))
  assert.equal((await revive(call, ally.id)).code, 'EXHAUSTION_LEVEL_REQUIRED')
  assert.deepEqual(await call('get_game_state'), before)
  assert.equal(before.monsters[ally.id].isAlive, false)
  assert.equal(ok(await call('roll_dice', { notation: '1d20' })).total, 19)
})
