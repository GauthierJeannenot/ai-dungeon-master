const test = require('node:test')
const assert = require('node:assert/strict')
Object.assign(process.env, { MONETIZATION_ENABLED: 'false', LLM_MODE: 'mock', ALLOW_PAID_LLM: 'false' })
const { installPgMem } = require('./helpers/pg-mem.cjs')
const pg = installPgMem()
const { engine, ok } = require('./helpers/mcp-toolkit.cjs')
const { saveSession, loadSession, deleteSession } = require('../lib/session-store.ts')
const { prepareHerbalismCourse } = require('./helpers/xge-brewing-fixture.cjs')
test.after(() => pg.restore())

test('one real brewing day and a pit-fighting day share the dated budget before a retained wilderness event survives SQL', async t => {
  const { preparePit } = require('./helpers/xge-pit-fighting-fixture.cjs')
  const { prepareHigherPotion } = require('./helpers/xge-higher-brewing-fixture.cjs')
  const { setupWilderness, qualifyWilderness } = require('./helpers/wilderness-chase-fixture.cjs')
  const call = await engine(t, { adventureId: 'sarah-of-yellowcrest-manor', characterId: 'wizard', dice: '20,10,5,1,19' })
  const course = await prepareHerbalismCourse(call, 'w32-cross-herbalism')
  await course.completeInstruction()
  ok(await call('complete_xge_training', course.completion))
  await course.nextDay()
  const site = (await call('get_game_state')).player.position
  ok(await call('create_treasure', { treasureId: 'w32-cross-supply-coins', name: 'Fournitures réellement payées', mode: 'authored',
    description: 'Mille pièces d’or réelles ramassées pour cette préparation, sans crédit ni fourniture gratuite.', cell: site, coins: { gp: 1000 } }))
  ok(await call('collect_treasure', { treasureId: 'w32-cross-supply-coins' }))
  const start = await prepareHigherPotion(call, course.input.practiceToolItemId, {
    eventId: 'w32-cross-superior', potionItemId: 'w32-cross-superior-dose', paid: { gp: 1000 },
    potionType: 'superior',
  })
  ok(await call('start_xge_healing_potion_project', start))
  const effort = { eventId: 'w32-cross-superior-day', projectId: start.eventId,
    activitySource: 'Huit heures réellement consacrées à cette potion, sur cette date, au site initial.' }
  const beforeBrew = await call('get_game_state')
  ok(await call('work_xge_healing_potion_project', effort))
  const afterBrew = await call('get_game_state')
  assert.equal(afterBrew.worldTimeSeconds - beforeBrew.worldTimeSeconds, 28800)
  assert.equal(afterBrew.droppedItems?.[start.potionItemId], undefined)
  const pit = await preparePit(call, { weekId: 'w32-cross-pit-week' })
  ok(await call('start_xge_pit_fighting', pit.input))
  const beforeConflict = await call('get_game_state')
  const conflict = await call('work_xge_pit_fighting', pit.work(0))
  assert.ok(conflict.error, JSON.stringify(conflict))
  assert.equal(conflict.code, 'DOWNTIME_SHARED_DAY_REQUIRED')
  assert.deepEqual(await call('get_game_state'), beforeConflict)
  await course.nextDay()
  const beforePit = await call('get_game_state')
  ok(await call('work_xge_pit_fighting', pit.work(1)))
  const afterPit = await call('get_game_state')
  assert.equal(afterPit.worldTimeSeconds - beforePit.worldTimeSeconds, 28800)
  assert.equal(afterPit.dmTools.xgeBrewing.projects.find(p => p.start.input.eventId === start.eventId).segments.length, 1)
  const reverseConflict = await call('work_xge_healing_potion_project', { ...effort, eventId: 'w32-cross-no-second-day-credit' })
  assert.equal(reverseConflict.code, 'DOWNTIME_SHARED_DAY_REQUIRED', JSON.stringify(reverseConflict))
  assert.deepEqual(await call('get_game_state'), afterPit)
  await course.nextDay()
  const chase = await setupWilderness(t, { call })
  const turnEventId = 'w32-cross-real-wilderness-turn'
  ok(await call('resolve_chase_turn', { eventId: turnEventId, chaseId: chase.input.chaseId }))
  const pending = await call('get_game_state')
  assert.equal(pending.dmTools.chases.episodes[chase.input.chaseId].turns[turnEventId].d20, 5)
  assert.deepEqual(pending.dmTools.xgeBrewing, afterPit.dmTools.xgeBrewing)
  const sessionId = 'w32-three-real-procedures-' + process.pid
  t.after(() => deleteSession(sessionId))
  await saveSession(sessionId, { gameState: pending, history: [], adventureId: pending.adventureId, characterId: pending.characterId })
  const fresh = await engine(t, { adventureId: pending.adventureId, characterId: pending.characterId, dice: '1,19' })
  ok(await fresh('replace_game_state', { gameState: (await loadSession(sessionId)).gameState }))
  const restored = await fresh('get_game_state')
  assert.deepEqual(restored, pending)
  assert.equal(ok(await fresh('work_xge_healing_potion_project', effort)).replayed, true)
  assert.equal(ok(await fresh('work_xge_pit_fighting', pit.work(1))).replayed, true)
  assert.deepEqual(await fresh('get_game_state'), restored)
  await qualifyWilderness({ ...chase, call: fresh }, turnEventId, 5)
  const resolve = { eventId: 'w32-cross-dust-save', chaseId: chase.input.chaseId, turnEventId, choice: 'resolve' }
  ok(await fresh('resolve_chase_complication', resolve))
  const blinded = await fresh('get_game_state')
  assert.ok(blinded.monsters[chase.pursuer.id].conditions.includes('blinded'))
  assert.deepEqual(blinded.dmTools.xgeBrewing, restored.dmTools.xgeBrewing)
  const refused = await fresh('work_xge_healing_potion_project', { ...effort, eventId: 'w32-cross-no-combat-effort' })
  assert.ok(refused.error, JSON.stringify(refused))
  assert.deepEqual(await fresh('get_game_state'), blinded)
  assert.equal(ok(await fresh('roll_dice', { notation: '1d20' })).total, 19)
  await saveSession(sessionId, { gameState: blinded, history: [], adventureId: blinded.adventureId, characterId: blinded.characterId })
  const resumed = await engine(t, { adventureId: blinded.adventureId, characterId: blinded.characterId, dice: '19' })
  ok(await resumed('replace_game_state', { gameState: (await loadSession(sessionId)).gameState }))
  assert.deepEqual(await resumed('get_game_state'), blinded)
  assert.equal(ok(await resumed('resolve_chase_complication', resolve)).replayed, true)
  assert.deepEqual(await resumed('get_game_state'), blinded)
  assert.equal(ok(await resumed('roll_dice', { notation: '1d20' })).total, 19)
})
