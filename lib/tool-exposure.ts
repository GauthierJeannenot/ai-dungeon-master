// Restrict discovery and exposed schemas to the current engine phase/character.
export function selectToolsForPhase<T extends { name: string }>(tools: T[], phase: GamePhase, srdHero=false): T[] {
  const inCombat = phase === 'combat'
  return tools.filter(tool => {
    if(SRD_HERO_TOOLS.has(tool.name)&&!srdHero)return false
    if (COMBAT_ONLY_TOOLS.has(tool.name)) return inCombat
    if (EXPLORATION_ONLY_TOOLS.has(tool.name)) return !inCombat
    return true
  })
}

